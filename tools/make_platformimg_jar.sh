#!/bin/sh
#
# make_platformimg_jar.sh - build tests/fixtures/platformdemo.jar
#
# A MIDlet that feeds the runtime three assets IT HAS NO DECODER FOR:
#
#   pic.bmp   a 32x32 24-bit BMP, left half red, right half blue
#   pic.webp  the same picture as WebP
#   tone.mp3  half a second of MP3
#   tone.amr  half a second of AMR-NB
#
# and prints what it got.  On the desktop build all three are refused, because
# src/gfx has no BMP decoder, no WebP decoder and src/midp has no MP3 decoder.
# On Android all three succeed, because the port hands them to BitmapFactory
# and MediaCodec - which is the whole point of the platform codec hooks, and
# the only way to test them without a phone in the loop.
#
# So the same jar is a positive test on Android and a negative test on the
# desktop, and both answers are expected:
#
#   build/nj2me --port headless --run-frames 20 tests/fixtures/platformdemo.jar
#     -> PLATFORM pic.bmp FAILED ... / pic.webp FAILED ... / tone.mp3 FAILED ...
#        tone.amr decodes here (the runtime has its own AMR decoder)
#   (on the emulator)
#     -> PLATFORM pic.bmp OK 32x32 ff0000 ff / pic.webp OK ... / tone.mp3 OK ...
#        and with --no-amr, tone.amr OK too - the platform decoder answered
set -eu

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${1:-$ROOT/tests/fixtures/platformdemo.jar}"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

mkdir -p "$WORK/src" "$WORK/classes"

# --- the pictures -------------------------------------------------------
python3 - "$WORK" <<'PY'
import sys
from PIL import Image

work = sys.argv[1]
im = Image.new("RGB", (32, 32), (0, 0, 0))
for y in range(32):
    for x in range(32):
        im.putpixel((x, y), (255, 0, 0) if x < 16 else (0, 0, 255))
im.save(work + "/pic.bmp")
im.save(work + "/pic.webp", lossless=True)
PY

# --- the sound ----------------------------------------------------------
# 0.5 s of a 440 Hz sine, mono, as MP3.  Any decoder gives back roughly the
# same number of PCM bytes; the test only asks whether it decoded at all.
ffmpeg -loglevel error -y -f lavfi -i "sine=frequency=440:duration=0.5:sample_rate=22050" \
       -ac 1 -b:a 32k "$WORK/tone.mp3"

# AMR-NB at 8 kHz: the format this runtime decodes itself, which is what makes
# it the test for the CUT half of the story - a build with -DNJ_ENABLE_AMR=0
# has to reach the platform decoder through the same hook MP3 uses.
ffmpeg -loglevel error -y -f lavfi -i "sine=frequency=660:duration=0.5:sample_rate=8000" \
       -ac 1 -ar 8000 -c:a libopencore_amrnb -b:a 12.2k "$WORK/tone.amr"

# --- the assets, inlined as Java byte arrays ----------------------------
# Inlined rather than read from the jar: this runtime has no ldc of a
# CONSTANT_Class, so a MIDlet cannot call getClass().getResourceAsStream() at
# all (it dies with "VerifyError: bad ldc operand").  Inlining also keeps the
# test to exactly the two things it is about: Image.createImage(byte[]) and
# Manager.createPlayer().
python3 - "$WORK" <<'PY'
import sys

work = sys.argv[1]


def emit(name, path):
    data = open(path, "rb").read()
    body = ",".join(str(b if b < 128 else b - 256) for b in data)
    return "    static final byte[] %s = new byte[]{%s};\n" % (name, body)


with open(work + "/src/Assets.java", "w") as f:
    f.write("/* generated by tools/make_platformimg_jar.sh */\n")
    f.write("class Assets {\n")
    f.write(emit("BMP", work + "/pic.bmp"))
    f.write(emit("WEBP", work + "/pic.webp"))
    f.write(emit("MP3", work + "/tone.mp3"))
    f.write(emit("AMR", work + "/tone.amr"))
    f.write("}\n")
PY

# --- the MIDlet ---------------------------------------------------------
cat > "$WORK/src/PlatformDemo.java" <<'JAVA'
import java.io.ByteArrayInputStream;
import javax.microedition.lcdui.Canvas;
import javax.microedition.lcdui.Display;
import javax.microedition.lcdui.Graphics;
import javax.microedition.lcdui.Image;
import javax.microedition.midlet.MIDlet;
import javax.microedition.media.Manager;
import javax.microedition.media.Player;

/*
 * Three assets, three codecs the runtime does not have.  Every line is printed
 * rather than drawn so that a headless run and a device run can be compared
 * with a grep.
 */
public class PlatformDemo extends MIDlet {
    static class Show extends Canvas {
        protected void paint(Graphics g) {
            g.setColor(0x101010);
            g.fillRect(0, 0, getWidth(), getHeight());
            g.setColor(0xFFFFFF);
            g.drawString("platform codecs", getWidth() / 2, 8,
                         Graphics.TOP | Graphics.HCENTER);
        }
    }

    static void image(String name, byte[] data, int[] probe) {
        try {
            Image img = Image.createImage(data, 0, data.length);
            int[] px = new int[img.getWidth() * img.getHeight()];
            img.getRGB(px, 0, img.getWidth(), 0, 0, img.getWidth(), img.getHeight());
            System.out.println("PLATFORM " + name + " OK " + img.getWidth() + "x" +
                               img.getHeight() + " " +
                               Integer.toHexString(px[probe[0]]) + " " +
                               Integer.toHexString(px[probe[1]]));
        } catch (Throwable t) {
            System.out.println("PLATFORM " + name + " FAILED " + t);
        }
    }

    /*
     * Realize, then PLAY: a decoder that returns the right length but never
     * hands a sample to the mixer would pass a duration-only check, so the
     * media time after 400 ms is the part that matters.
     */
    static void sound(String name, byte[] data, String mime) {
        try {
            Player p = Manager.createPlayer(new ByteArrayInputStream(data), mime);
            p.realize();
            long d = p.getDuration();
            p.start();
            try { Thread.sleep(400); } catch (InterruptedException ie) { }
            long t = p.getMediaTime();
            p.close();
            System.out.println("PLATFORM " + name + " OK duration=" + d +
                               " played=" + t);
        } catch (Throwable t) {
            System.out.println("PLATFORM " + name + " FAILED " + t);
        }
    }

    public void startApp() {
        Display.getDisplay(this).setCurrent(new Show());
        image("pic.bmp", Assets.BMP, new int[] { 16 * 32 + 8, 16 * 32 + 24 });
        image("pic.webp", Assets.WEBP, new int[] { 16 * 32 + 8, 16 * 32 + 24 });
        sound("tone.mp3", Assets.MP3, "audio/mpeg");
        sound("tone.amr", Assets.AMR, "audio/amr");
        System.out.println("PLATFORM done");
    }

    public void pauseApp() { }
    public void destroyApp(boolean u) { }
}
JAVA

STUBS="$(python3 "$ROOT/tools/midp_stubs.py" --quiet)"
javac --release 8 -nowarn -classpath "$STUBS" -d "$WORK/classes" \
      "$WORK/src/Assets.java" "$WORK/src/PlatformDemo.java"

mkdir -p "$WORK/classes/META-INF"
printf 'Manifest-Version: 1.0\r\nMIDlet-Name: PlatformDemo\r\nMIDlet-1: PlatformDemo, , PlatformDemo\r\n\r\n' \
    > "$WORK/classes/META-INF/MANIFEST.MF"
mkdir -p "$(dirname "$OUT")"
( cd "$WORK/classes" && jar cfm "$OUT" META-INF/MANIFEST.MF *.class )
echo "wrote $OUT"
