#!/usr/bin/env python3
"""Emit a MIDlet that prints every constant the stubs declare, plus what it
should print.

WHY THIS EXISTS.  A `public static final int` in the stubs is INLINED by javac
at every use site, so the stub's value is what a compiled MIDlet actually
carries - while the runtime compares against its OWN value.  List.IMPLICIT was
1 in the stubs and 3 in the runtime, so every MIDlet asking for an implicit list
got an exclusive one, and nothing anywhere said so.

That is a whole class of bug, not one bug: every constant in tools/midp_stubs.py
is a promise about what the runtime contains.  This generates the fixture and
the expectation FROM THE SAME SOURCE, so the two cannot drift, and the test
compares them against what the runtime actually returns.

Usage: gen_const_fixture.py <out-dir>
"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))


def load_stubs():
    spec = importlib.util.spec_from_file_location(
        "midp_stubs", os.path.join(HERE, "midp_stubs.py"))
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod.CLASSES


def main():
    out = sys.argv[1] if len(sys.argv) > 1 else "."
    classes = load_stubs()
    expected = []
    lines = []

    for path, spec in sorted(classes.items()):
        consts = spec.get("constants") or {}
        if not consts:
            continue
        java = path.replace("/", ".")
        for name, value in sorted(consts.items()):
            # Only ints and Strings; anything else is not inlined the same way
            # and is out of scope for this check.
            if value.startswith("null:"):
                # A typed null in the stubs that the RUNTIME constructs (an Alert
                # DISMISS_COMMAND, say).  Its identity is not a value that can be
                # compared as text, so it is exercised but not asserted on - the
                # type is what the stubs promise and the field read is what
                # proves it exists.
                # READ it - that proves the field exists with the type the
                # stubs promise - but print it under a prefix the test does not
                # compare, because its value is an object the runtime built and
                # there is nothing to compare it against as text.
                lines.append('        px("X %s.%s", String.valueOf(%s.%s));'
                             % (java, name, java, name))
                continue
            if value == "null" or not (value.lstrip("-").isdigit()):
                lines.append('        p("%s.%s", String.valueOf(%s.%s));'
                             % (java, name, java, name))
                expected.append("%s.%s=%s" % (java, name, "null"))
            else:
                lines.append('        p("%s.%s", String.valueOf((int)%s.%s));'
                             % (java, name, java, name))
                expected.append("%s.%s=%s" % (java, name, value.rstrip("L")))

    src = """package consts;

import javax.microedition.midlet.MIDlet;

/*
 * GENERATED by tools/gen_const_fixture.py - do not edit.
 *
 * Prints every constant the MIDP stubs declare, so tests/test_consts.c can
 * compare what the RUNTIME returns against what the STUBS promised.  They must
 * agree: javac inlines the stub's value into every MIDlet that uses it.
 */
public class ConstDemo extends MIDlet {
    private void p(String k, String v) {
        System.out.println("C " + k + "=" + v);
    }

    /* Same read, different prefix: the test asserts that these EXIST but not
     * what they are, since the runtime constructs them. */
    private void px(String k, String v) {
        System.out.println(k + "=" + v);
    }

    public void startApp() {
        try {
%s
        } catch (Throwable t) {
            System.out.println("C threw=" + t);
        }
        notifyDestroyed();
    }

    public void pauseApp() { }
    public void destroyApp(boolean u) { }
}
""" % "\n".join(lines)

    os.makedirs(os.path.join(out, "src", "consts"), exist_ok=True)
    with open(os.path.join(out, "src", "consts", "ConstDemo.java"), "w") as f:
        f.write(src)
    with open(os.path.join(out, "expected.txt"), "w") as f:
        f.write("\n".join(expected) + "\n")
    print("wrote %d constants" % len(expected))


if __name__ == "__main__":
    main()
