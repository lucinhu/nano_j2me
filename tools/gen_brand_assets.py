#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the shared brand assets from the Android launcher icon design.

The Android icon set (tools/gen_android_icon.py) is the single source of
truth for the app identity: a dark navy plate with a white D-pad and two
accent-blue buttons.  This tool reuses that geometry and palette so the
desktop SDL2 window icon, the README logo, and the web favicon/PWA icons all
show exactly the same mark.  Running it twice must produce byte-identical
files (the geometry and resize are deterministic; PNGs carry no timestamps).
"""
from __future__ import annotations

import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "tools"))
import gen_android_icon as icon  # noqa: E402


def square(size):
    return icon.render_square(size)


def maskable(size):
    bg = Image.new("RGBA", (size, size), icon.NAVY_BOTTOM)
    fg = icon.render_foreground(size)
    return Image.alpha_composite(bg, fg).convert("RGB")


def svg():
    """Vector twin of render_square(64): same plate, geometry and colours."""
    size = 64.0
    x0, y0, x1, y1 = icon.motif_bbox()
    k = (icon.MOTIF_SQUARE * size) / (x1 - x0)
    cx = size / 2.0 - (x0 + x1) / 2.0 * k
    cy = size / 2.0 - (y0 + y1) / 2.0 * k

    def px(mx):
        return cx + mx * k

    def py(my):
        return cy + my * k

    r = icon.ARM_HALF * k
    parts = [
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64" '
        'width="64" height="64" role="img" aria-label="nano_j2me">',
        "  <defs>",
        '    <linearGradient id="plate" x1="32" y1="0" x2="32" y2="64" '
        'gradientUnits="userSpaceOnUse">',
        '      <stop offset="0" stop-color="#16203A"/>',
        '      <stop offset="1" stop-color="#0E0E12"/>',
        "    </linearGradient>",
        "  </defs>",
        '  <rect width="64" height="64" rx="14" fill="url(#plate)"/>',
        '  <rect x="%.2f" y="%.2f" width="%.2f" height="%.2f" rx="%.2f" '
        'fill="#F2F4F8"/>'
        % (px(-icon.CROSS_HALF), py(-icon.ARM_HALF),
           px(icon.CROSS_HALF) - px(-icon.CROSS_HALF), 2 * icon.ARM_HALF * k, r),
        '  <rect x="%.2f" y="%.2f" width="%.2f" height="%.2f" rx="%.2f" '
        'fill="#F2F4F8"/>'
        % (px(-icon.ARM_HALF), py(-icon.CROSS_HALF),
           2 * icon.ARM_HALF * k, py(icon.CROSS_HALF) - py(-icon.CROSS_HALF), r),
    ]
    for bx, by in icon.BTNS:
        parts.append('  <circle cx="%.2f" cy="%.2f" r="%.2f" fill="#2F6FED"/>'
                     % (px(bx), py(by), icon.BTN_R * k))
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


def c_header(size=64):
    img = square(size)
    rows = []
    for y in range(size):
        for x in range(size):
            r, g, b = img.getpixel((x, y))
            rows.append("0x%02x,0x%02x,0x%02x,0xff," % (r, g, b))
    lines = [
        "/* Generated by tools/gen_brand_assets.py -- do not edit by hand.",
        " * The Android launcher mark, RGBA8888 rows top-down, for the SDL2",
        " * window icon (SDL_SetWindowIcon). */",
        "#ifndef NJ_ICON_H",
        "#define NJ_ICON_H",
        "",
        "#define NJ_ICON_SIZE %d" % size,
        "",
        "static const unsigned char nj_icon_rgba[NJ_ICON_SIZE * NJ_ICON_SIZE * 4] = {",
    ]
    for i in range(0, len(rows), 8):
        lines.append("    " + " ".join(rows[i:i + 8]))
    lines += ["};", "", "#endif", ""]
    return "\n".join(lines)


def write_png(img, rel):
    path = os.path.join(ROOT, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    img.save(path, "PNG", optimize=True)
    return path


def main():
    written = []
    written.append(write_png(square(512), "docs/images/nano_j2me-icon.png"))
    written.append(write_png(square(256), "data/nj2me.png"))
    written.append(write_png(square(512), "web/assets/icon-512.png"))
    written.append(write_png(square(192), "web/assets/icon-192.png"))
    written.append(write_png(maskable(512), "web/assets/icon-maskable-512.png"))
    svg_path = os.path.join(ROOT, "web/assets/icon.svg")
    with open(svg_path, "w", encoding="utf-8") as f:
        f.write(svg())
    written.append(svg_path)
    header_path = os.path.join(ROOT, "src/port/posix/nj_icon.h")
    with open(header_path, "w", encoding="utf-8") as f:
        f.write(c_header())
    written.append(header_path)
    for p in written:
        print(os.path.relpath(p, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
