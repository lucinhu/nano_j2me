"""Compute MPEG-4 intra escape boundaries from the declared coding events.

For a fixed LAST and RUN, the largest represented magnitude is the level
boundary. For a fixed LAST and magnitude, the largest represented RUN is
the run boundary. This generator computes those set projections directly;
it does not read FFmpeg code or use an implementation's initialization rule.

The input header is regenerated from pinned MIT OxideAV numeric data by
tools/gen_m4v_tables.py. See docs/M4V_TABLE_PROVENANCE.md for source hashes
and attribution. This generator does not audit unrelated decoder algorithms.
"""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
DEFAULT_INPUT = ROOT / 'include/nj2me/nj_m4v_tables.h'
DEFAULT_OUTPUT = ROOT / 'include/nj2me/nj_m4v_escape.h'


def load_events(path):
    source = re.sub(r'/\*.*?\*/', '', path.read_text(), flags=re.S)

    def constant(name):
        match = re.search(r'^#define\s+' + name + r'\s+(\d+)u?\b', source, re.M)
        if not match:
            raise ValueError('missing numeric constant ' + name)
        return int(match[1])

    def array(name):
        match = re.search(r'\b' + name + r'\[[^]]+\]\s*=\s*\{([^}]+)\}', source)
        if not match or not re.fullmatch(r'[\d,\s]+', match[1]):
            raise ValueError('missing decimal event array ' + name)
        return [int(v) for v in re.findall(r'\d+', match[1])]

    count = constant('NJ_M4V_AC_SYMS')
    first_last = constant('NJ_M4V_AC_LAST')
    runs, levels = array('nj_m4v_ac_run'), array('nj_m4v_ac_level')
    if len(runs) != count or len(levels) != count or not 0 < first_last < count:
        raise ValueError('event count or LAST boundary does not match the declared data')
    events = {(int(index >= first_last), run, level)
              for index, (run, level) in enumerate(zip(runs, levels))}
    if len(events) != count or any(run > 63 or not 1 <= level <= 127 for _, run, level in events):
        raise ValueError('duplicate or out-of-range coding event')
    return events


def boundaries(events):
    run_bound = max(run for _, run, _ in events)
    level_bound = max(level for _, _, level in events)
    result = []
    for last in (0, 1):
        level_boundary = [max((level for flag, run, level in events
                              if flag == last and run == coordinate), default=0)
                          for coordinate in range(run_bound + 1)]
        run_boundary = [max((run for flag, run, level in events
                            if flag == last and level == coordinate), default=0)
                        for coordinate in range(level_bound + 1)]
        result.append((level_boundary, run_boundary))
    return run_bound, level_bound, result


def render(events):
    run_bound, level_bound, limits = boundaries(events)
    lines = ['/* SPDX-License-Identifier: MIT',
             ' * Generated by tools/gen_m4v_escape.py from nj_m4v_tables.h events.',
             ' * Input: MIT OxideAV/oxideav-mpeg4video numeric data.',
             ' * Copyright (c) 2026 Karpelès Lab Inc.',
             ' * Retain docs/licenses/third-party-code-MIT.txt; see',
             ' * docs/M4V_TABLE_PROVENANCE.md. Do not edit arrays manually. */',
             '#ifndef NJ_M4V_ESCAPE_H', '#define NJ_M4V_ESCAPE_H', '',
             '#define NJ_M4V_MAX_RUN   %d' % run_bound,
             '#define NJ_M4V_MAX_LEVEL %d' % level_bound, '']
    for last, (levels, runs) in enumerate(limits):
        for name, values in [('level', levels), ('run', runs)]:
            lines.append('static const nj_u1 nj_m4v_max_%s_%d[%d] = {' % (name, last, len(values)))
            lines += ['    ' + ', '.join('%3d' % v for v in values[i:i+12]) + ','
                      for i in range(0, len(values), 12)]
            lines += ['};', '']
    return '\n'.join(lines + ['#endif', ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('input', nargs='?', type=Path, default=DEFAULT_INPUT,
                        help='Project event header (not an external decoder header)')
    parser.add_argument('--output', type=Path, default=DEFAULT_OUTPUT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = render(load_events(args.input))
    if args.check:
        if args.output.read_text() != output:
            raise SystemExit('escape header requires regeneration')
    else:
        args.output.write_text(output)
    print('PASS: escape boundaries computed from coding-event sets' +
          ('; generated file current' if args.check else '; header regenerated'))


if __name__ == '__main__':
    main()
