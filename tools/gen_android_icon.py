#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Generate the Nano J2ME Android launcher icon set.

Design
------
A dark navy plate carrying the app header gradient (#16203A at the top to
#0E0E12 at the bottom) with a white D-pad: two stadium-shaped bars crossed at
the centre give four rounded arms, and two small round buttons sit off its
upper-right corner, the lower one in the app accent blue (#2F6FED).  There is
deliberately no text and no lettering -- glyphs turn to mud at 48x48.

Geometry is authored once in "motif units", where the D-pad spans -1..1 on
both axes, and is then re-scaled per variant:

  legacy square  ic_launcher.png             motif = 66% of the canvas, on a
                                             fully opaque gradient plate (the
                                             composition is centred on its own
                                             bounding box, so a launcher that
                                             crops the icon to a circle still
                                             does not clip the D-pad)
  round          ic_launcher_round.png       motif = 58%, disc mask = the
                                             canvas circle; everything outside
                                             the disc is exactly transparent,
                                             and the smaller motif keeps clear
                                             of the rim
  adaptive fg    ic_launcher_foreground.png  motif = 62% on transparency, which
                                             keeps the art inside the central
                                             66% safe zone that launchers mask
                                             and can zoom the layer

Everything is drawn at 4x the target size and downsampled with LANCZOS, so the
shipped PNGs are never the 4x rendering.  Flat colours and few distinct pixels
keep every file far below the 8 KB budget: the foregrounds carry their
antialiasing in the alpha channel over a flat two-colour RGB field, and the
round icons snap the rim's alpha ramp to 16 steps (see render_foreground and
_trim_alpha for why that is what the size actually goes on).

Sizes
-----
  mipmap-{m,h,xh,xxh,xxxh}dpi/ic_launcher.png             48, 72, 96, 144, 192
  mipmap-{m,h,xh,xxh,xxxh}dpi/ic_launcher_round.png       48, 72, 96, 144, 192
  mipmap-{m,h,xh,xxh,xxxh}dpi/ic_launcher_foreground.png 108, 162, 216, 324, 432

Written alongside them:
  mipmap-anydpi-v26/ic_launcher.xml, mipmap-anydpi-v26/ic_launcher_round.xml
  drawable/ic_launcher_background.xml   (108x108 vector gradient)
  values/colors.xml                     (ic_launcher_background = #16203A,
                                         existing content preserved)

Usage
-----
    tools/gen_android_icon.py [--out src/port/android/res]

The output is deterministic: the same tree is regenerated byte for byte.
"""

from __future__ import annotations

import argparse
import os
import re
import sys
from xml.etree import ElementTree

from PIL import Image, ImageChops, ImageDraw

# --- palette ---------------------------------------------------------------
NAVY_TOP = (0x16, 0x20, 0x3A, 0xFF)
NAVY_BOTTOM = (0x0E, 0x0E, 0x12, 0xFF)
CROSS_COLOR = (0xF2, 0xF4, 0xF8, 0xFF)   # near-white, reads at 48x48
ACCENT_BLUE = (0x2F, 0x6F, 0xED, 0xFF)   # the app accent
CLEAR = (0x00, 0x00, 0x00, 0x00)

SS = 4                     # supersampling factor: draw at 4x, ship at 1x
MOTIF_SQUARE = 0.66        # motif width as a fraction of a legacy square icon
MOTIF_ROUND = 0.58         # ... of a round icon (scaled down, never clipped)
MOTIF_FOREGROUND = 0.62    # ... of an adaptive foreground (safe zone is 66%)
ALPHA_FLOOR = 6            # alpha below this is LANCZOS ringing: drop it
ALPHA_LEVELS = 16          # steps the disc rim's alpha ramp is snapped to

# --- motif geometry, in motif units (D-pad spans -1..1 on both axes) -------
CROSS_HALF = 1.00          # half extent of the D-pad cross
ARM_HALF = 0.36            # half the stroke width of an arm (0.72 wide)
BTN_R = 0.25               # radius of a button
BTNS = ((1.22, -0.88), (1.58, -0.42))   # upper-right pair, y grows downwards

DENSITIES = (("mdpi", 48), ("hdpi", 72), ("xhdpi", 96),
             ("xxhdpi", 144), ("xxxhdpi", 192))
FOREGROUND_DENSITIES = (("mdpi", 108), ("hdpi", 162), ("xhdpi", 216),
                        ("xxhdpi", 324), ("xxxhdpi", 432))

COLOR_NAME = "ic_launcher_background"
COLOR_VALUE = "#16203A"

ADAPTIVE_ICON_XML = """<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@mipmap/ic_launcher_foreground"/>
</adaptive-icon>
"""

BACKGROUND_VECTOR_XML = """<?xml version="1.0" encoding="utf-8"?>
<!-- Adaptive-icon background layer: the app header gradient, #16203A at the
     top to #0E0E12 at the bottom, on the full 108x108 viewport (the launcher
     supplies the mask and the shape). -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    xmlns:aapt="http://schemas.android.com/aapt"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path android:pathData="M0,0h108v108H0z">
        <aapt:attr name="android:fillColor">
            <gradient
                android:type="linear"
                android:startX="54" android:startY="0"
                android:endX="54" android:endY="108">
                <item android:offset="0" android:color="#FF16203A" />
                <item android:offset="1" android:color="#FF0E0E12" />
            </gradient>
        </aapt:attr>
    </path>
</vector>
"""


def motif_bbox():
    """(x0, y0, x1, y1) of the whole motif, buttons included, in motif units."""
    xs = [-CROSS_HALF, CROSS_HALF]
    ys = [-CROSS_HALF, CROSS_HALF]
    for bx, by in BTNS:
        xs += [bx - BTN_R, bx + BTN_R]
        ys += [by - BTN_R, by + BTN_R]
    return min(xs), min(ys), max(xs), max(ys)


def _gradient(size):
    """Vertical navy gradient, `size` x `size`, opaque RGBA."""
    img = Image.new("RGBA", (size, size), NAVY_TOP)
    draw = ImageDraw.Draw(img)
    span = max(size - 1, 1)
    for y in range(size):
        t = y / span
        draw.line(
            [(0, y), (size - 1, y)],
            fill=tuple(round(a + (b - a) * t) for a, b in zip(NAVY_TOP, NAVY_BOTTOM)),
        )
    return img


def _draw_motif(img, content_frac, cross=True, buttons=True):
    """Draw the D-pad and the two buttons, centred on the motif bounding box.

    `cross` / `buttons` select which parts are drawn, so a single-colour layer
    can be rendered on its own (see render_foreground).
    """
    size = img.width
    x0, y0, x1, y1 = motif_bbox()
    k = (content_frac * size) / (x1 - x0)          # motif units -> pixels
    cx, cy = size / 2.0 - (x0 + x1) / 2.0 * k, size / 2.0 - (y0 + y1) / 2.0 * k

    def px(mx):
        return cx + mx * k

    def py(my):
        return cy + my * k

    draw = ImageDraw.Draw(img)
    r = ARM_HALF * k
    # Two stadium bars crossing at the centre: four rounded D-pad arms.
    if cross:
        draw.rounded_rectangle(
            (px(-CROSS_HALF), py(-ARM_HALF), px(CROSS_HALF), py(ARM_HALF)),
            radius=r, fill=CROSS_COLOR)
        draw.rounded_rectangle(
            (px(-ARM_HALF), py(-CROSS_HALF), px(ARM_HALF), py(CROSS_HALF)),
            radius=r, fill=CROSS_COLOR)
    # Two small round buttons off the upper-right corner.
    if buttons:
        for bx, by in BTNS:
            draw.ellipse((px(bx - BTN_R), py(by - BTN_R),
                          px(bx + BTN_R), py(by + BTN_R)), fill=ACCENT_BLUE)


def _downscale(img, size):
    return img.resize((size, size), Image.LANCZOS)


def disc_radius(size):
    """Radius of the round icon's disc, in continuous pixels of the final image.

    Half a pixel inside the canvas edge: the disc is inscribed in the square
    with a hair of clearance, so pixels whose centre lies outside it can be
    left exactly transparent without the rim looking bitten.
    """
    return size / 2.0 - 0.5


def _outside_disc(size, x, y):
    """True when the centre of pixel (x, y) lies outside the round icon disc."""
    radius = disc_radius(size)
    centre = size / 2.0
    dx, dy = x + 0.5 - centre, y + 0.5 - centre
    return dx * dx + dy * dy > radius * radius


def _disc_mask(size):
    """Antialiased filled-circle mask that is exactly 0 outside the disc."""
    big = size * SS
    r = disc_radius(size) * SS
    mask = Image.new("L", (big, big), 0)
    ImageDraw.Draw(mask).ellipse((big / 2.0 - r, big / 2.0 - r,
                                  big / 2.0 + r, big / 2.0 + r), fill=255)
    mask = mask.resize((size, size), Image.LANCZOS)
    # LANCZOS rings a little past the rim; hard-zero everything outside it so
    # "outside the circle is transparent" holds exactly, not approximately.
    px = mask.load()
    for y in range(size):
        for x in range(size):
            if _outside_disc(size, x, y):
                px[x, y] = 0
    return mask


def _floor_alpha(alpha, threshold=ALPHA_FLOOR):
    """Drop LANCZOS's faint fringe: everything below `threshold` becomes clear.

    The ringing tail spreads a couple of destination pixels past every edge;
    left in place it both blurs the silhouette and costs kilobytes, because
    each fringed pixel carries a coverage value that no filter predicts.
    """
    return alpha.point(lambda v: 0 if v < threshold else v)


def _trim_alpha(img, levels=ALPHA_LEVELS):
    """Snap the alpha ramp to `levels` steps and flatten the RGB left clear.

    A LANCZOS rim is a long, finely-graded ramp, and every step of it is a
    fresh pixel value that no PNG filter predicts -- that ramp, not the art, is
    what makes an otherwise flat icon expensive.  Sixteen steps cost at most
    8/255 of opacity anywhere on the rim (invisible), and because the sub-step
    tail now collapses to exactly 0, the pixels outside the disc can share one
    flat clear colour instead of carrying the gradient with them.
    """
    rgba = img.convert("RGBA")
    step = 255.0 / (levels - 1)
    alpha = rgba.getchannel("A").point(
        lambda v: int(round(round(v / step) * step)))
    solid = alpha.point(lambda v: 255 if v else 0)
    rgba = Image.composite(rgba, Image.new("RGBA", rgba.size, CLEAR), solid)
    rgba.putalpha(alpha)
    return rgba


def render_square(size):
    """Opaque legacy icon: gradient plate, motif at 66%, mode RGB."""
    big = _gradient(size * SS)
    _draw_motif(big, MOTIF_SQUARE)
    return _downscale(big, size).convert("RGB")


def render_round(size):
    """Round icon: gradient disc, motif at 58%, transparent outside."""
    big = _gradient(size * SS)
    _draw_motif(big, MOTIF_ROUND)
    img = _downscale(big, size)
    img.putalpha(_disc_mask(size))
    return _trim_alpha(img)


def _flat_layer(size, fill, content_frac, cross, buttons):
    """One motif part as a single flat colour, coverage carried by alpha.

    The transparent field is painted in the same colour as the shape, so the
    LANCZOS downscale leaves the RGB channels perfectly flat and puts the whole
    antialiased ramp in the alpha channel.  Downscaling a white shape against
    transparent black instead would drag the edge RGB towards black, and a
    launcher compositing the layer over the navy background would show it as a
    dark fringe around the D-pad.
    """
    big = Image.new("RGBA", (size * SS, size * SS), fill[:3] + (0,))
    _draw_motif(big, content_frac, cross=cross, buttons=buttons)
    return _downscale(big, size)


def render_foreground(size):
    """Adaptive foreground: transparent, motif at 62%, inside the 66% safe zone.

    The two colours are merged by hand rather than with alpha_composite: the
    RGB a launcher will actually show is a flat white field clipped to the
    D-pad's coverage (a flat blue one for the buttons), while the alpha channel
    keeps the ramp.  Blending the layers pixel by pixel would mix white into
    blue along every edge and put the expensive ramp straight back into the RGB
    for nothing -- RGB is ignored wherever alpha is 0, and wherever alpha is
    not 0 the D-pad is white by definition.  The two shapes never overlap, so
    their coverages simply add up.
    """
    cross = _flat_layer(size, CROSS_COLOR, MOTIF_FOREGROUND, True, False)
    buttons = _flat_layer(size, ACCENT_BLUE, MOTIF_FOREGROUND, False, True)
    alpha_cross = _floor_alpha(cross.getchannel("A"))
    alpha_buttons = _floor_alpha(buttons.getchannel("A"))
    rgb = Image.new("RGB", (size, size), ACCENT_BLUE[:3])
    rgb.paste(CROSS_COLOR[:3], mask=alpha_cross.point(lambda v: 255 if v else 0))
    out = rgb.convert("RGBA")
    out.putalpha(ImageChops.add(alpha_cross, alpha_buttons))
    return out


def _write_png(img, path):
    img.save(path, "PNG", optimize=True)
    return os.path.getsize(path)


def _write_text(path, text):
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return os.path.getsize(path)


def write_colors_xml(res_dir):
    """Add ic_launcher_background to values/colors.xml, keeping what is there."""
    path = os.path.join(res_dir, "values", "colors.xml")
    entry = '    <color name="%s">%s</color>\n' % (COLOR_NAME, COLOR_VALUE)
    if os.path.exists(path):
        with open(path, encoding="utf-8") as fh:
            text = fh.read()
        if re.search(r'name\s*=\s*"%s"' % re.escape(COLOR_NAME), text):
            return path, False
        end = text.rindex("</resources>")
        text = text[:end] + entry + text[end:]
    else:
        text = ('<?xml version="1.0" encoding="utf-8"?>\n<resources>\n'
                + entry + '</resources>\n')
    _write_text(path, text)
    return path, True


def generate(res_dir):
    """Write the whole icon set; returns (pngs, xmls) as [(path, size, mode, bytes)]."""
    pngs, xmls = [], []

    for name, size, render in (
            ("ic_launcher", DENSITIES, render_square),
            ("ic_launcher_round", DENSITIES, render_round),
            ("ic_launcher_foreground", FOREGROUND_DENSITIES, render_foreground)):
        for density, px in size:
            folder = os.path.join(res_dir, "mipmap-" + density)
            os.makedirs(folder, exist_ok=True)
            path = os.path.join(folder, name + ".png")
            img = render(px)
            nbytes = _write_png(img, path)
            pngs.append((path, img.size, img.mode, nbytes))

    anydpi = os.path.join(res_dir, "mipmap-anydpi-v26")
    os.makedirs(anydpi, exist_ok=True)
    for name in ("ic_launcher", "ic_launcher_round"):
        path = os.path.join(anydpi, name + ".xml")
        xmls.append((path, _write_text(path, ADAPTIVE_ICON_XML)))

    drawable = os.path.join(res_dir, "drawable")
    os.makedirs(drawable, exist_ok=True)
    path = os.path.join(drawable, "ic_launcher_background.xml")
    xmls.append((path, _write_text(path, BACKGROUND_VECTOR_XML)))

    colors, changed = write_colors_xml(res_dir)
    xmls.append((colors, os.path.getsize(colors), changed))

    return pngs, xmls


def verify(res_dir, pngs):
    """Check every generated PNG; returns a list of problem strings."""
    problems = []

    def alpha_extrema(img):
        return img.convert("RGBA").getchannel("A").getextrema()

    for path, size, mode, nbytes in pngs:
        img = Image.open(path)
        if img.size != size or img.mode != mode:
            problems.append("%s: reopened as %s %s, expected %s %s"
                            % (path, img.mode, img.size, mode, size))
            continue
        if nbytes > 8192:
            problems.append("%s: %d bytes, over the 8 KB budget" % (path, nbytes))

        if path.endswith("ic_launcher.png"):
            if alpha_extrema(img) != (255, 255):
                problems.append("%s: legacy icon is not fully opaque" % path)
        elif path.endswith("ic_launcher_round.png"):
            rgba = img.convert("RGBA")
            if rgba.getpixel((0, 0))[3] != 0:
                problems.append("%s: corner pixel is not transparent" % path)
            w, h = rgba.size
            alpha = rgba.getchannel("A").load()
            outside = 0
            for y in range(h):
                for x in range(w):
                    if _outside_disc(w, x, y) and alpha[x, y] != 0:
                        outside += 1
            if outside:
                problems.append("%s: %d pixels outside the disc are not clear"
                                % (path, outside))
        else:  # adaptive foreground
            rgba = img.convert("RGBA")
            if rgba.getpixel((0, 0))[3] != 0:
                problems.append("%s: corner pixel is not transparent" % path)
            bbox = rgba.getchannel("A").getbbox()
            if bbox is None:
                problems.append("%s: nothing was drawn" % path)
            else:
                edge = rgba.size[0]
                lo, hi = 0.17 * edge, 0.83 * edge   # central 66% safe zone
                if bbox[0] < lo or bbox[1] < lo or bbox[2] > hi or bbox[3] > hi:
                    problems.append("%s: art escapes the central 66%% safe zone %s"
                                    % (path, bbox))

    for name in ("ic_launcher.xml", "ic_launcher_round.xml"):
        path = os.path.join(res_dir, "mipmap-anydpi-v26", name)
        try:
            ElementTree.parse(path)
        except Exception as exc:  # noqa: BLE001 - report, do not raise
            problems.append("%s: XML does not parse: %s" % (path, exc))
    for path in (os.path.join(res_dir, "drawable", "ic_launcher_background.xml"),
                 os.path.join(res_dir, "values", "colors.xml")):
        try:
            ElementTree.parse(path)
        except Exception as exc:  # noqa: BLE001
            problems.append("%s: XML does not parse: %s" % (path, exc))

    return problems


def report(pngs, xmls):
    total = 0
    for path, size, mode, nbytes in pngs:
        total += nbytes
        print("  %-58s %4dx%-4d %-5s %6d B" % (path, size[0], size[1], mode, nbytes))
    for entry in xmls:
        path, nbytes = entry[0], entry[1]
        print("  %-58s %14s %6d B" % (path, "xml", nbytes))
        total += nbytes
    print("  %-58s %14s %6d B" % ("TOTAL", "", total))


def main(argv=None):
    repo_root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", default="src/port/android/res",
                        help="resource directory to write into "
                             "(default: src/port/android/res)")
    parser.add_argument("--list", action="store_true",
                        help="print the generated files and their sizes only")
    args = parser.parse_args(argv)

    res_dir = args.out
    if not os.path.isabs(res_dir):
        candidate = os.path.abspath(res_dir)
        fallback = os.path.join(repo_root, res_dir)
        if not os.path.isdir(candidate) and os.path.isdir(fallback):
            res_dir = fallback          # run from anywhere inside the repo
        else:
            res_dir = candidate
    if not os.path.isdir(res_dir):
        parser.error("resource directory does not exist: %s" % res_dir)

    pngs, xmls = generate(res_dir)
    print("wrote %d PNGs and %d XML files into %s" % (len(pngs), len(xmls), res_dir))
    report(pngs, xmls)
    if args.list:
        return 0

    problems = verify(res_dir, pngs)
    if problems:
        for problem in problems:
            print("FAIL: " + problem, file=sys.stderr)
        return 1
    print("verify: OK - sizes, modes, opacity, round transparency, "
          "foreground safe zone and XML parsing all check out")
    return 0


if __name__ == "__main__":
    sys.exit(main())
