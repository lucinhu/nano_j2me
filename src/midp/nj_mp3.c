/* scalefactors                                                       */
/* ------------------------------------------------------------------ */

static void mp3_split(int *dst, nj_u4 *sf, int n)
{
    nj_u4 m;

    switch (n) {
    case 3:
        m = (*sf * 171u) >> 9;
        *dst = (int)(*sf - 3u * m);
        *sf = m;
        break;
    case 4:
        *dst = (int)(*sf & 3u);
        *sf >>= 2;
        break;
    case 5:
        m = (*sf * 205u) >> 10;
        *dst = (int)(*sf - 5u * m);
        *sf = m;
        break;
    case 6:
        m = (*sf * 171u) >> 10;
        *dst = (int)(*sf - 6u * m);
        *sf = m;
        break;
    default:
        *dst = 0;
        break;
    }
}

static void mp3_lsf_expand(int slen[4], nj_u4 sf, int n1, int n2, int n3)
{
    mp3_split(&slen[3], &sf, n3);
    mp3_split(&slen[2], &sf, n2);
    mp3_split(&slen[1], &sf, n1);
    slen[0] = (int)sf;
}

static void mp3_read_sf(nj_av_dec *d, mp3_bits *b, const mp3_header *h,
                        int gr, int ch)
{
    mp3_granule *g = &d->gran[ch][gr];
    int i, j = 0, k;

    memset(g->sf, 0, sizeof(g->sf));
    if (!h->lsf) {
        int slen1 = (int)mp3_slen1[g->scalefac_compress & 15u];
        int slen2 = (int)mp3_slen2[g->scalefac_compress & 15u];
        nj_u2 sc = (gr == 1) ? d->scfsi[ch] : 0u;

        if (g->block_type == 2) {
            int n = g->mixed ? 17 : 18;

            for (i = 0; i < n; i++) {
                g->sf[j++] = (nj_u1)bits_get(b, slen1);
            }
            for (i = 0; i < 18; i++) {
                g->sf[j++] = (nj_u1)bits_get(b, slen2);
            }
            for (i = 0; i < 3; i++) {
                g->sf[j++] = 0;
            }
        } else {
            for (k = 0; k < 4; k++) {
                int n = (k == 0) ? 6 : 5;

                if ((sc & (nj_u2)(0x8u >> k)) != 0u) {
                    for (i = 0; i < n; i++) {
                        g->sf[j] = d->gran[ch][0].sf[j];
                        j++;
                    }
                } else {
                    int slen = (k < 2) ? slen1 : slen2;

                    for (i = 0; i < n; i++) {
                        g->sf[j++] = (nj_u1)bits_get(b, slen);
                    }
                }
            }
            g->sf[j++] = 0;
        }
    } else {
        int slen[4];
        int tindex, tindex2, n;
        nj_u4 sf = g->scalefac_compress;

        if ((h->mode_ext & 1) != 0 && ch == 1) {
            sf >>= 1;
            if (sf < 180u) {
                mp3_lsf_expand(slen, sf, 6, 6, 0);
                tindex2 = 3;
            } else if (sf < 244u) {
                mp3_lsf_expand(slen, sf - 180u, 4, 4, 0);
                tindex2 = 4;
            } else {
                mp3_lsf_expand(slen, sf - 244u, 3, 0, 0);
                tindex2 = 5;
            }
        } else {
            if (sf < 400u) {
                mp3_lsf_expand(slen, sf, 5, 4, 4);
                tindex2 = 0;
            } else if (sf < 500u) {
                mp3_lsf_expand(slen, sf - 400u, 5, 4, 0);
                tindex2 = 1;
            } else {
                mp3_lsf_expand(slen, sf - 500u, 3, 0, 0);
                tindex2 = 2;
                g->preflag = 1;
            }
        }
        tindex = (g->block_type == 2) ? (g->mixed ? 2 : 1) : 0;
        for (k = 0; k < 4; k++) {
            n = (int)mp3_lsf_nsf[(tindex2 * 3 + tindex) * 4 + k];
            for (i = 0; i < n; i++) {
                g->sf[j++] = (nj_u1)bits_get(b, slen[k]);
            }
        }
    }
}

/* ------------------------------------------------------------------ */
/* band layout and regions                                            */
/* ------------------------------------------------------------------ */

static void mp3_bands(const mp3_header *h, mp3_granule *g)
{
    int r = h->rate_index;

    if (g->window_switching) {
        if (g->block_type == 2) {
            g->region_size[0] = (r == 8) ? 36 : 18;
        } else if (r <= 2) {
            g->region_size[0] = 18;
        } else if (r == 8) {
            g->region_size[0] = 54;
        } else {
            g->region_size[0] = 27;
        }
        g->region_size[1] = 288;
    } else {
        int r0 = g->region0_count + 1;
        int r1 = g->region0_count + g->region1_count + 2;

        if (r0 > 22) {
            r0 = 22;
        }
        if (r1 > 22) {
            r1 = 22;
        }
        g->region_size[0] = (int)mp3_band_long[r * 23 + r0] / 2;
        g->region_size[1] = (int)mp3_band_long[r * 23 + r1] / 2;
        if (g->region_size[1] < g->region_size[0]) {
            g->region_size[1] = g->region_size[0];
        }
    }
    if (g->block_type == 2) {
        if (g->mixed) {
            g->long_end = (r <= 2) ? 8 : 6;
            g->short_start = 3;
        } else {
            g->long_end = 0;
            g->short_start = 0;
        }
    } else {
        g->long_end = 22;
        g->short_start = 13;
    }
}

/* ------------------------------------------------------------------ */
/* requantisation                                                     */
/* ------------------------------------------------------------------ */

static void mp3_requant(nj_av_dec *d, const mp3_header *h, int gr, int ch)
{
    mp3_granule *g = &d->gran[ch][gr];
    const nj_u2 *bl = &mp3_band_long[h->rate_index * 23];
    const nj_u2 *bs = &mp3_band_short[h->rate_index * 14];
    float *x = d->is[ch];
    int gain = g->global_gain - 210;
    int shift = g->scalefac_scale + 1;
    int l, i, w, k;

    for (l = 0; l < g->long_end; l++) {
        int e = gain - (((int)g->sf[l]
                         + (g->preflag ? (int)mp3_pretab[l] : 0)) << shift);
        float f = mp3_pow2q(e);
        int s = (int)bl[l];
        int t = (int)bl[l + 1];

        for (i = s; i < t; i++) {
            x[i] *= f;
        }
    }
    if (g->short_start < 13) {
        k = g->long_end;
        for (l = g->short_start; l < 13; l++) {
            int len = (int)bs[l + 1] - (int)bs[l];
            int base = 3 * (int)bs[l];

            for (w = 0; w < 3; w++) {
                int e = (gain - (g->subblock_gain[w] << 3))
                      - (((int)g->sf[k++]) << shift);
                float f = mp3_pow2q(e);

                for (i = 0; i < len; i++) {
                    x[base + w * len + i] *= f;
                }
            }
        }
    }
}

/* ------------------------------------------------------------------ */
/* joint stereo                                                       */
/* ------------------------------------------------------------------ */

static void mp3_is_scale(float *lft, float *rgt, int len, int sf, int lsf,
                         const float *tab)
{
    float v1, v2;
    int i;

    if (lsf) {
        v1 = tab[sf];
        v2 = tab[16 + sf];
    } else {
        v1 = tab[sf];
        v2 = tab[6 - sf];
    }
    for (i = 0; i < len; i++) {
        float t = lft[i];

        lft[i] = t * v1;
        rgt[i] = t * v2;
    }
}

static void mp3_ms(float *lft, float *rgt, int len)
{
    int i;

    for (i = 0; i < len; i++) {
        float a = lft[i];
        float b = rgt[i];

        lft[i] = (a + b) * MP3_ISQRT2;
        rgt[i] = (a - b) * MP3_ISQRT2;
    }
}

static void mp3_stereo(nj_av_dec *d, const mp3_header *h, int gr)
{
    mp3_granule *g1 = &d->gran[1][gr];
    float *l = d->is[0];
    float *r = d->is[1];
    int ms = (h->mode_ext >> 1) & 1;
    int isf = h->mode_ext & 1;
    const nj_u2 *bs = &mp3_band_short[h->rate_index * 14];
    const nj_u2 *bl = &mp3_band_long[h->rate_index * 23];
    int j, len, t0, t1, band, w, k;

    if (!ms && !isf) {
        return;
    }
#if !NJ_MP3_ENABLE_INTENSITY
    isf = 0;
#endif
    if (!isf) {
        if (ms) {
            mp3_ms(l, r, 576);
        }
        return;
    }
    {
        int sf_max = h->lsf ? 16 : 7;
        const float *tab = h->lsf ? &mp3_is_lsf[(g1->scalefac_compress & 1u) * 32u]
                                  : mp3_is_m1;
        int nz[3];

        nz[0] = nz[1] = nz[2] = 0;
        t0 = 576;
        t1 = 576;
        k = (13 - g1->short_start) * 3 + g1->long_end - 3;
        for (band = 12; band >= g1->short_start; band--) {
            if (band != 11) {
                k -= 3;
            }
            len = (int)bs[band + 1] - (int)bs[band];
            for (w = 2; w >= 0; w--) {
                int found;

                t0 -= len;
                t1 -= len;
                found = nz[w];
                if (!found) {
                    for (j = 0; j < len; j++) {
                        if (r[t1 + j] != 0.0f) {
                            found = 1;
                            break;
                        }
                    }
                }
                if (!found) {
                    int sf = (int)g1->sf[k + w];

                    if (sf < sf_max) {
                        mp3_is_scale(l + t0, r + t1, len, sf, h->lsf, tab);
                    } else {
                        found = 1;
                    }
                }
                if (found) {
                    nz[w] = 1;
                    if (ms) {
                        mp3_ms(l + t0, r + t1, len);
                    }
                }
            }
        }
        {
            int nz_any = nz[0] | nz[1] | nz[2];

            for (band = g1->long_end - 1; band >= 0; band--) {
                int found;

                len = (int)bl[band + 1] - (int)bl[band];
                t0 -= len;
                t1 -= len;
                found = nz_any;
                if (!found) {
                    for (j = 0; j < len; j++) {
                        if (r[t1 + j] != 0.0f) {
                            found = 1;
                            break;
                        }
                    }
                }
                if (!found) {
                    int sf = (int)g1->sf[(band == 21) ? 20 : band];

                    if (sf < sf_max) {
                        mp3_is_scale(l + t0, r + t1, len, sf, h->lsf, tab);
                    } else {
                        found = 1;
                    }
                }
                if (found) {
                    nz_any = 1;
                    if (ms) {
                        mp3_ms(l + t0, r + t1, len);
                    }
                }
            }
        }
    }
}

/* ------------------------------------------------------------------ */
/* reorder                                                            */
/* ------------------------------------------------------------------ */

static void mp3_reorder(nj_av_dec *d, const mp3_header *h, int gr, int ch)
{
    mp3_granule *g = &d->gran[ch][gr];
    const nj_u2 *bs = &mp3_band_short[h->rate_index * 14];
    float *x = d->is[ch];
    float tmp[3 * 72];
    nj_u4 p;
    int i, j, len;

    if (g->block_type != 2) {
        return;
    }
    p = (nj_u4)bs[g->short_start] * 3u;
    for (i = g->short_start; i < 13; i++) {
        len = (int)bs[i + 1] - (int)bs[i];
        for (j = 0; j < len; j++) {
            tmp[3 * j + 0] = x[p + (nj_u4)j];
            tmp[3 * j + 1] = x[p + (nj_u4)(len + j)];
            tmp[3 * j + 2] = x[p + (nj_u4)(2 * len + j)];
        }
        for (j = 0; j < 3 * len; j++) {
            x[p + (nj_u4)j] = tmp[j];
        }
        p += (nj_u4)(3 * len);
    }
}

/* ------------------------------------------------------------------ */
/* antialias                                                          */
/* ------------------------------------------------------------------ */

static void mp3_antialias(nj_av_dec *d, int gr, int ch)
{
    mp3_granule *g = &d->gran[ch][gr];
    float *x = d->is[ch];
    int n, b, j;

    if (g->block_type == 2) {
        if (!g->mixed) {
            return;
        }
        n = 1;
    } else {
        n = 31;
    }
    for (b = 1; b <= n; b++) {
        float *p = x + 18 * b;

        for (j = 0; j < 8; j++) {
            float t0 = p[-1 - j];
            float t1 = p[j];

            p[-1 - j] = t0 * mp3_aa_c[j] - t1 * mp3_aa_s[j];
            p[j] = t0 * mp3_aa_s[j] + t1 * mp3_aa_c[j];
        }
    }
}

/* ------------------------------------------------------------------ */
/* IMDCT + window + overlap-add                                       */
/* ------------------------------------------------------------------ */

static void mp3_imdct_long(nj_av_dec *d, int gr, int ch, int sb, int win)
{
    float *x = &d->is[ch][sb * 18];
    float *ov = d->ovl[ch][sb];
    const float *w;
    float y[36];
    int i, k;

    for (i = 0; i < 9; i++) {
        float a = 0.0f;
        float b = 0.0f;

        for (k = 0; k < 18; k++) {
            a += mp3_imdct_la[i * 18 + k] * x[k];
            b += mp3_imdct_lb[i * 18 + k] * x[k];
        }
        y[i] = a;
        y[17 - i] = -a;
        y[18 + i] = b;
        y[35 - i] = b;
    }
    w = (win == 1) ? mp3_win_start : ((win == 3) ? mp3_win_stop : mp3_win_norm);
    for (i = 0; i < 36; i++) {
        y[i] *= w[i];
    }
    if ((sb & 1) != 0) {
        for (i = 1; i < 36; i += 2) {
            y[i] = -y[i];
        }
    }
    for (i = 0; i < 18; i++) {
        float o = y[i] + ov[i];

        ov[i] = y[18 + i];
        x[i] = o;
    }
    (void)gr;
}

static void mp3_imdct_short(nj_av_dec *d, int ch, int sb)
{
    float *x = &d->is[ch][sb * 18];
    float *ov = d->ovl[ch][sb];
    float y[36];
    int i, k, j;

    for (i = 0; i < 36; i++) {
        y[i] = 0.0f;
    }
    for (j = 0; j < 3; j++) {
        float a[3], b[3], w[12];

        for (i = 0; i < 3; i++) {
            a[i] = 0.0f;
            b[i] = 0.0f;
            for (k = 0; k < 6; k++) {
                a[i] += mp3_imdct_sa[i * 6 + k] * x[3 * k + j];
                b[i] += mp3_imdct_sb[i * 6 + k] * x[3 * k + j];
            }
        }
        for (i = 0; i < 3; i++) {
            w[i] = a[i];
            w[5 - i] = -a[i];
            w[6 + i] = b[i];
            w[11 - i] = b[i];
        }
        for (i = 0; i < 12; i++) {
            y[6 + 6 * j + i] += w[i] * mp3_win_short[i];
        }
    }
    if ((sb & 1) != 0) {
        for (i = 1; i < 36; i += 2) {
            y[i] = -y[i];
        }
    }
    for (i = 0; i < 18; i++) {
        float o = y[i] + ov[i];

        ov[i] = y[18 + i];
        x[i] = o;
    }
}

/* Hybrid filterbank for one channel/granule: 32 subbands of 18 lines each. */
static void mp3_hybrid(nj_av_dec *d, const mp3_header *h, int gr, int ch)
{
    mp3_granule *g = &d->gran[ch][gr];
    int sb, long_sb = 0;

    if (g->block_type == 2) {
        long_sb = g->mixed ? ((h->rate_index == 8) ? 4 : 2) : 0;
    }
    for (sb = 0; sb < 32; sb++) {
        if (g->block_type != 2 || sb < long_sb) {
            int win = 0;

            if (g->block_type == 1) {
                win = 1;
            } else if (g->block_type == 3) {
                win = 3;
            }
            mp3_imdct_long(d, gr, ch, sb, win);
        } else {
            mp3_imdct_short(d, ch, sb);
        }
    }
}

/* ------------------------------------------------------------------ */
/* polyphase synthesis                                                */
/* ------------------------------------------------------------------ */

static void mp3_synth(nj_av_dec *d, int ch, int ts, nj_s2 *dst, nj_u4 stride)
{
    const float *s = d->is[ch];
    float *v = d->vsyn[ch];
    float out[32];
    nj_u4 head, i, j;
    int k;

    d->vhead[ch] = (d->vhead[ch] - 64u) & 1023u;
    head = d->vhead[ch];

    /* matrixing: 64 values from the 32 subband samples of this time slot */
    for (i = 0; i < 64; i++) {
        const float *nm = &mp3_nmat[i * 16u];
        float acc = 0.0f;
        float sign = ((i & 1u) != 0u) ? -1.0f : 1.0f;

        for (k = 0; k < 16; k++) {
            acc += nm[k] * (s[(nj_u4)k * 18u + (nj_u4)ts]
                            + sign * s[(nj_u4)(31 - k) * 18u + (nj_u4)ts]);
        }
        v[(head + i) & 1023u] = acc;
    }

    /* windowing and 16-tap overlap-sum of the 512-tap bank */
    for (j = 0; j < 32; j++) {
        out[j] = 0.0f;
    }
    for (i = 0; i < 16; i++) {
        nj_u4 base = 128u * (i >> 1) + (((i & 1u) != 0u) ? 96u : 0u);
        const float *dw = &mp3_dwin[i * 32u];

        for (j = 0; j < 32; j++) {
            out[j] += v[(head + base + j) & 1023u] * dw[j];
        }
    }
    for (j = 0; j < 32; j++) {
        float val = out[j] * MP3_PCM_SCALE;
        int iv;

        if (val > 32767.0f) {
            val = 32767.0f;
        } else if (val < -32768.0f) {
            val = -32768.0f;
        }
        iv = (int)(val + ((val >= 0.0f) ? 0.5f : -0.5f));
        dst[j * stride] = (nj_s2)iv;
    }
}

/* ------------------------------------------------------------------ */
/* frame decoding                                                     */
/* ------------------------------------------------------------------ */

static void mp3_read_side_info(nj_av_dec *d, const nj_u1 *si, const mp3_header *h)
{
    mp3_bits b;
    int gr, ch, i;

    bits_init(&b, si, (nj_u4)h->side_bytes * 8u);
    d->main_data_begin = bits_get(&b, h->lsf ? 8 : 9);
    if (!h->lsf) {
        bits_skip(&b, (h->channels == 1) ? 5 : 3);
        for (ch = 0; ch < h->channels; ch++) {
            d->scfsi[ch] = (nj_u2)bits_get(&b, 4);
        }
    } else {
        bits_skip(&b, (h->channels == 1) ? 1 : 2);
        d->scfsi[0] = 0;
        d->scfsi[1] = 0;
    }
    for (gr = 0; gr < h->granules; gr++) {
        for (ch = 0; ch < h->channels; ch++) {
            mp3_granule *g = &d->gran[ch][gr];

            memset(g, 0, sizeof(*g));
            g->part2_3_length = bits_get(&b, 12);
            g->big_values = bits_get(&b, 9);
            g->global_gain = (int)bits_get(&b, 8);
            g->scalefac_compress = bits_get(&b, h->lsf ? 9 : 4);
            g->window_switching = (int)bits_get(&b, 1);
            if (g->window_switching) {
                g->block_type = (int)bits_get(&b, 2);
                g->mixed = (int)bits_get(&b, 1);
                g->table_select[0] = bits_get(&b, 5);
                g->table_select[1] = bits_get(&b, 5);
                for (i = 0; i < 3; i++) {
                    g->subblock_gain[i] = (int)bits_get(&b, 3);
                }
            } else {
                for (i = 0; i < 3; i++) {
                    g->table_select[i] = bits_get(&b, 5);
                }
                g->region0_count = (int)bits_get(&b, 4);
                g->region1_count = (int)bits_get(&b, 3);
            }
            if (!h->lsf) {
                g->preflag = (int)bits_get(&b, 1);
            }
            g->scalefac_scale = (int)bits_get(&b, 1);
            g->count1table_select = (int)bits_get(&b, 1);
            mp3_bands(h, g);
        }
    }
}

/*
 * Decode one complete frame that sits at fifo[fifo_pos].  Returns 0 on
 * success, -1 when there is no valid header (caller resyncs), -2 when the
 * frame is not fully buffered yet and -3 when the frame was skipped.
 */
static int mp3_frame(nj_av_dec *d)
{
    mp3_header h;
    const nj_u1 *p = d->fifo + d->fifo_pos;
    nj_u4 avail = d->fifo_len - d->fifo_pos;
    nj_u4 md_off, md_len, start, nbits;
    mp3_bits b;
    int gr, ch;

    if (!mp3_sync_at(p, avail, &h, 0)) {
        return -1;
    }
    if ((nj_u4)h.frame_bytes > avail) {
        return -2;
    }
    if (h.channels != d->channels || h.rate != d->rate) {
        d->fifo_pos += (nj_u4)h.frame_bytes;
        return -3;
    }

    /* side information, then main data into the reservoir */
    mp3_read_side_info(d, p + 4u + (h.crc ? 2u : 0u), &h);
    md_off = 4u + (h.crc ? 2u : 0u) + (nj_u4)h.side_bytes;
    md_len = (nj_u4)h.frame_bytes - md_off;
    if (md_len > MP3_RES) {
        md_len = MP3_RES;
    }
    if (d->res_len + md_len > MP3_RES) {
        nj_u4 keep = MP3_RES - md_len;
        nj_u4 drop = d->res_len - keep;

        memmove(d->res, d->res + drop, keep);
        d->res_len = keep;
    }
    memcpy(d->res + d->res_len, p + md_off, md_len);
    start = (d->res_len >= d->main_data_begin)
          ? (d->res_len - d->main_data_begin) : 0u;
    d->res_len += md_len;
    nbits = (d->res_len - start) * 8u;
    bits_init(&b, d->res + start, nbits);

    d->pcm_base = d->pcm_base + (nj_s8)d->pcm_frames;
    d->pcm_frames = 0;
    d->pcm_off = 0;
    if (d->pcm_base == 0) {
        d->pcm_base = 0;
    }

    for (gr = 0; gr < h.granules; gr++) {
        for (ch = 0; ch < h.channels; ch++) {
            mp3_granule *g = &d->gran[ch][gr];
            nj_u4 end = b.pos + g->part2_3_length;

            memset(d->is[ch], 0, sizeof(d->is[ch]));
            mp3_read_sf(d, &b, &h, gr, ch);
            if (end > b.nbits) {
                end = b.nbits;
            }
            mp3_huff_data(d, &b, gr, ch, end);
            if (b.pos < end) {
                bits_skip(&b, (int)(end - b.pos));
            }
            mp3_requant(d, &h, gr, ch);
        }
        if (h.channels == 2) {
            mp3_stereo(d, &h, gr);
        }
        for (ch = 0; ch < h.channels; ch++) {
            mp3_reorder(d, &h, gr, ch);
            mp3_antialias(d, gr, ch);
            mp3_hybrid(d, &h, gr, ch);
        }
        {
            int ts;

            for (ts = 0; ts < 18; ts++) {
                for (ch = 0; ch < h.channels; ch++) {
                    nj_u4 off = ((nj_u4)gr * 576u + (nj_u4)ts * 32u)
                              * (nj_u4)h.channels + (nj_u4)ch;

                    mp3_synth(d, ch, ts, &d->pcm[off], (nj_u4)h.channels);
                }
            }
        }
        d->pcm_frames += (nj_u4)h.spf / (nj_u4)h.granules;
    }

    /* keep the tail of the reservoir for the next frame */
    if (d->res_len > MP3_RES_KEEP) {
        nj_u4 drop = d->res_len - MP3_RES_KEEP;

        memmove(d->res, d->res + drop, MP3_RES_KEEP);
        d->res_len = MP3_RES_KEEP;
    }
    d->fifo_pos += (nj_u4)h.frame_bytes;
    return 0;
}

/* Align the FIFO to the next plausible frame header. */
static int mp3_sync_fifo(nj_av_dec *d)
{
    nj_u4 avail = d->fifo_len - d->fifo_pos;
    nj_u4 i;

    if (avail < 4u) {
        return 0;
    }
    if (mp3_sync_at(d->fifo + d->fifo_pos, avail, NULL, 1)) {
        return 1;
    }
    for (i = 1; i + 4u <= avail; i++) {
        if (mp3_sync_at(d->fifo + d->fifo_pos + i, avail - i, NULL, 1)) {
            d->fifo_pos += i;
            return 1;
        }
    }
    if (avail > 3u) {
        d->fifo_pos = d->fifo_len - 3u;
    }
    return 0;
}

/* Append input to the FIFO.  Returns the number of bytes added. */
static nj_u4 mp3_fill(nj_av_dec *d, nj_av_step *s)
{
    nj_u4 space, n;

    if (d->fifo_pos > 0u) {
        if (d->fifo_len > d->fifo_pos) {
            memmove(d->fifo, d->fifo + d->fifo_pos, d->fifo_len - d->fifo_pos);
        }
        d->fifo_len -= d->fifo_pos;
        d->fifo_pos = 0;
    }
    space = MP3_FIFO - d->fifo_len;
    if (space == 0u) {
        return 0;
    }
    if (s != NULL && s->in != NULL && s->in_len > s->in_used) {
        n = s->in_len - s->in_used;
        if (n > space) {
            n = space;
        }
        memcpy(d->fifo + d->fifo_len, s->in + s->in_used, n);
        s->in_used += n;
        d->in_total += n;
        d->fifo_len += n;
        return n;
    }
    /* The caller handed us a chunk and we have consumed it: report back
       instead of stealing bytes from the buffer passed to open().  Only a
       call with no input at all (in_len == 0) may read the retained
       stream, which is how seek() and whole-file decoders get fed. */
    if (s != NULL && s->in_len != 0u) {
        return 0;
    }
    if (!d->src_used) {
        d->src_used = 1;
        d->src_pos = d->first_frame + d->in_total;
        if (d->src_pos > d->data_end) {
            d->src_pos = d->data_end;
        }
    }
    if (d->src_pos >= d->data_end) {
        d->src_done = 1;
        return 0;
    }
    n = d->data_end - d->src_pos;
    if (n > space) {
        n = space;
    }
    memcpy(d->fifo + d->fifo_len, d->src + d->src_pos, n);
    d->src_pos += n;
    d->in_total += n;
    d->fifo_len += n;
    return n;
}

/* Hand PCM out to the caller. */
static int mp3_drain(nj_av_dec *d, nj_av_step *s)
{
    nj_u4 fb = (nj_u4)d->channels * 2u;
    nj_u4 avail = d->pcm_frames - d->pcm_off;
    nj_u4 cap = (s->out != NULL) ? (s->out_cap / fb) : 0u;
    nj_u4 n = (avail < cap) ? avail : cap;
    nj_u4 i;
    const nj_s2 *src;

    s->frames = 0;
    if (n == 0u) {
        s->time_us = -1;
        return NJ_AV_OK;
    }
    s->time_us = (d->pcm_base + (nj_s8)d->pcm_off) * 1000000 / (nj_s8)d->rate;
    src = &d->pcm[d->pcm_off * (nj_u4)d->channels];
    for (i = 0; i < n * (nj_u4)d->channels; i++) {
        nj_s2 v = src[i];

        s->out[2u * i + 0u] = (nj_u1)((nj_u4)v & 0xFFu);
        s->out[2u * i + 1u] = (nj_u1)(((nj_u4)v >> 8) & 0xFFu);
    }
    d->pcm_off += n;
    s->frames = n;
    s->out_used = n * fb;
    return NJ_AV_OK;
}

static int mp3_decode(nj_av_dec *dec, nj_av_step *s)
{
    nj_av_dec *d = dec;
    int guard = 0;

    if (d == NULL || s == NULL) {
        return NJ_AV_ERR_CORRUPT;
    }
    if (s->in_len != 0u && s->in == NULL) {
        return NJ_AV_ERR_CORRUPT;
    }
    s->in_used = 0;
    s->out_used = 0;
    s->frames = 0;
    s->time_us = -1;

    for (;;) {
        if (d->pcm_off < d->pcm_frames) {
            return mp3_drain(d, s);
        }
        if (d->fifo_len > d->fifo_pos) {
            if (mp3_sync_fifo(d)) {
                int r = mp3_frame(d);

                if (r == 0) {
                    continue;
                }
                if (r == -2) {
                    /* the frame is not fully buffered yet */
                } else if (r == -1) {
                    d->fifo_pos += 1u;
                }
                /* r == -3: the frame has already been dropped */
            }
        }
        if (mp3_fill(d, s) == 0u) {
            if (d->src_done || d->src_pos >= d->data_end) {
                return NJ_AV_ERR_END;
            }
            return NJ_AV_ERR_AGAIN;
        }
        if (++guard > 4096) {
            return NJ_AV_ERR_CORRUPT;
        }
    }
}

/* ------------------------------------------------------------------ */
/* open / accepts / seek / close                                      */
/* ------------------------------------------------------------------ */

static int mp3_accepts(const nj_u1 *data, nj_u4 len)
{
    nj_u4 off = 0u, end = len, pos, limit;

    if (data == NULL || len < 4u) {
        return 0;
    }
#if NJ_MP3_ENABLE_ID3
    off = mp3_id3_size(data, len);
    if (len > off + 128u && memcmp(data + len - 128u, "TAG", 3) == 0) {
        end = len - 128u;
    }
#endif
    limit = (end - off > 65536u) ? off + 65536u : end;
    for (pos = off; pos + 4u <= limit; pos++) {
        if (mp3_sync_at(data + pos, end - pos, NULL, 1)) {
            return 1;
        }
    }
    return 0;
}

static nj_av_dec *mp3_open(const nj_u1 *data, nj_u4 len, const nj_av_mem *mem,
                           nj_av_info *info, const char **err)
{
    nj_av_dec *d;
    nj_u4 off = 0u, end = len, pos, first = 0u, frames = 0;
    nj_u4 total = 0;
    mp3_header h;
    int found = 0;

    if (err != NULL) {
        *err = "MP3: unsupported stream";
    }
    if (data == NULL || len < 4u) {
        if (err != NULL) {
            *err = "MP3: stream is too short";
        }
        return NULL;
    }
    if (mem == NULL || mem->alloc == NULL || mem->free == NULL) {
        if (err != NULL) {
            *err = "MP3: no allocator";
        }
        return NULL;
    }
#if NJ_MP3_ENABLE_ID3
    off = mp3_id3_size(data, len);
    if (len > off + 128u && memcmp(data + len - 128u, "TAG", 3) == 0) {
        end = len - 128u;
    }
#endif
    for (pos = off; pos + 4u <= end; pos++) {
        if (mp3_sync_at(data + pos, end - pos, &h, 1)) {
            first = pos;
            found = 1;
            break;
        }
    }
    if (!found) {
        if (err != NULL) {
            *err = "MP3: no Layer III frame found";
        }
        return NULL;
    }
    d = (nj_av_dec *)mem->alloc(mem->ud, (nj_u4)sizeof(*d));
    if (d == NULL) {
        if (err != NULL) {
            *err = "MP3: out of memory";
        }
        return NULL;
    }
    memset(d, 0, sizeof(*d));
    d->mem = *mem;
    d->src = data;
    d->src_len = len;
    d->data_end = end;
    d->first_frame = first;
    d->rate = h.rate;
    d->channels = h.channels;
    d->spf = h.spf;
    d->granules = h.granules;
    d->lsf = h.lsf;
    d->src_pos = first;
    if (d->channels < 1) {
        d->channels = 1;
    }

    /* count frames, resyncing over damaged stretches */
    pos = first;
    while (pos + 4u <= end) {
        mp3_header fh;

        if (!mp3_parse_header(data + pos, end - pos, &fh)
            || (nj_u4)fh.frame_bytes > end - pos) {
            nj_u4 p2;
            int ok = 0;

            for (p2 = pos + 1u; p2 + 4u <= end; p2++) {
                if (mp3_sync_at(data + p2, end - p2, &fh, 1)) {
                    pos = p2;
                    ok = 1;
                    break;
                }
            }
            if (!ok) {
                break;
            }
            continue;
        }
        frames++;
        pos += (nj_u4)fh.frame_bytes;
    }
    d->total_pcm = (nj_s8)frames * (nj_s8)h.spf;
    total = (nj_u4)h.bitrate * 1000u;

    if (info != NULL) {
        info->format = NJ_AV_AUDIO_MP3;
        info->rate = (nj_u4)h.rate;
        info->channels = (nj_u4)h.channels;
        info->frames = (nj_u4)d->total_pcm;
        info->duration_ms = (h.rate > 0)
            ? (nj_u4)(d->total_pcm * 1000 / (nj_s8)h.rate) : 0u;
        info->bitrate = total / 1000u;
    }

#if NJ_MP3_ENABLE_SEEK
    if (frames > 1u) {
        nj_u4 stride = 16u;
        nj_u4 n, i;

        if (frames / stride > 4096u) {
            stride = (frames + 4095u) / 4096u;
        }
        n = frames / stride + 1u;
        d->idx = (mp3_seek_pt *)mem->alloc(mem->ud,
                                          n * (nj_u4)sizeof(mp3_seek_pt));
        if (d->idx != NULL) {
            d->idx_stride = stride;
            d->idx_count = n;
            pos = first;
            for (i = 0; i < n; i++) {
                mp3_header fh;
                nj_u4 skip = stride;

                d->idx[i].byte = pos;
                d->idx[i].pcm = i * stride * (nj_u4)h.spf;
                while (skip-- > 0u && pos + 4u <= end
                       && mp3_parse_header(data + pos, end - pos, &fh)
                       && (nj_u4)fh.frame_bytes <= end - pos) {
                    pos += (nj_u4)fh.frame_bytes;
                }
            }
        }
    }
#endif

    if (err != NULL) {
        *err = NULL;
    }
    return d;
}

#if NJ_MP3_ENABLE_SEEK
static int mp3_seek(nj_av_dec *dec, nj_s8 time_us)
{
    nj_av_dec *d = dec;
    nj_s8 target;
    nj_u4 start_byte = 0u;
    nj_u4 start_pcm = 0u;
    int i;

    if (d == NULL) {
        return NJ_AV_ERR_CORRUPT;
    }
    if (time_us < 0) {
        time_us = 0;
    }
    target = time_us * (nj_s8)d->rate / 1000000;
    if (d->total_pcm > 0 && target > d->total_pcm) {
        target = d->total_pcm;
    }
    d->pcm_frames = 0;
    d->pcm_off = 0;
    d->pcm_base = target;
    d->fifo_pos = 0;
    d->fifo_len = 0;
    d->res_len = 0;
    d->main_data_begin = 0;
    d->vhead[0] = 0;
    d->vhead[1] = 0;
    memset(d->vsyn, 0, sizeof(d->vsyn));
    memset(d->ovl, 0, sizeof(d->ovl));
    d->src_done = 0;

    if (d->idx != NULL && d->idx_count > 0u) {
        for (i = (int)d->idx_count - 1; i >= 0; i--) {
            if ((nj_s8)d->idx[i].pcm <= target) {
                start_byte = d->idx[i].byte;
                start_pcm = d->idx[i].pcm;
                break;
            }
        }
    } else {
        start_byte = d->first_frame;
        start_pcm = 0u;
    }
    d->src_used = 1;
    d->src_pos = start_byte;
    d->in_total = start_byte - d->first_frame;
    d->pcm_base = (nj_s8)start_pcm;
    d->pcm_frames = 0;

    /* decode forward; the overlap state has to be rebuilt */
    while (d->pcm_base + (nj_s8)d->pcm_frames <= target) {
        nj_av_step st;

        /* The source may already be entirely in the FIFO. Decode buffered
         * frames before asking for more input, just as mp3_decode() does. */
        if (mp3_sync_fifo(d)) {
            int r = mp3_frame(d);

            if (r == 0) {
                d->pcm_off = d->pcm_frames;
                continue;
            }
            if (r == -1) {
                d->fifo_pos += 1u;
                continue;
            }
            if (r == -3) continue;
        }
        st.in = NULL;
        st.in_len = 0u;
        st.in_used = 0u;
        st.out = NULL;
        st.out_cap = 0u;
        st.out_used = 0u;
        st.frames = 0u;
        st.time_us = -1;
        if (mp3_fill(d, &st) == 0u) {
            break;
        }
    }
    {
        nj_s8 off = target - d->pcm_base;

        if (off < 0) {
            off = 0;
        }
        if (off > (nj_s8)d->pcm_frames) {
            off = (nj_s8)d->pcm_frames;
        }
        d->pcm_off = (nj_u4)off;
    }
    return NJ_AV_OK;
}
#endif

static void mp3_close(nj_av_dec *dec)
{
    nj_av_mem mem;

    if (dec == NULL) {
        return;
    }
    mem = dec->mem;
#if NJ_MP3_ENABLE_SEEK
    if (dec->idx != NULL && mem.free != NULL) {
        mem.free(mem.ud, dec->idx);
    }
#endif
    if (mem.free != NULL) {
        mem.free(mem.ud, dec);
    }
}

