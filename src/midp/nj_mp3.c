/*
 * nano_j2me - nj_mp3.c
 *
 * MPEG-1/2/2.5 Layer III software decoder, exposed as an nj_avcodec.h audio
 * provider.  All decoder state lives in the handle allocated through the
 * nj_av_mem hooks; the file has no writable globals and no statics (the
 * constant tables below are compile-time rodata).  Only <string.h> is used -
 * even the two transcendental helpers (2^(e/4) and x^(4/3)) are built from
 * integer bit tricks and polynomials, so no libm dependency is introduced.
 *
 * Decode chain per frame:
 *   sync + side info -> scalefactors -> Huffman -> requantisation ->
 *   joint stereo (MS always, intensity stereo optionally) -> reorder ->
 *   antialias -> IMDCT 18/6 + window + overlap-add ->
 *   polyphase synthesis (ISO 512-tap Table B.3 window).
 *
 * Trim macros (include/nj2me/nj_config.h):
 *   NJ_MP3_LAYER3_ONLY       Layer III is the only layer implemented; other
 *                            layers are rejected either way.
 *   NJ_MP3_ENABLE_ID3        skip ID3v2 tags and an ID3v1 trailer; when off the
 *                            decoder simply resyncs from byte 0.
 *   NJ_MP3_ENABLE_SEEK       off => ops.seek is NULL and no seek index is built.
 *   NJ_MP3_ENABLE_INTENSITY  off => intensity stereo is decoded as plain MS.
 */
