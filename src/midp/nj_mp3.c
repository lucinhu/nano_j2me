typedef struct mp3_header {
    int version;        /* 1 = MPEG-1, 2 = MPEG-2, 25 = MPEG-2.5 */
    int lsf;            /* MPEG-2 / 2.5 */
    int rate;           /* sampling rate in Hz */
    int rate_index;     /* 0..8, index into the band-size tables */
    int bitrate;        /* kbit/s */
    int channels;       /* 1 or 2 */
    int mode;           /* 0 stereo, 1 joint, 2 dual, 3 mono */
    int mode_ext;       /* joint stereo extension bits */
    int crc;            /* CRC word present */
    int granules;       /* 1 (LSF) or 2 (MPEG-1) */
    int spf;            /* PCM frames per MPEG frame: 576 or 1152 */
    int side_bytes;     /* side information size */
    int frame_bytes;    /* whole frame, padding included */
} mp3_header;

static const nj_u2 mp3_bitrate_m1[16] = {
    0, 32, 40, 48, 56, 64, 80, 96, 112, 128, 160, 192, 224, 256, 320, 0
};
static const nj_u2 mp3_bitrate_lsf[16] = {
    0, 8, 16, 24, 32, 40, 48, 56, 64, 80, 96, 112, 128, 144, 160, 0
};
static const nj_u2 mp3_rate_tab[3][3] = {
    { 44100, 48000, 32000 },
    { 22050, 24000, 16000 },
    { 11025, 12000, 8000 }
};
static const nj_u1 mp3_rate_idx[3][3] = {
    { 0, 1, 2 },
    { 3, 4, 5 },
    { 6, 7, 8 }
};

static int mp3_parse_header(const nj_u1 *p, nj_u4 len, mp3_header *h)
{
    nj_u4 b1, b2, b3, br, ri, ver, lay, pad;
    int row, bt;

    if (p == NULL || len < 4u) {
        return 0;
    }
    if (p[0] != 0xFFu || (p[1] & 0xE0u) != 0xE0u) {
        return 0;
    }
    b1 = (nj_u4)p[1];
    b2 = (nj_u4)p[2];
    b3 = (nj_u4)p[3];
    ver = (b1 >> 3) & 3u;
    if (ver == 1u) {
        return 0;
    }
    lay = (b1 >> 1) & 3u;
    if (lay != 1u) {                    /* Layer III only */
        return 0;
    }
    br = (b2 >> 4) & 0xFu;
    ri = (b2 >> 2) & 3u;
    if (br == 0u || br == 0xFu || ri == 3u) {   /* free format / invalid */
        return 0;
    }
    pad = (b2 >> 1) & 1u;

    memset(h, 0, sizeof(*h));
    h->version = (ver == 3u) ? 1 : ((ver == 2u) ? 2 : 25);
    h->lsf = (h->version != 1);
    row = h->lsf ? ((h->version == 2) ? 1 : 2) : 0;
    bt = (h->version == 1) ? (int)mp3_bitrate_m1[br] : (int)mp3_bitrate_lsf[br];
    h->bitrate = bt;
    h->rate_index = (int)mp3_rate_idx[row][ri];
    h->rate = mp3_rate_tab[row][ri];
    h->mode = (int)((b3 >> 6) & 3u);
    h->mode_ext = (int)((b3 >> 4) & 3u);
    h->channels = (h->mode == 3) ? 1 : 2;
    h->crc = ((b1 & 1u) == 0u) ? 1 : 0;
    h->granules = h->lsf ? 1 : 2;
    h->spf = h->lsf ? 576 : 1152;
    h->side_bytes = h->lsf ? (h->channels == 2 ? 17 : 9)
                           : (h->channels == 2 ? 32 : 17);
    if (h->version == 1) {
        h->frame_bytes = (int)((144000u * (nj_u4)bt) / (nj_u4)h->rate) + (int)pad;
    } else {
        h->frame_bytes = (int)((72000u * (nj_u4)bt) / (nj_u4)h->rate) + (int)pad;
    }
    if (h->frame_bytes < 4 + (h->crc ? 2 : 0) + h->side_bytes) {
        return 0;
    }
    if ((nj_u4)h->frame_bytes > MP3_MAX_FRAME) {
        return 0;
    }
    return 1;
}

/*
 * Sync check.  In strict mode the header is only accepted when the next frame
 * header (if it is inside the buffer) agrees on version and sampling rate,
 * which makes false syncs inside garbage very unlikely.
 */
static int mp3_sync_at(const nj_u1 *p, nj_u4 len, mp3_header *h, int strict)
{
    mp3_header a, b;

    if (!mp3_parse_header(p, len, &a)) {
        return 0;
    }
    if (strict && (nj_u4)a.frame_bytes + 4u <= len) {
        const nj_u1 *n = p + a.frame_bytes;

        /* An ID3v1 or ID3v2 marker behind a frame means the audio ends here:
         * the frame itself is still the last one of the stream. */
        if (!((n[0] == 'T' && n[1] == 'A' && n[2] == 'G')
              || (n[0] == 'I' && n[1] == 'D' && n[2] == '3'))) {
            if (!mp3_parse_header(n, len - (nj_u4)a.frame_bytes, &b)) {
                return 0;
            }
            if (b.version != a.version || b.rate != a.rate) {
                return 0;
            }
        }
    }
    if (h != NULL) {
        *h = a;
    }
    return 1;
}

