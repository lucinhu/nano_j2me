typedef struct mp3_bits {
    const nj_u1 *buf;
    nj_u4 nbits;
    nj_u4 pos;
    int err;
} mp3_bits;

static void bits_init(mp3_bits *b, const nj_u1 *buf, nj_u4 nbits)
{
    b->buf = buf;
    b->nbits = nbits;
    b->pos = 0;
    b->err = 0;
}

/* Peek up to 24 bits; bits past the end read as 0 and set no error here. */
static nj_u4 bits_peek(const mp3_bits *b, int n)
{
    nj_u4 v, p;

    if (n <= 0) {
        return 0;
    }
    p = b->pos;
    if ((p >> 3) + 4u <= (b->nbits >> 3)) {
        const nj_u1 *q = b->buf + (p >> 3);
        nj_u4 w = ((nj_u4)q[0] << 24) | ((nj_u4)q[1] << 16)
                | ((nj_u4)q[2] << 8) | (nj_u4)q[3];

        w <<= (p & 7u);
        return w >> (32 - n);
    }
    v = 0;
    while (n-- > 0) {
        nj_u4 bit = 0;

        if (p < b->nbits) {
            bit = ((nj_u4)b->buf[p >> 3] >> (7 - (p & 7u))) & 1u;
        }
        v = (v << 1) | bit;
        p++;
    }
    return v;
}

static nj_u4 bits_get(mp3_bits *b, int n)
{
    nj_u4 v;

    if (n <= 0) {
        return 0;
    }
    v = bits_peek(b, n);
    if (b->pos + (nj_u4)n > b->nbits) {
        b->err = 1;
        b->pos = b->nbits;
    } else {
        b->pos += (nj_u4)n;
    }
    return v;
}

static void bits_skip(mp3_bits *b, int n)
{
    if (n <= 0) {
        return;
    }
    if (b->pos + (nj_u4)n > b->nbits) {
        b->err = 1;
        b->pos = b->nbits;
    } else {
        b->pos += (nj_u4)n;
    }
}

