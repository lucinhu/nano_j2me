/* 2^(e/4) */
static float mp3_pow2q(int e)
{
    int k, f, ex;
    union { float f; nj_u4 u; } v;

    k = e >> 2;                 /* arithmetic shift == floor */
    f = e - k * 4;        /* not (k << 2): k may be negative, shifts are UB */
    if (k > 120) {
        return 1.0e30f;
    }
    if (k < -126) {
        return 0.0f;
    }
    ex = (k + 127) << 23;
    v.u = (nj_u4)ex;
    return v.f * mp3_pow2f[f & 3];
}

/* x^(4/3) for 0 <= x <= 8191, relative error below 1.3e-5 */
static float mp3_pow43(nj_u4 x)
{
    union { float f; nj_u4 u; } v;
    nj_u4 u, mant;
    int k, q, r, e4, ex;
    float m, p, s;
    static const float p2r[3] = { 1.0f, 1.25992105f, 1.58740105f };

    if (x == 0u) {
        return 0.0f;
    }
    v.f = (float)x;
    u = v.u;
    k = (int)((u >> 23) & 0xFFu) - 127;
    mant = (u & 0x007FFFFFu) | 0x3F800000u;
    v.u = mant;
    m = v.f;                                    /* mantissa in [1, 2) */
    p = ((((0.00734437f * m - 0.06991111f) * m + 0.38500722f) * m
          + 0.74405416f) * m - 0.06650665f);
    e4 = 4 * k;
    q = e4 / 3;
    if (e4 < 0 && q * 3 != e4) {
        q--;
    }
    r = e4 - 3 * q;                             /* 0, 1 or 2 */
    if (q > 120) {
        s = 1.0e30f;
    } else if (q < -126) {
        s = 0.0f;
    } else {
        ex = (q + 127) << 23;
        v.u = (nj_u4)ex;
        s = v.f;
    }
    return s * p2r[r] * p;
}

