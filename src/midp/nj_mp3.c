static int mp3_huff1(mp3_bits *b, int book, int *x, int *y)
{
    const mp3_huff_book *hb = &mp3_hbook[book];
    const nj_u4 *first = &mp3_huff_first[book * 20];
    const nj_u1 *cnt = &mp3_huff_cnt[book * 20];
    const nj_u2 *base = &mp3_huff_base[book * 20];
    nj_u4 code = 0;
    int len;

    for (len = 1; len <= (int)hb->maxbits; len++) {
        code = (code << 1) | bits_get(b, 1);
        if (b->err) {
            return 0;
        }
        if (code < first[len] + (nj_u4)cnt[len]) {
            nj_u1 sym = mp3_huff_sym[hb->off + (nj_u4)base[len]
                                    + code - first[len]];

            *x = (int)(sym >> 4);
            *y = (int)(sym & 15u);
            return 1;
        }
    }
    return 0;
}

/*
 * Decode the big_values region and the count1 region of one granule.  `end` is
 * the bit position at which part2_3_length says the data stops.
 */
static void mp3_huff_data(nj_av_dec *d, mp3_bits *b, int gr, int ch, nj_u4 end)
{
    mp3_granule *g = &d->gran[ch][gr];
    float *x = d->is[ch];
    int sz[3];
    int i, r, s_index, j, k;

    sz[0] = g->region_size[0];
    sz[1] = g->region_size[1];
    sz[2] = 288;
    j = 0;
    for (i = 0; i < 3; i++) {
        k = sz[i];
        if (k > (int)g->big_values) {
            k = (int)g->big_values;
        }
        sz[i] = k - j;
        if (sz[i] < 0) {
            sz[i] = 0;
        }
        j = k;
    }

    s_index = 0;
    for (r = 0; r < 3; r++) {
        int book = (int)g->table_select[r];
        int n = sz[r];

        if (n <= 0) {
            continue;
        }
        if (mp3_huff_idx[book] == 0xFFu) {
            s_index += 2 * n;
            continue;
        }
        for (; n > 0; n--) {
            int xx, yy;
            int idx = (int)mp3_huff_idx[book];
            int lin = (int)mp3_linbits[book];

            if (b->pos >= end) {
                return;
            }
            if (!mp3_huff1(b, idx, &xx, &yy)) {
                return;
            }
            if (xx == 15 && lin > 0) {
                xx += (int)bits_get(b, lin);
            }
            if (xx != 0) {
                float v = mp3_pow43((nj_u4)xx);

                if (bits_get(b, 1) != 0u) {
                    v = -v;
                }
                x[s_index] = v;
            } else {
                x[s_index] = 0.0f;
            }
            if (yy == 15 && lin > 0) {
                yy += (int)bits_get(b, lin);
            }
            if (yy != 0) {
                float v = mp3_pow43((nj_u4)yy);

                if (bits_get(b, 1) != 0u) {
                    v = -v;
                }
                x[s_index + 1] = v;
            } else {
                x[s_index + 1] = 0.0f;
            }
            s_index += 2;
        }
    }

    /* count1: groups of four +-1/0 values until the bit budget is used up */
    while (s_index <= 572 && b->pos < end) {
        nj_u4 code = bits_peek(b, 6);
        nj_u1 q = mp3_quad_lut[(nj_u4)g->count1table_select * 64u + code];
        int idx;

        if (q == 0u) {
            break;
        }
        bits_skip(b, (int)(q >> 4));
        if (b->err) {
            break;
        }
        idx = (int)(q & 15u);
        for (i = 0; i < 4; i++) {
            if (((idx >> (3 - i)) & 1) != 0) {
                x[s_index + i] = (bits_get(b, 1) != 0u) ? -1.0f : 1.0f;
            } else {
                x[s_index + i] = 0.0f;
            }
        }
        s_index += 4;
    }
    if (b->pos < end) {
        bits_skip(b, (int)(end - b->pos));
    }
}

