/*
 * The field layout is the reference decoder's, and it has to be: the per-mode
 * bit allocation tables in nj_amr_tables.h address fields by their byte
 * offset in this structure, through the NJ_AMR_OFF macros below.  Two bytes
 * per field, four subframes of ten words.  Change the widths and the tables
 * write to the wrong bytes.
 */
typedef struct nj_amr_subframe {
    nj_u2 p_lag;        /* pitch delay index */
    nj_u2 p_gain;       /* pitch gain index */
    nj_u2 fixed_gain;   /* codebook gain index */
    nj_u2 pulses[10];   /* algebraic codebook indices */
} nj_amr_subframe;

typedef struct nj_amr_frame {
    nj_u2 lsf[5];       /* LSF split vector indices */
    nj_amr_subframe subframe[4];
} nj_amr_frame;

