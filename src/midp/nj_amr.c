/* A 10.2 kbit/s index: seven bits in base 5 give three positions, the three
 * low bits are the least significant bit of each. */
static void nj_amr_10bit_pulse(int code, int *pulse_position,
                               int i1, int i2, int i3)
{
    const nj_u1 *positions = nj_amr_base_five_table[code >> 3];

    pulse_position[i1] = (positions[2] << 1) + (code & 1);
    pulse_position[i2] = (positions[1] << 1) + ((code >> 1) & 1);
    pulse_position[i3] = (positions[0] << 1) + ((code >> 2) & 1);
}

/* The eight pulses of the 10.2 kbit/s codebook, 31 bits, four interleaved
 * tracks of two pulses each. */
static void nj_amr_8_pulses_31bits(const nj_u2 *fixed_index,
                                   nj_amr_fixed *fixed_sparse)
{
    int pulse_position[8];
    int i, temp;

    nj_amr_10bit_pulse((int)fixed_index[4], pulse_position, 0, 4, 1);
    nj_amr_10bit_pulse((int)fixed_index[5], pulse_position, 2, 6, 5);

    temp = (((int)fixed_index[6] >> 2) * 25 + 12) >> 5;
    pulse_position[3] = temp % 5;
    pulse_position[7] = temp / 5;
    if (pulse_position[7] & 1)
        pulse_position[3] = 4 - pulse_position[3];
    pulse_position[3] = (pulse_position[3] << 1) + ((int)fixed_index[6] & 1);
    pulse_position[7] = (pulse_position[7] << 1) + (((int)fixed_index[6] >> 1) & 1);

    fixed_sparse->n = 8;
    for (i = 0; i < 4; i++) {
        const int   pos1 = (pulse_position[i] << 2) + i;
        const int   pos2 = (pulse_position[i + 4] << 2) + i;
        const float sign = fixed_index[i] ? -1.0f : 1.0f;

        fixed_sparse->x[i]     = (nj_u1)pos1;
        fixed_sparse->x[i + 4] = (nj_u1)pos2;
        fixed_sparse->y[i]     = sign;
        fixed_sparse->y[i + 4] = pos2 < pos1 ? -sign : sign;
    }
}

/* The 12.2 kbit/s codebook: ten pulses, 35 bits, positions Gray coded. */
static void nj_amr_10_pulses_35bits(const nj_u2 *fixed_index,
                                    nj_amr_fixed *fixed_sparse)
{
    const int mask = (1 << 3) - 1;
    int i;

    fixed_sparse->no_repeat_mask = 0;
    fixed_sparse->n = 10;

    for (i = 0; i < 5; i++) {
        const int   pos1 = nj_amr_gray_decode[fixed_index[2 * i + 1] & mask] + i;
        const int   pos2 = nj_amr_gray_decode[fixed_index[2 * i]     & mask] + i;
        const float sign = (fixed_index[2 * i + 1] & (1 << 3)) ? -1.0f : 1.0f;

        fixed_sparse->x[2 * i + 1] = (nj_u1)pos1;
        fixed_sparse->x[2 * i]     = (nj_u1)pos2;
        fixed_sparse->y[2 * i + 1] = sign;
        fixed_sparse->y[2 * i]     = pos2 < pos1 ? -sign : sign;
    }
}

/*
 * Turn the codebook indices into pulse positions and signs.  The number of
 * pulses, their tracks and their signs all depend on the mode, and so does
 * how many bits each index has - the bit allocation table is what says.
 */
static void nj_amr_decode_fixed_sparse(nj_amr_fixed *fixed_sparse,
                                       const nj_u2 *pulses, int mode,
                                       int subframe)
{
    if (mode == NJ_AMR_MODE_12K2) {
        nj_amr_10_pulses_35bits(pulses, fixed_sparse);
        return;
    }

    if (mode == NJ_AMR_MODE_10K2) {
        nj_amr_8_pulses_31bits(pulses, fixed_sparse);
        return;
    }

    {
        const int fixed_index = (int)pulses[0];
        int       pulse_position[4];
        int       i, pulse_subset;

        if (mode <= NJ_AMR_MODE_5K15) {
            /* two pulses, five tracks: two per subframe pair */
            pulse_subset      = ((fixed_index >> 3) & 8) + (subframe << 1);
            pulse_position[0] = (fixed_index & 7) * 5 +
                                nj_amr_track_position[pulse_subset];
            pulse_position[1] = ((fixed_index >> 3) & 7) * 5 +
                                nj_amr_track_position[pulse_subset + 1];
            fixed_sparse->n = 2;
        } else if (mode == NJ_AMR_MODE_5K9) {
            pulse_subset      = ((fixed_index & 1) << 1) + 1;
            pulse_position[0] = ((fixed_index >> 1) & 7) * 5 + pulse_subset;
            pulse_subset      = (fixed_index >> 4) & 3;
            pulse_position[1] = ((fixed_index >> 6) & 7) * 5 + pulse_subset +
                                (pulse_subset == 3 ? 1 : 0);
            fixed_sparse->n = pulse_position[0] == pulse_position[1] ? 1 : 2;
        } else if (mode == NJ_AMR_MODE_6K7) {
            pulse_position[0] = (fixed_index & 7) * 5;
            pulse_subset      = (fixed_index >> 2) & 2;
            pulse_position[1] = ((fixed_index >> 4) & 7) * 5 + pulse_subset + 1;
            pulse_subset      = (fixed_index >> 6) & 2;
            pulse_position[2] = ((fixed_index >> 8) & 7) * 5 + pulse_subset + 2;
            fixed_sparse->n = 3;
        } else {
            /* 7.4 and 7.95 kbit/s: four pulses on four tracks */
            pulse_position[0] = nj_amr_gray_decode[fixed_index & 7];
            pulse_position[1] = nj_amr_gray_decode[(fixed_index >> 3) & 7] + 1;
            pulse_position[2] = nj_amr_gray_decode[(fixed_index >> 6) & 7] + 2;
            pulse_subset      = (fixed_index >> 9) & 1;
            pulse_position[3] = nj_amr_gray_decode[(fixed_index >> 10) & 7] +
                                pulse_subset + 3;
            fixed_sparse->n = 4;
        }

        for (i = 0; i < fixed_sparse->n; i++) {
            fixed_sparse->x[i] = (nj_u1)pulse_position[i];
            fixed_sparse->y[i] = (pulses[1] >> i) & 1 ? 1.0f : -1.0f;
        }
    }
}

/* The sparse vector as a signal: each pulse, then the same pulse a pitch lag
 * further on, attenuated by the sharpening factor, until the subframe ends. */
static void nj_amr_set_fixed_vector(float *out, const nj_amr_fixed *in,
                                    float scale, int size)
{
    int i;

    for (i = 0; i < in->n; i++) {
        int   x       = in->x[i];
        int   repeats = !((in->no_repeat_mask >> i) & 1);
        float y       = in->y[i] * scale;

        if (in->pitch_lag > 0) {
            do {
                out[x] += y;
                y *= in->pitch_fac;
                x += in->pitch_lag;
            } while (x < size && repeats);
        }
    }
}

/* Take the pulses back out again, so the vector is all zeros for the next
 * subframe.  The same walk; the signal itself is never cleared. */
static void nj_amr_clear_fixed_vector(float *out, const nj_amr_fixed *in,
                                      int size)
{
    int i;

    for (i = 0; i < in->n; i++) {
        int x       = in->x[i];
        int repeats = !((in->no_repeat_mask >> i) & 1);

        if (in->pitch_lag > 0) {
            do {
                out[x] = 0.0f;
                x += in->pitch_lag;
            } while (x < size && repeats);
        }
    }
}

/* Pitch sharpening: the fixed vector is repeated at the pitch lag with a
 * factor that follows the pitch gain. */
static void nj_amr_pitch_sharpening(nj_amr_state *p, int subframe,
                                    nj_amr_fixed *fixed_sparse)
{
    /* The standard suggests the current pitch gain always, but outside the
     * 12.2 kbit/s mode the pitch and codebook gains are quantised together,
     * so the codebook gain cannot depend on a pitch gain not yet decoded. */
    if (p->mode == NJ_AMR_MODE_12K2) {
        p->beta = p->pitch_gain[4] < 1.0f ? p->pitch_gain[4] : 1.0f;
    }

    fixed_sparse->pitch_lag = p->pitch_lag_int;
    fixed_sparse->pitch_fac = p->beta;

    /* 4.75 kbit/s quantises the gains of two subframes together, so its
     * sharpening factor is only updated on the second and fourth. */
    if (p->mode != NJ_AMR_MODE_4K75 || (subframe & 1)) {
        p->beta = p->pitch_gain[4] < 0.0f ? 0.0f :
                 (p->pitch_gain[4] > NJ_AMR_SHARP_MAX ? NJ_AMR_SHARP_MAX
                                                      : p->pitch_gain[4]);
    }
}

/* ------------------------------------------------------------------ */
/* Gains                                                               */
/* ------------------------------------------------------------------ */

/*
 * The codebook gain: the quantised correction factor times the predicted
 * energy, in dB, less the energy of the vector it will scale - which is why
 * the vector has to exist before the gain does.  The prediction error history
 * rolls on regardless.
 */
static float nj_amr_set_fixed_gain(float fixed_gain_factor,
                                   float fixed_mean_energy,
                                   float *prediction_error,
                                   float energy_mean,
                                   const float *pred_table)
{
    float val = fixed_gain_factor *
        (float)nj_amr_exp10(0.05 * ((double)nj_amr_dot(pred_table,
                                                       prediction_error, 4) +
                                    (double)energy_mean)) /
        (float)nj_amr_sqrt(fixed_mean_energy != 0.0f
                           ? (double)fixed_mean_energy : 1.0);

    prediction_error[0] = prediction_error[1];
    prediction_error[1] = prediction_error[2];
    prediction_error[2] = prediction_error[3];
    prediction_error[3] = 20.0f * (float)nj_amr_log10((double)fixed_gain_factor);

    return val;
}

static void nj_amr_decode_gains(nj_amr_state *p,
                                const nj_amr_subframe *subframe,
                                int subframe_no, float *fixed_gain_factor)
{
    if (p->mode == NJ_AMR_MODE_12K2 || p->mode == NJ_AMR_MODE_7K95) {
        p->pitch_gain[4]   = nj_amr_qua_gain_pit[subframe->p_gain] *
                             (1.0f / 16384.0f);
        *fixed_gain_factor = nj_amr_qua_gain_code[subframe->fixed_gain] *
                             (1.0f / 2048.0f);
    } else {
        const nj_u2 *gains;

        if (p->mode >= NJ_AMR_MODE_6K7) {
            gains = nj_amr_gains_high[subframe->p_gain];
        } else if (p->mode >= NJ_AMR_MODE_5K15) {
            gains = nj_amr_gains_low[subframe->p_gain];
        } else {
            /* 4.75 kbit/s codes one gain index for two subframes */
            gains = nj_amr_gains_4k75[(p->frame.subframe[subframe_no & 2].p_gain
                                       << 1) + (subframe_no & 1)];
        }

        p->pitch_gain[4]   = gains[0] * (1.0f / 16384.0f);
        *fixed_gain_factor = gains[1] * (1.0f / 4096.0f);
    }
}

/*
 * Fixed gain smoothing: while the spectrum is moving, the codebook gain is
 * pulled towards its recent average so that the gain does not step audibly
 * between subframes.
 *
 * `diff` is measured from the averaged LSFs of the previous frame against
 * this subframe's, which is what the two counters are for: ten subframes of
 * movement start a forty subframe window in which smoothing is disabled.
 */
static float nj_amr_fixed_gain_smooth(nj_amr_state *p, const float *lsf,
                                      const float *lsf_avg)
{
    float diff = 0.0f;
    int   i;

    for (i = 0; i < NJ_AMR_LPC_ORDER; i++) {
        float d = (lsf_avg[i] - lsf[i]) / lsf_avg[i];
        diff += d < 0.0f ? -d : d;
    }

    p->diff_count++;
    if (diff <= 0.65f)
        p->diff_count = 0;

    if (p->diff_count > 10) {
        p->hang_count = 0;
        p->diff_count--;    /* do not let the counter run away */
    }

    if (p->hang_count < 40) {
        p->hang_count++;
    } else if (p->mode < NJ_AMR_MODE_7K4 || p->mode == NJ_AMR_MODE_10K2) {
        float smoothing_factor = 4.0f * diff - 1.6f;

        if (smoothing_factor < 0.0f) smoothing_factor = 0.0f;
        if (smoothing_factor > 1.0f) smoothing_factor = 1.0f;

        {
            float mean = (p->fixed_gain[0] + p->fixed_gain[1] +
                          p->fixed_gain[2] + p->fixed_gain[3] +
                          p->fixed_gain[4]) * 0.2f;
            return smoothing_factor * p->fixed_gain[4] +
                   (1.0f - smoothing_factor) * mean;
        }
    }

    return p->fixed_gain[4];
}

/* ------------------------------------------------------------------ */
/* Adaptive phase dispersion                                           */
/* ------------------------------------------------------------------ */

/*
 * Circularly convolve the sparse fixed vector with a phase dispersion filter:
 * out[n] = sum over pulses of the filter, placed at the pulse and wrapped
 * around the subframe.  With a pitch lag shorter than the subframe the filter
 * is extended by its own lagged copies first, so a repeated pulse is filtered
 * as a repetition rather than as a fresh onset.
 */
static void nj_amr_apply_ir_filter(float *out, const nj_amr_fixed *in,
                                   const float *filter)
{
    float filter1[NJ_AMR_SUBFRAME];
    float filter2[NJ_AMR_SUBFRAME];
    int   lag  = in->pitch_lag;
    float fac  = in->pitch_fac;
    int   i;

    if (lag < NJ_AMR_SUBFRAME) {
        nj_amr_circ_add(filter1, filter, filter, lag, fac, NJ_AMR_SUBFRAME);

        if (lag < NJ_AMR_SUBFRAME / 2)
            nj_amr_circ_add(filter2, filter, filter1, lag, fac, NJ_AMR_SUBFRAME);
    }

    memset(out, 0, NJ_AMR_SUBFRAME * sizeof(float));

    for (i = 0; i < in->n; i++) {
        int          x = in->x[i];
        float        y = in->y[i];
        const float *filterp;

        if (x >= NJ_AMR_SUBFRAME - lag)
            filterp = filter;
        else if (x >= NJ_AMR_SUBFRAME - (lag << 1))
            filterp = filter1;
        else
            filterp = filter2;

        nj_amr_circ_add(out, out, filterp, x, y, NJ_AMR_SUBFRAME);
    }
}

/*
 * Choose how much to smooth the fixed vector, and do it.  A subframe of
 * voiced speech wants its pulses spread; a subframe of silence does not, and
 * a sudden onset must not be smeared at all.
 */
static const float *nj_amr_anti_sparseness(nj_amr_state *p,
                                           nj_amr_fixed *fixed_sparse,
                                           const float *fixed_vector,
                                           float fixed_gain, float *out)
{
    int ir_filter_nr;

    if (p->pitch_gain[4] < 0.6f)
        ir_filter_nr = 0;       /* strong filtering */
    else if (p->pitch_gain[4] < 0.9f)
        ir_filter_nr = 1;       /* medium filtering */
    else
        ir_filter_nr = 2;       /* none */

    /* An onset holds the filtering off for two subframes. */
    if (fixed_gain > 2.0f * p->prev_sparse_fixed_gain)
        p->ir_filter_onset = 2;
    else if (p->ir_filter_onset)
        p->ir_filter_onset--;

    if (!p->ir_filter_onset) {
        int i, count = 0;

        for (i = 0; i < 5; i++)
            if (p->pitch_gain[i] < 0.6f)
                count++;
        if (count > 2)
            ir_filter_nr = 0;

        if (ir_filter_nr > p->prev_ir_filter_nr + 1)
            ir_filter_nr--;
    } else if (ir_filter_nr < 2) {
        ir_filter_nr++;
    }

    /* Very quiet subframes are left alone: the reference source does this and
     * the technical description does not mention it, but without it the
     * filter rings on in the silence. */
    if (fixed_gain < 5.0f)
        ir_filter_nr = 2;

    if (p->mode != NJ_AMR_MODE_7K4 && p->mode < NJ_AMR_MODE_10K2 &&
        ir_filter_nr < 2) {
        nj_amr_apply_ir_filter(out, fixed_sparse,
                               (p->mode == NJ_AMR_MODE_7K95
                                ? nj_amr_ir_lookup_7k95
                                : nj_amr_ir_lookup)[ir_filter_nr]);
        fixed_vector = out;
    }

    p->prev_ir_filter_nr      = ir_filter_nr;
    p->prev_sparse_fixed_gain = fixed_gain;

    return fixed_vector;
}

/* ------------------------------------------------------------------ */
/* Synthesis and postfilter                                            */
/* ------------------------------------------------------------------ */

/*
 * One subframe of speech: the excitation is the pitch and codebook
 * contributions summed, with the pitch contribution emphasised when the pitch
 * gain is high, and the short term filter turns it into samples.  Returns
 * whether the result overflowed 16 bits, in which case the caller runs it
 * again with the pitch vector scaled down.
 */
static int nj_amr_synthesis(nj_amr_state *p, float *lpc, float fixed_gain,
                            const float *fixed_vector, float *samples,
                            int overflow)
{
    float excitation[NJ_AMR_SUBFRAME];
    int   i;

    if (overflow)
        for (i = 0; i < NJ_AMR_SUBFRAME; i++)
            p->pitch_vector[i] *= 0.25f;

    nj_amr_weighted_sum(excitation, p->pitch_vector, fixed_vector,
                        p->pitch_gain[4], fixed_gain, NJ_AMR_SUBFRAME);

    if (p->pitch_gain[4] > 0.5f && !overflow) {
        float energy = nj_amr_dot(excitation, excitation, NJ_AMR_SUBFRAME);
        float pitch_factor = p->pitch_gain[4] *
            (p->mode == NJ_AMR_MODE_12K2
             ? 0.25f * (p->pitch_gain[4] < 1.0f ? p->pitch_gain[4] : 1.0f)
             : 0.5f * (p->pitch_gain[4] < NJ_AMR_SHARP_MAX
                       ? p->pitch_gain[4] : NJ_AMR_SHARP_MAX));

        for (i = 0; i < NJ_AMR_SUBFRAME; i++)
            excitation[i] += pitch_factor * p->pitch_vector[i];

        nj_amr_scale_to_sum_of_squares(excitation, excitation, energy,
                                       NJ_AMR_SUBFRAME);
    }

    nj_amr_lp_synthesis(samples, lpc, excitation, NJ_AMR_SUBFRAME,
                        NJ_AMR_LPC_ORDER);

    for (i = 0; i < NJ_AMR_SUBFRAME; i++)
        if (samples[i] > NJ_AMR_SAMPLE_BOUND ||
            samples[i] < -NJ_AMR_SAMPLE_BOUND)
            return 1;

    return 0;
}

/* End of subframe: the histories shift by one subframe, the fourth LSP set
 * becomes the previous frame's. */
static void nj_amr_update_state(nj_amr_state *p)
{
    int i;

    for (i = 0; i < NJ_AMR_LPC_ORDER; i++)
        p->prev_lsp_sub4[i] = p->lsp[3][i];

    memmove(&p->excitation_buf[0], &p->excitation_buf[NJ_AMR_SUBFRAME],
            (nj_size)(NJ_AMR_PITCH_DELAY_MAX + NJ_AMR_LPC_ORDER + 1) *
            sizeof(float));

    for (i = 0; i < 4; i++) {
        p->pitch_gain[i] = p->pitch_gain[i + 1];
        p->fixed_gain[i] = p->fixed_gain[i + 1];
    }

    memmove(&p->samples_in[0], &p->samples_in[NJ_AMR_SUBFRAME],
            (nj_size)NJ_AMR_LPC_ORDER * sizeof(float));
}

/* The tilt of a filter, from the first two autocorrelations of its impulse
 * response. */
static float nj_amr_tilt_factor(const float *lpc_n, const float *lpc_d)
{
    float impulse[NJ_AMR_LPC_ORDER + NJ_AMR_TILT_RESPONSE];
    float *hf = impulse + NJ_AMR_LPC_ORDER;
    float rh0, rh1;

    memset(impulse, 0, sizeof(impulse));

    hf[0] = 1.0f;
    memcpy(hf + 1, lpc_n, NJ_AMR_LPC_ORDER * sizeof(float));

    nj_amr_lp_synthesis(hf, lpc_d, hf, NJ_AMR_TILT_RESPONSE, NJ_AMR_LPC_ORDER);

    rh0 = nj_amr_dot(hf, hf, NJ_AMR_TILT_RESPONSE);
    rh1 = nj_amr_dot(hf, hf + 1, NJ_AMR_TILT_RESPONSE - 1);

    /* The standard only asks for the check in the two highest modes, but the
     * reference treats a negative tilt as no tilt everywhere. */
    return rh1 >= 0.0f ? rh1 / rh0 * NJ_AMR_TILT_GAMMA_T : 0.0f;
}

/*
 * The formant postfilter: the synthesis filter's poles and zeros pulled in
 * by two different factors, which widens the formants and makes the speech
 * sound less synthetic, then tilt compensation and gain control to put back
 * the energy the filter moved.
 */
static void nj_amr_postfilter(nj_amr_state *p, float *lpc, float *buf_out)
{
    float       *samples = p->samples_in + NJ_AMR_LPC_ORDER;
    float        speech_gain = nj_amr_dot(samples, samples, NJ_AMR_SUBFRAME);
    float        pole_out[NJ_AMR_SUBFRAME + NJ_AMR_LPC_ORDER];
    const float *gamma_n;
    const float *gamma_d;
    float        lpc_n[NJ_AMR_LPC_ORDER];
    float        lpc_d[NJ_AMR_LPC_ORDER];
    int          i;

    if (p->mode == NJ_AMR_MODE_12K2 || p->mode == NJ_AMR_MODE_10K2) {
        gamma_n = nj_amr_pow_0_7;
        gamma_d = nj_amr_pow_0_75;
    } else {
        gamma_n = nj_amr_pow_0_55;
        gamma_d = nj_amr_pow_0_7;
    }

    for (i = 0; i < NJ_AMR_LPC_ORDER; i++) {
        lpc_n[i] = lpc[i] * gamma_n[i];
        lpc_d[i] = lpc[i] * gamma_d[i];
    }

    memcpy(pole_out, p->postfilter_mem, NJ_AMR_LPC_ORDER * sizeof(float));
    nj_amr_lp_synthesis(pole_out + NJ_AMR_LPC_ORDER, lpc_d, samples,
                        NJ_AMR_SUBFRAME, NJ_AMR_LPC_ORDER);
    memcpy(p->postfilter_mem, pole_out + NJ_AMR_SUBFRAME,
           NJ_AMR_LPC_ORDER * sizeof(float));

    nj_amr_lp_zero_synthesis(buf_out, lpc_n,
                             pole_out + NJ_AMR_LPC_ORDER, NJ_AMR_SUBFRAME,
                             NJ_AMR_LPC_ORDER);

    nj_amr_tilt_compensation(&p->tilt_mem, nj_amr_tilt_factor(lpc_n, lpc_d),
                             buf_out, NJ_AMR_SUBFRAME);

    nj_amr_adaptive_gain_control(buf_out, buf_out, speech_gain,
                                 NJ_AMR_SUBFRAME, NJ_AMR_AGC_ALPHA,
                                 &p->postfilter_agc);
}

/* ------------------------------------------------------------------ */
/* One frame                                                           */
/* ------------------------------------------------------------------ */

/*
 * Decode one 20 ms frame into `block`, 160 floats in the reference decoder's
 * scale (the high-pass at the end of the chain applies AMR_SAMPLE_SCALE, so a
 * full scale sample is about 1.0).
 */
static void nj_amr_decode_frame(nj_amr_state *p, const nj_u1 *buf, nj_u4 size,
                                float *block)
{
    nj_amr_fixed fixed_sparse;
    float        fixed_gain_factor;
    float        spare_vector[NJ_AMR_SUBFRAME];
    float        synth_fixed_gain;
    const float *synth_fixed_vector;
    int          i, subframe;

    p->mode = nj_amr_unpack(p, buf, size);

    if (p->mode >= NJ_AMR_MODE_SID) {
        /* Comfort noise and missing frames: silence rather than a guess. */
        memset(block, 0, (nj_size)NJ_AMR_BLOCK * sizeof(float));
        return;
    }

    if (p->mode == NJ_AMR_MODE_12K2)
        nj_amr_lsf2lsp_12k2(p);
    else
        nj_amr_lsf2lsp_3(p);

    for (i = 0; i < 4; i++)
        nj_amr_lspd2lpc(p->lsp[i], p->lpc[i]);

    memset(&fixed_sparse, 0, sizeof(fixed_sparse));

    for (subframe = 0; subframe < 4; subframe++) {
        const nj_amr_subframe *amr_subframe = &p->frame.subframe[subframe];

        nj_amr_decode_pitch_vector(p, amr_subframe, subframe);

        nj_amr_decode_fixed_sparse(&fixed_sparse, amr_subframe->pulses,
                                   p->mode, subframe);

        /* The fixed gain depends on the fixed vector, and the fixed vector
         * depends on pitch sharpening, which depends on the pitch gain: so
         * the pitch gain is decoded first even though the standard lists the
         * codebook gain first. */
        nj_amr_decode_gains(p, amr_subframe, subframe, &fixed_gain_factor);

        nj_amr_pitch_sharpening(p, subframe, &fixed_sparse);

        /* No lag of zero: the standard forbids it, the reference refuses a
         * frame that has one, and the lag decoded above cannot be below 17. */

        nj_amr_set_fixed_vector(p->fixed_vector, &fixed_sparse, 1.0f,
                                NJ_AMR_SUBFRAME);

        p->fixed_gain[4] = nj_amr_set_fixed_gain(
            fixed_gain_factor,
            nj_amr_dot(p->fixed_vector, p->fixed_vector, NJ_AMR_SUBFRAME) /
            (float)NJ_AMR_SUBFRAME,
            p->prediction_error, nj_amr_energy_mean[p->mode],
            nj_amr_energy_pred_fac);

        /* The excitation that feeds the next subframe's pitch search is built
         * without any of the smoothing below: the reference does it this way
         * and the technical description does not say either way. */
        for (i = 0; i < NJ_AMR_SUBFRAME; i++)
            p->excitation[i] *= p->pitch_gain[4];
        nj_amr_set_fixed_vector(p->excitation, &fixed_sparse, p->fixed_gain[4],
                                NJ_AMR_SUBFRAME);

        /* No fractional bits in the excitation, as in the reference: the
         * encoder can emit long runs of a pitch factor above one, and a
         * non-zero excitation feedback turns those into a buzz. */
        for (i = 0; i < NJ_AMR_SUBFRAME; i++)
            p->excitation[i] = nj_amr_truncf(p->excitation[i]);

        synth_fixed_gain = nj_amr_fixed_gain_smooth(p, p->lsf_q[subframe],
                                                    p->lsf_avg);

        synth_fixed_vector = nj_amr_anti_sparseness(p, &fixed_sparse,
                                                    p->fixed_vector,
                                                    synth_fixed_gain,
                                                    spare_vector);

        if (nj_amr_synthesis(p, p->lpc[subframe], synth_fixed_gain,
                             synth_fixed_vector,
                             &p->samples_in[NJ_AMR_LPC_ORDER], 0))
            nj_amr_synthesis(p, p->lpc[subframe], synth_fixed_gain,
                             synth_fixed_vector,
                             &p->samples_in[NJ_AMR_LPC_ORDER], 1);

        nj_amr_postfilter(p, p->lpc[subframe],
                          block + subframe * NJ_AMR_SUBFRAME);

        nj_amr_clear_fixed_vector(p->fixed_vector, &fixed_sparse,
                                  NJ_AMR_SUBFRAME);
        nj_amr_update_state(p);
    }

    nj_amr_order_2(block, block, nj_amr_highpass_zeros, nj_amr_highpass_poles,
                   nj_amr_highpass_gain * NJ_AMR_SAMPLE_SCALE,
                   p->high_pass_mem, NJ_AMR_BLOCK);

    /* The averaged LSF vector trails the current frame: the reference uses
     * qbar(n-1) where the technical description's equation 71 says qbar(n). */
    nj_amr_weighted_sum(p->lsf_avg, p->lsf_avg, p->lsf_q[3], 0.84f, 0.16f,
                        NJ_AMR_LPC_ORDER);
}

