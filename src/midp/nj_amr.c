/* LSF and LSP                                                         */
/* ------------------------------------------------------------------ */

/*
 * A set of 5 split-matrix quantised LSF indices into an LSP vector: the
 * 12.2 kbit/s quantiser, whose residual is predicted from the previous
 * frame's with a fixed factor.  Called twice per frame, once per LSP pair
 * (offset 0 and 2 of the five subvectors).
 */
static void nj_amr_lsf2lsp_12k2_part(nj_amr_state *p, double *lsp,
                                     const float *lsf_no_r,
                                     const nj_s2 *const *quantizer,
                                     int offset, int sign, int update)
{
    nj_s2 lsf_r[NJ_AMR_LPC_ORDER];
    float lsf_q[NJ_AMR_LPC_ORDER];
    int   i;

    for (i = 0; i < NJ_AMR_LPC_ORDER / 2; i++) {
        lsf_r[i << 1]     = quantizer[i][offset];
        lsf_r[(i << 1) + 1] = quantizer[i][offset + 1];
    }

    if (sign) {
        lsf_r[4] = (nj_s2)-lsf_r[4];
        lsf_r[5] = (nj_s2)-lsf_r[5];
    }

    if (update)
        for (i = 0; i < NJ_AMR_LPC_ORDER; i++)
            p->prev_lsf_r[i] = (float)lsf_r[i];

    for (i = 0; i < NJ_AMR_LPC_ORDER; i++)
        lsf_q[i] = (float)lsf_r[i] * (NJ_AMR_LSF_R_FAC / 8000.0f) +
                   lsf_no_r[i] * (1.0f / 8000.0f);

    /* The standard's minimum spacing keeps the LSPs ordered; a quantiser that
     * violates it would make the synthesis filter unstable. */
    {
        float prev = 0.0f;
        for (i = 0; i < NJ_AMR_LPC_ORDER; i++)
            prev = lsf_q[i] = lsf_q[i] > prev + NJ_AMR_MIN_LSF_SPACING
                            ? lsf_q[i] : prev + NJ_AMR_MIN_LSF_SPACING;
    }

    if (update) {
        for (i = 0; i < 4; i++)
            nj_amr_weighted_sum(p->lsf_q[i], p->lsf_q[3], lsf_q,
                                0.25f * (float)(3 - i), 0.25f * (float)(i + 1),
                                NJ_AMR_LPC_ORDER);
    }

    for (i = 0; i < NJ_AMR_LPC_ORDER; i++)
        lsp[i] = nj_amr_cos(2.0 * 3.14159265358979323846 * (double)lsf_q[i]);
}

/* The 12.2 kbit/s frame: five subvectors, two of them shared between the
 * second and fourth subframe's LSPs, and the two in between interpolated. */
static void nj_amr_lsf2lsp_12k2(nj_amr_state *p)
{
    const nj_u2 *lsf_param = p->frame.lsf;
    const nj_s2 *quantizer[5];
    float lsf_no_r[NJ_AMR_LPC_ORDER];
    int   i;

    quantizer[0] = nj_amr_lsf_5_1[lsf_param[0]];
    quantizer[1] = nj_amr_lsf_5_2[lsf_param[1]];
    quantizer[2] = nj_amr_lsf_5_3[lsf_param[2] >> 1];
    quantizer[3] = nj_amr_lsf_5_4[lsf_param[3]];
    quantizer[4] = nj_amr_lsf_5_5[lsf_param[4]];

    for (i = 0; i < NJ_AMR_LPC_ORDER; i++)
        lsf_no_r[i] = p->prev_lsf_r[i] * NJ_AMR_LSF_R_FAC *
                      NJ_AMR_PRED_FAC_12K2 + nj_amr_lsf_5_mean[i];

    nj_amr_lsf2lsp_12k2_part(p, p->lsp[1], lsf_no_r, quantizer, 0,
                             (int)(lsf_param[2] & 1u), 0);
    nj_amr_lsf2lsp_12k2_part(p, p->lsp[3], lsf_no_r, quantizer, 2,
                             (int)(lsf_param[2] & 1u), 1);

    nj_amr_weighted_sum_d(p->lsp[0], p->prev_lsp_sub4, p->lsp[1],
                          0.5, 0.5, NJ_AMR_LPC_ORDER);
    nj_amr_weighted_sum_d(p->lsp[2], p->lsp[1], p->lsp[3],
                          0.5, 0.5, NJ_AMR_LPC_ORDER);
}

/* Every other mode: three subvectors, the mean removed residual predicted
 * with the standard's per-coefficient factors. */
static void nj_amr_lsf2lsp_3(nj_amr_state *p)
{
    const nj_u2 *lsf_param = p->frame.lsf;
    const nj_s2 *quantizer;
    nj_s2 lsf_r[NJ_AMR_LPC_ORDER];
    float lsf_q[NJ_AMR_LPC_ORDER];
    int   i, j;

    quantizer = (p->mode == NJ_AMR_MODE_7K95 ? nj_amr_lsf_3_1_7k95
                                             : nj_amr_lsf_3_1)[lsf_param[0]];
    for (i = 0; i < 3; i++)
        lsf_r[i] = quantizer[i];

    quantizer = nj_amr_lsf_3_2[lsf_param[1]
                               << (p->mode <= NJ_AMR_MODE_5K15 ? 1 : 0)];
    for (i = 0; i < 3; i++)
        lsf_r[3 + i] = quantizer[i];

    quantizer = (p->mode <= NJ_AMR_MODE_5K15 ? nj_amr_lsf_3_3_5k15
                                             : nj_amr_lsf_3_3)[lsf_param[2]];
    for (i = 0; i < 4; i++)
        lsf_r[6 + i] = quantizer[i];

    for (i = 0; i < NJ_AMR_LPC_ORDER; i++)
        lsf_q[i] = ((float)lsf_r[i] +
                    p->prev_lsf_r[i] * nj_amr_pred_fac[i]) *
                   (NJ_AMR_LSF_R_FAC / 8000.0f) +
                   nj_amr_lsf_3_mean[i] * (1.0f / 8000.0f);

    {
        float prev = 0.0f;
        for (i = 0; i < NJ_AMR_LPC_ORDER; i++)
            prev = lsf_q[i] = lsf_q[i] > prev + NJ_AMR_MIN_LSF_SPACING
                            ? lsf_q[i] : prev + NJ_AMR_MIN_LSF_SPACING;
    }

    for (i = 0; i < 4; i++)
        nj_amr_weighted_sum(p->lsf_q[i], p->lsf_q[3], lsf_q,
                            0.25f * (float)(3 - i), 0.25f * (float)(i + 1),
                            NJ_AMR_LPC_ORDER);

    for (i = 0; i < NJ_AMR_LPC_ORDER; i++)
        p->prev_lsf_r[i] = (float)lsf_r[i];

    for (i = 0; i < NJ_AMR_LPC_ORDER; i++)
        p->lsp[3][i] = nj_amr_cos(2.0 * 3.14159265358979323846 *
                                  (double)lsf_q[i]);

    /* The intermediate subframes interpolate between the previous frame's
     * fourth LSP set and this frame's. */
    for (i = 1; i <= 3; i++)
        for (j = 0; j < NJ_AMR_LPC_ORDER; j++)
            p->lsp[i - 1][j] = p->prev_lsp_sub4[j] +
                (p->lsp[3][j] - p->prev_lsp_sub4[j]) * 0.25 * (double)i;
}

/* LSP to LPC: the two polynomials whose roots the LSPs are, summed and
 * differenced into the symmetric and antisymmetric halves of the filter. */
static void nj_amr_lsp2poly(const double *lsp, double *f, int half)
{
    double val;
    int    i, j;

    f[0] = 1.0;
    f[1] = -2.0 * lsp[0];

    for (i = 2; i <= half; i++) {
        val  = -2.0 * lsp[2 * i - 2];
        f[i] = val * f[i - 1] + 2.0 * f[i - 2];
        for (j = i - 1; j >= 2; j--)
            f[j] += f[j - 1] * val + f[j - 2];
        f[1] += val;
    }
}

static void nj_amr_lspd2lpc(const double *lsp, float *lpc)
{
    const int half = NJ_AMR_LPC_ORDER / 2;
    double pa[NJ_AMR_LPC_ORDER / 2 + 1];
    double qa[NJ_AMR_LPC_ORDER / 2 + 1];
    float *lpc2 = lpc + NJ_AMR_LPC_ORDER - 1;
    int    i;

    nj_amr_lsp2poly(lsp, pa, half);
    nj_amr_lsp2poly(lsp + 1, qa, half);

    for (i = half - 1; i >= 0; i--) {
        double paf = pa[i + 1] + pa[i];
        double qaf = qa[i + 1] - qa[i];

        lpc[i]        = (float)(0.5 * (paf + qaf));
        lpc2[-i]      = (float)(0.5 * (paf - qaf));
    }
}

