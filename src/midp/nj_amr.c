/*
 * The 12.2 kbit/s mode codes its pitch lag at a sixth of a sample, in two
 * different ways: subframes 1 and 3 absolutely, subframes 2 and 4 relative to
 * the lag that came before.
 */
static void nj_amr_pitch_lag_1_6(int *lag_int, int *lag_frac, int pitch_index,
                                 int prev_lag_int, int subframe)
{
    if (subframe == 0 || subframe == 2) {
        if (pitch_index < 463) {
            *lag_int  = (pitch_index + 107) * 10923 >> 16;
            *lag_frac = pitch_index - *lag_int * 6 + 105;
        } else {
            *lag_int  = pitch_index - 368;
            *lag_frac = 0;
        }
    } else {
        int min_lag;

        *lag_int  = ((pitch_index + 5) * 10923 >> 16) - 1;
        *lag_frac = pitch_index - *lag_int * 6 - 3;

        min_lag = prev_lag_int - 5;
        if (min_lag < NJ_AMR_PITCH_LAG_MIN_12K2)
            min_lag = NJ_AMR_PITCH_LAG_MIN_12K2;
        if (min_lag > NJ_AMR_PITCH_DELAY_MAX - 9)
            min_lag = NJ_AMR_PITCH_DELAY_MAX - 9;
        *lag_int += min_lag;
    }
}

/*
 * The other modes: a search range around the previous lag, at a quarter,
 * third or sixth of a sample depending on how many bits the mode spends on
 * the index.  n * 10923 >> 15 is floor(n/3) for every n a lag can be.
 */
static void nj_amr_decode_pitch_lag(int *lag_int, int *lag_frac,
                                    int pitch_index, int prev_lag_int,
                                    int subframe, int third_as_first,
                                    int resolution)
{
    if (subframe == 0 || (subframe == 2 && third_as_first)) {
        if (pitch_index < 197)
            pitch_index += 59;
        else
            pitch_index = 3 * pitch_index - 335;
    } else if (resolution == 4) {
        int min_lag = prev_lag_int - 5;

        if (min_lag < NJ_AMR_PITCH_DELAY_MIN)
            min_lag = NJ_AMR_PITCH_DELAY_MIN;
        if (min_lag > NJ_AMR_PITCH_DELAY_MAX - 9)
            min_lag = NJ_AMR_PITCH_DELAY_MAX - 9;

        if (pitch_index < 4) {
            /* integer precision in the first four positions */
            pitch_index = 3 * (pitch_index + min_lag) + 1;
        } else if (pitch_index < 12) {
            /* a third of a sample through the middle */
            pitch_index += 3 * min_lag + 7;
        } else {
            /* integer precision again, six samples up */
            pitch_index = 3 * (pitch_index + min_lag - 6) + 1;
        }
    } else {
        int min_lag;

        pitch_index--;

        if (resolution == 5) {
            min_lag = prev_lag_int - 10;
            if (min_lag < NJ_AMR_PITCH_DELAY_MIN)
                min_lag = NJ_AMR_PITCH_DELAY_MIN;
            if (min_lag > NJ_AMR_PITCH_DELAY_MAX - 19)
                min_lag = NJ_AMR_PITCH_DELAY_MAX - 19;
        } else {
            min_lag = prev_lag_int - 5;
            if (min_lag < NJ_AMR_PITCH_DELAY_MIN)
                min_lag = NJ_AMR_PITCH_DELAY_MIN;
            if (min_lag > NJ_AMR_PITCH_DELAY_MAX - 9)
                min_lag = NJ_AMR_PITCH_DELAY_MAX - 9;
        }

        pitch_index += 3 * min_lag;
    }

    *lag_int  = pitch_index * 10923 >> 15;
    *lag_frac = pitch_index - 3 * *lag_int - 1;
}

/*
 * The pitch vector: the past excitation interpolated at the decoded lag with
 * the standard's windowed sinc, at sixth sample resolution.
 */
static void nj_amr_decode_pitch_vector(nj_amr_state *p,
                                       const nj_amr_subframe *subframe,
                                       int subframe_no)
{
    int pitch_lag_int, pitch_lag_frac;

    if (p->mode == NJ_AMR_MODE_12K2) {
        nj_amr_pitch_lag_1_6(&pitch_lag_int, &pitch_lag_frac,
                             (int)subframe->p_lag, p->pitch_lag_int,
                             subframe_no);
    } else {
        nj_amr_decode_pitch_lag(&pitch_lag_int, &pitch_lag_frac,
                                (int)subframe->p_lag, p->pitch_lag_int,
                                subframe_no,
                                p->mode != NJ_AMR_MODE_4K75 &&
                                p->mode != NJ_AMR_MODE_5K15,
                                p->mode <= NJ_AMR_MODE_6K7 ? 4 :
                                (p->mode == NJ_AMR_MODE_7K95 ? 5 : 6));
        pitch_lag_frac *= 2;
    }

    p->pitch_lag_int = pitch_lag_int;    /* the previous lag, for the next one */

    pitch_lag_int += pitch_lag_frac > 0;

    nj_amr_interpolate(p->excitation, p->excitation + 1 - pitch_lag_int,
                       nj_amr_b60_sinc, 6,
                       pitch_lag_frac + 6 - 6 * (pitch_lag_frac > 0),
                       10, NJ_AMR_SUBFRAME);

    memcpy(p->pitch_vector, p->excitation,
           NJ_AMR_SUBFRAME * sizeof(float));
}

