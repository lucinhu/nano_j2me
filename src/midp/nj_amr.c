static float nj_amr_dot(const float *a, const float *b, int n)
{
    float sum = 0.0f;
    int   i;

    for (i = 0; i < n; i++)
        sum += a[i] * b[i];
    return sum;
}

static void nj_amr_weighted_sum(float *out, const float *a, const float *b,
                                float wa, float wb, int n)
{
    int i;

    for (i = 0; i < n; i++)
        out[i] = wa * a[i] + wb * b[i];
}

static void nj_amr_weighted_sum_d(double *out, const double *a, const double *b,
                                  double wa, double wb, int n)
{
    int i;

    for (i = 0; i < n; i++)
        out[i] = wa * a[i] + wb * b[i];
}

/*
 * Interpolate the past excitation at a fractional pitch lag with the 60 tap
 * Hamming windowed sinc of the standard.  The filter coefficient table is
 * indexed with a fractional position and a step of `precision`: this is
 * upsampling by six, and the two taps per term are the two sides of the
 * window around the sample.
 */
static void nj_amr_interpolate(float *out, const float *in,
                               const float *coeffs, int precision,
                               int frac_pos, int filter_length, int length)
{
    int n, i;

    for (n = 0; n < length; n++) {
        int   idx = 0;
        float v = 0.0f;

        for (i = 0; i < filter_length; ) {
            v += in[n + i] * coeffs[idx + frac_pos];
            idx += precision;
            i++;
            v += in[n - i] * coeffs[idx - frac_pos];
        }
        out[n] = v;
    }
}

/* Second order transfer function: the high-pass at the end of a frame. */
static void nj_amr_order_2(float *out, const float *in,
                           const float zero_coeffs[2],
                           const float pole_coeffs[2],
                           float gain, float mem[2], int n)
{
    int   i;
    float tmp;

    for (i = 0; i < n; i++) {
        tmp = gain * in[i] - pole_coeffs[0] * mem[0] - pole_coeffs[1] * mem[1];
        out[i] = tmp + zero_coeffs[0] * mem[0] + zero_coeffs[1] * mem[1];

        mem[1] = mem[0];
        mem[0] = tmp;
    }
}

/* Tilt compensation: remove the spectral tilt the postfilter introduced. */
static void nj_amr_tilt_compensation(float *mem, float tilt, float *samples,
                                     int size)
{
    float new_mem = samples[size - 1];
    int   i;

    for (i = size - 1; i > 0; i--)
        samples[i] -= tilt * samples[i - 1];

    samples[0] -= tilt * *mem;
    *mem = new_mem;
}

/*
 * Circularly add a scaled, lagged copy of `lagged` to `in`.  The pitch
 * sharpening of the fixed vector and the phase dispersion filter are both
 * this operation.
 */
static void nj_amr_circ_add(float *out, const float *in, const float *lagged,
                            int lag, float fac, int n)
{
    int k;

    for (k = 0; k < lag; k++)
        out[k] = in[k] + fac * lagged[n + k - lag];
    for (; k < n; k++)
        out[k] = in[k] + fac * lagged[k - lag];
}

/* Tenth order synthesis: the short term filter, one output sample at a time.
 * The reference's fast path unrolls this by four; the arithmetic is the same
 * and the summation order does not matter at float precision. */
static void nj_amr_lp_synthesis(float *out, const float *coeffs,
                                const float *in, int length, int order)
{
    int i, n;

    for (n = 0; n < length; n++) {
        out[n] = in[n];
        for (i = 1; i <= order; i++)
            out[n] -= coeffs[i - 1] * out[n - i];
    }
}

/* The zero filter: the numerator of the postfilter, which sees the input. */
static void nj_amr_lp_zero_synthesis(float *out, const float *coeffs,
                                     const float *in, int length, int order)
{
    int i, n;

    for (n = 0; n < length; n++) {
        out[n] = in[n];
        for (i = 1; i <= order; i++)
            out[n] += coeffs[i - 1] * in[n - i];
    }
}

/*
 * Adaptive gain control: scale the postfiltered subframe back to the energy
 * the unfiltered one had, with the one pole smoothing of the standard.
 */
static void nj_amr_adaptive_gain_control(float *out, const float *in,
                                         float speech_energ, int size,
                                         float alpha, float *gain_mem)
{
    float postfilter_energ = nj_amr_dot(in, in, size);
    float gain_scale_factor = 1.0f;
    float mem = *gain_mem;
    int   i;

    if (postfilter_energ != 0.0f)
        gain_scale_factor = (float)nj_amr_sqrt((double)speech_energ /
                                               (double)postfilter_energ);

    gain_scale_factor *= 1.0f - alpha;

    for (i = 0; i < size; i++) {
        mem = alpha * mem + gain_scale_factor;
        out[i] = in[i] * mem;
    }

    *gain_mem = mem;
}

static void nj_amr_scale_to_sum_of_squares(float *out, const float *in,
                                           float sum_of_squares, int n)
{
    float scalefactor = nj_amr_dot(in, in, n);
    int   i;

    if (scalefactor != 0.0f)
        scalefactor = (float)nj_amr_sqrt((double)sum_of_squares /
                                         (double)scalefactor);

    for (i = 0; i < n; i++)
        out[i] = in[i] * scalefactor;
}

