#!/usr/bin/env python3
"""Rebuild the Vulkan 1.0 modules with glslangValidator and validate SPIR-V."""
import pathlib
import struct
import subprocess
import tempfile

root = pathlib.Path(__file__).resolve().parent
def rebuild(name):
    lines = ["/* Generated by generate_shaders.py. Edit %s.vert / %s.frag. */" % (name, name)]
    with tempfile.TemporaryDirectory() as tmp:
        for stage in ("vert", "frag"):
            output = pathlib.Path(tmp) / "shader.spv"
            subprocess.run(["glslangValidator", "--target-env", "vulkan1.0", "-Os",
                            "-o", output, root / ("%s.%s" % (name, stage))], check=True)
            subprocess.run(["spirv-val", "--target-env", "vulkan1.0", output], check=True)
            data = output.read_bytes()
            words = struct.unpack("<%dI" % (len(data) // 4), data)
            lines.append("static const uint32_t %s_%s[] = {" % (name, stage))
            for i in range(0, len(words), 8):
                lines.append("    " + ", ".join("0x%08x" % v for v in words[i:i+8]) + ",")
            lines.append("};")
    (root / (name + "_spv.inc")).write_text("\n".join(lines) + "\n", encoding="ascii")
rebuild("tri")
rebuild("post")
