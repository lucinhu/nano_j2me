static int ref_worst_delta(const nj_u1 *pcm, const nj_s2 *ref, nj_u4 samples)
{
    nj_u4 i;
    int worst = 0;

    for (i = 0; i < samples; i++) {
        nj_u2 raw = (nj_u2)((nj_u2)pcm[2u * i] |
                            ((nj_u2)pcm[2u * i + 1u] << 8));
        int v = (int)(nj_s2)raw;
        int d = v - (int)ref[i];

        if (d < 0) {
            d = -d;
        }
        if (d > worst) {
            worst = d;
        }
    }
    return worst;
}

static int ref_peak(const nj_s2 *ref, nj_u4 samples)
{
    nj_u4 i;
    int peak = 0;

    for (i = 0; i < samples; i++) {
        int v = (int)ref[i];

        if (v < 0) {
            v = -v;
        }
        if (v > peak) {
            peak = v;
        }
    }
    return peak;
}

static void test_reference_pcm(void)
{
    nj_u1 *pcm;
    run_stat st;
    nj_u4 got;
    int worst;

    pcm = (nj_u1 *)malloc(65536);
    ok(pcm != NULL, "reference PCM buffer allocated");
    if (pcm == NULL) {
        return;
    }

    /* MPEG-1 mono: 10 frames (Info + 9 audio), last frame is short. */
    got = run_collect(&nj_av_audio_mp3, fx_m1_mono_mp3,
                      (nj_u4)sizeof(fx_m1_mono_mp3), 97u, pcm, 65536u, &st);
    okf(got == 23040u, "MPEG-1 mono PCM bytes %ld (want %ld)",
        (long)got, (long)23040u);
    okf(st.frames == 11520u, "MPEG-1 mono PCM frames %ld (want %ld)",
        (long)st.frames, (long)11520u);
    ok(ref_peak(fx_m1_mono_ref, 1152u) > 1000,
       "MPEG-1 mono reference frame is not silence");
    worst = ref_worst_delta(pcm + 9u * 1152u * 2u, fx_m1_mono_ref, 1152u);
    okf(worst <= 1, "MPEG-1 mono reference worst delta %ld (max %ld)",
        (long)worst, (long)1);

    /* MPEG-1 stereo: same stream shape, interleaved samples. */
    got = run_collect(&nj_av_audio_mp3, fx_m1_stereo_mp3,
                      (nj_u4)sizeof(fx_m1_stereo_mp3), 97u, pcm, 65536u, &st);
    okf(got == 46080u, "MPEG-1 stereo PCM bytes %ld (want %ld)",
        (long)got, (long)46080u);
    okf(st.frames == 11520u, "MPEG-1 stereo PCM frames %ld (want %ld)",
        (long)st.frames, (long)11520u);
    ok(ref_peak(fx_m1_stereo_ref, 2304u) > 1000,
       "MPEG-1 stereo reference frame is not silence");
    worst = ref_worst_delta(pcm + 9u * 1152u * 4u, fx_m1_stereo_ref, 2304u);
    okf(worst <= 1, "MPEG-1 stereo reference worst delta %ld (max %ld)",
        (long)worst, (long)1);

    /* MPEG-2.5 mono: one granule per frame, 576 samples per frame. */
    got = run_collect(&nj_av_audio_mp3, fx_m25_mono_mp3,
                      (nj_u4)sizeof(fx_m25_mono_mp3), 97u, pcm, 65536u, &st);
    okf(got == 8064u, "MPEG-2.5 mono PCM bytes %ld (want %ld)",
        (long)got, (long)8064u);
    okf(st.frames == 4032u, "MPEG-2.5 mono PCM frames %ld (want %ld)",
        (long)st.frames, (long)4032u);
    ok(ref_peak(fx_m25_mono_ref, 576u) > 1000,
       "MPEG-2.5 mono reference frame is not silence");
    worst = ref_worst_delta(pcm + 6u * 576u * 2u, fx_m25_mono_ref, 576u);
    okf(worst <= 1, "MPEG-2.5 mono reference worst delta %ld (max %ld)",
        (long)worst, (long)1);


    /* MPEG-2.5 stereo: one granule per frame, two interleaved channels. */
    got = run_collect(&nj_av_audio_mp3, fx_m25_stereo_mp3,
                      (nj_u4)sizeof(fx_m25_stereo_mp3), 97u, pcm, 65536u, &st);
    okf(got == 16128u, "MPEG-2.5 stereo PCM bytes %ld (want %ld)",
        (long)got, (long)16128u);
    okf(st.frames == 4032u, "MPEG-2.5 stereo PCM frames %ld (want %ld)",
        (long)st.frames, (long)4032u);
    ok(ref_peak(fx_m25_stereo_ref, 1152u) > 1000,
       "MPEG-2.5 stereo reference frame is not silence");
    worst = ref_worst_delta(pcm + 6u * 576u * 4u, fx_m25_stereo_ref, 1152u);
    okf(worst <= 1, "MPEG-2.5 stereo reference worst delta %ld (max %ld)",
        (long)worst, (long)1);

    free(pcm);
}

