#!/usr/bin/env python3
"""Generate tests/ioapi/ioapi_fixture.h from the compiled Java fixture.

The java.io contract cannot be exercised from C alone.  The bug this fixture
guards lives in constant-pool resolution: `invokeinterface
java/io/DataInput.readFloat:()F` has to find the method on the interface that
declares it, and `getfield java/io/Reader.lock:Ljava/lang/Object;` has to find
a protected field inherited from a superclass.  A C-level nj_call() names the
class directly, so it bypasses exactly the lookup that broke.

tests/test_ioapi.c therefore embeds the fixture classes as byte arrays and runs
their real bytecode with nj_class_load() + nj_call_static(), the pattern
tests/test_resolution.c established.  The arrays are generated here so the C
file stays readable, and the header is checked in so the CMake build needs no
Java toolchain.

Regenerate after editing a fixture source:

    javac --release 8 -d /tmp/ioapi tests/ioapi/*.java
    python3 tests/ioapi/gen_c_header.py /tmp/ioapi

The expected values are a desktop HotSpot run of the same sources; the oracle
program is tests/ioapi/IoApiDesktop.java (see README.md in this directory).
"""

import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
HEADER = os.path.join(HERE, "ioapi_fixture.h")

# (C array name, path below the class output directory)
CLASSES = [
    ("ioapi_IoApiProbe_class", "ioapi/IoApiProbe.class"),
    ("ioapi_LockReader_class", "ioapi/LockReader.class"),
    ("ioapi_RangeOnlyReader_class", "ioapi/RangeOnlyReader.class"),
]


def main():
    if len(sys.argv) != 2:
        sys.stderr.write("usage: gen_c_header.py <class-output-dir>\n")
        return 2
    root = sys.argv[1]
    out = []
    out.append("/*")
    out.append(" * Generated by tests/ioapi/gen_c_header.py - do not edit.")
    out.append(" *")
    out.append(" * Class-file bytes of the java.io fixture, compiled from")
    out.append(" * tests/ioapi/*.java with javac --release 8.  The major version")
    out.append(" * is lowered to 48 (CLDC) the way tests/test_resolution.c does,")
    out.append(" * so the embedded classes look like MIDP class files.")
    out.append(" */")
    out.append("#ifndef IOAPI_FIXTURE_H")
    out.append("#define IOAPI_FIXTURE_H")
    for cname, rel in CLASSES:
        path = os.path.join(root, rel)
        with open(path, "rb") as f:
            data = bytearray(f.read())
        if data[:4] != b"\xca\xfe\xba\xbe" or len(data) < 8:
            raise SystemExit("%s is not a class file" % path)
        data[6:8] = b"\x00\x30"      # major version 48, minor 0
        out.append("")
        out.append("static const nj_u1 %s[] = {" % cname)
        line = "    "
        for i, b in enumerate(data):
            line += "0x%02x, " % b
            if (i + 1) % 16 == 0:
                out.append(line.rstrip())
                line = "    "
        if line.strip():
            out.append(line.rstrip())
        out.append("};")
    out.append("")
    out.append("#endif /* IOAPI_FIXTURE_H */")
    text = "\n".join(out) + "\n"
    with open(HEADER, "w", encoding="ascii") as f:
        f.write(text)
    print("wrote %s (%d bytes)" % (HEADER, len(text)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
