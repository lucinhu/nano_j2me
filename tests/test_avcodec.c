typedef struct fake_dec {
    int left;
} fake_dec;

static int fake_accepts(const nj_u1 *data, nj_u4 len)
{
    (void)data;
    return len > 0u;
}

static nj_av_dec *fake_open(const nj_u1 *data, nj_u4 len, const nj_av_mem *mem,
                            nj_av_info *info, const char **err)
{
    fake_dec *d;

    (void)data;
    (void)err;
    d = (fake_dec *)mem->alloc(mem->ud, (nj_size)sizeof(*d));
    if (d == NULL) {
        return NULL;
    }
    d->left = 16;
    info->format = NJ_AV_AUDIO_MP3;
    info->rate = 8000u;
    info->channels = 1u;
    info->frames = 16u;
    (void)len;
    return (nj_av_dec *)d;
}

