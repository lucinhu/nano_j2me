static nj_ref make_player(nj_vm *vm)
{
    nj_ref bar, in, player;
    nj_value a[2], ret;

    bar = nj_byte_array_new(vm, (nj_u4)sizeof(mp3));
    if (bar == NULL) {
        nj_clear_exception(vm);
        return NULL;
    }
    memcpy(bar->u.bytes, mp3, sizeof(mp3));
    in = nj_object_new(vm, "java/io/ByteArrayInputStream");
    if (in == NULL) {
        nj_clear_exception(vm);
        return NULL;
    }
    a[0].r = bar;
    if (nj_call_special(vm, in, "java/io/ByteArrayInputStream", "<init>",
                        "([B)V", a, NULL) != NJ_OK) {
        nj_clear_exception(vm);
        return NULL;
    }
    a[0].r = in;
    a[1].r = nj_string_new(vm, "audio/mpeg");
    ret.bits = 0u;
    if (nj_call_static(vm, MEDIA_MGR, "createPlayer",
                       "(Ljava/io/InputStream;Ljava/lang/String;)L"
                       "javax/microedition/media/Player;", a, &ret) != NJ_OK) {
        nj_clear_exception(vm);
        return NULL;
    }
    return ret.r;
}

int main(void)
{
    nj_port port;
    nj_vm *vm;
    const nj_av_audio_ops *found;
    nj_value a[2];

    memset(&port, 0, sizeof(port));
    if (nj_port_headless(&port) != NJ_OK) {
        fprintf(stderr, "FAIL: headless port\n");
        return 1;
    }
    port.pcm_write = capture_pcm;
    vm = nj_vm_create(&port, 2u * 1024u * 1024u);
    if (vm == NULL) {
        fprintf(stderr, "FAIL: vm\n");
        return 1;
    }

    /* The built-in Layer III decoder is registered and finds a real stream. */
    ok(nj_avcodec_sw_mp3() != NULL, "the software MP3 provider exists");
    found = nj_avcodec_find_audio(vm, mp3, (nj_u4)sizeof(mp3));
    ok(found == nj_avcodec_sw_mp3(), "the built-in MP3 decoder is chosen");

    /* A stream no provider knows is refused by the lookup. */
    {
        static const nj_u1 junk[8] = { 0u, 1u, 2u, 3u, 29u, 55u, 89u, 233u };
        ok(nj_avcodec_find_audio(vm, junk, (nj_u4)sizeof(junk)) == NULL,
           "an unknown stream finds no audio provider");
    }

    /* A port's video decoder replaces the built-in one the same way. */
    ok(nj_avcodec_install_video(vm, &fake_h263) > 0,
       "a port can install a video provider");
    ok(nj_avcodec_find_video(vm, mp3, 2u) == &fake_h263,
       "the installed video provider is chosen first");
    ok(nj_avcodec_install_video(vm, NULL) == 0,
       "removing every video provider empties the table");
    ok(nj_avcodec_find_video(vm, mp3, 2u) == NULL,
       "with the table empty no video provider is found");

    /* Install the port's decoder: it must win over the built-in one. */
    ok(nj_avcodec_install_audio(vm, &fake_mp3) > 0,
       "a port can install an audio provider (returns the new count)");
    found = nj_avcodec_find_audio(vm, mp3, (nj_u4)sizeof(mp3));
    ok(found == &fake_mp3, "the installed provider is chosen over the built-in");

    /* And createPlayer() must hand the stream to it. */
    {
        nj_ref player = make_player(vm);
        nj_value args[2];
        nj_field *f;

        ok(player != NULL, "createPlayer() builds an MP3 Player");
        if (player != NULL) {
            args[0].i = 0;
            (void)nj_call(vm, player, "javax/microedition/media/Player",
                          "realize", "()V", NULL, NULL);
            (void)nj_call(vm, player, "javax/microedition/media/Player",
                          "prefetch", "()V", NULL, NULL);
            (void)nj_call(vm, player, "javax/microedition/media/Player",
                          "start", "()V", NULL, NULL);
            f = nj_field_lookup(vm, "javax/microedition/media/Player",
                                "pAvK", "Z", 0);
            ok(f != NULL && nj_field_read_int(vm, player, f) == 1,
               "the Player is rendered by an nj_avcodec provider");
            {
                int i;

                for (i = 0; i < 40; i++) {
                    nj_media_frame(vm);
                }
            }
            ok(captured == 0x1234,
               "the port's samples reach the device");
            (void)args;
        }
    }

    printf("test_avcodec: %d checks, %d failure(s)\n", checks, fails);
    nj_vm_destroy(vm);
    return fails == 0 ? 0 : 1;
}
