typedef struct acct_hdr {
    nj_u4 n;
    nj_u4 magic;
} acct_hdr;

#define ACCT_MAGIC 0x48433236u

static unsigned long live;
static unsigned long peak;
static int bad_free;

static void *acct_alloc(void *ud, nj_u4 n)
{
    acct_hdr *h;

    (void)ud;
    h = (acct_hdr *)malloc(sizeof(*h) + (size_t)n);
    if (h == NULL) {
        return NULL;
    }
    h->n = n;
    h->magic = ACCT_MAGIC;
    live += n;
    if (live > peak) {
        peak = live;
    }
    return (void *)(h + 1);
}

static void acct_free(void *ud, void *p)
{
    acct_hdr *h;

    (void)ud;
    if (p == NULL) {
        return;
    }
    h = ((acct_hdr *)p) - 1;
    if (h->magic != ACCT_MAGIC) {
        bad_free++;
        return;
    }
    h->magic = 0;
    live -= h->n;
    free(h);
}

static void acct_reset(void)
{
    live = 0;
    peak = 0;
    bad_free = 0;
}

static nj_av_mem acct_mem(void)
{
    nj_av_mem m;

    m.ud = NULL;
    m.alloc = acct_alloc;
    m.free = acct_free;
    return m;
}

