static int chan_delta(nj_u2 a, nj_u2 b)
{
    int ar = (a >> 11) & 0x1f;
    int ag = (a >> 5) & 0x3f;
    int ab = a & 0x1f;
    int br = (b >> 11) & 0x1f;
    int bg = (b >> 5) & 0x3f;
    int bb = b & 0x1f;
    int d = 0;
    int t;

    t = ar - br;
    if (t < 0) t = -t;
    if (t > d) d = t;
    t = ag - bg;
    if (t < 0) t = -t;
    if (t > d) d = t;
    t = ab - bb;
    if (t < 0) t = -t;
    if (t > d) d = t;
    return d;
}

static void check_spots(const nj_u1 *rgb, int width, const spot *spots,
                        int n, const char *what)
{
    int i;
    int bad = 0;
    int worst = 0;

    for (i = 0; i < n; i++) {
        const nj_u1 *p = rgb + ((size_t)spots[i].y * (size_t)width +
                                spots[i].x) * 2u;
        nj_u2 got;
        int d;

        memcpy(&got, p, sizeof(got));
        d = chan_delta(spots[i].rgb, got);
        if (d > worst) {
            worst = d;
        }
        if (d > 4) {
            bad++;
            printf("  spot %u,%u expected %04x got %04x (delta %d)\n",
                   (unsigned)spots[i].x, (unsigned)spots[i].y,
                   (unsigned)spots[i].rgb, (unsigned)got, d);
        }
    }
    ok(bad == 0, what);
    if (bad == 0) {
        printf("  %s: %d spots, worst channel delta %d\n", what, n, worst);
    }
}

