/*
 * nano_j2me - tests/test_h263.c
 *
 * Tests for the H.263 video path: the ISO base media sample iterator
 * (src/midp/nj_mp4.c) and the H.263 baseline provider (src/midp/nj_h263.c).
 *
 * The container fixtures are held as bytes so the test needs no files:
 *
 *   mini_mp4 / mini_co64  a two-sample, two-chunk movie built by hand here
 *                         (ftyp, mdat, moov with one s263 track), once with
 *                         stco and once with co64.  The samples are four
 *                         bytes each, so the assertions are about the tables,
 *                         not about a decoder.
 *   mini_mp4v             the same movie with an 'mp4v' sample entry; the
 *                         provider must refuse MPEG-4 Part 2 cleanly.
 *   clip_3gp              ffmpeg's 128x96 four-frame 3GP (I, P, P, P), used
 *                         to drive the provider's container path.
 *   raw_h263              the same codec's 128x96 two-frame elementary
 *                         stream (I, P), used for the raw path.
 *
 * Decoded pixels are compared with ffmpeg's own RGB565 output for the same
 * fixtures at thirteen positions per frame.  ffmpeg's IDCT and this integer
 * IDCT differ by at most a couple of levels, so the check allows +-4 per
 * channel; the measured worst case is 3.  This is a real cross-check of the
 * picture header, MCBPC/CBPY, DC/AC VLC, dequantiser, IDCT, motion vectors,
 * half-pel interpolation, edge replication and the YUV->RGB conversion, not
 * just a smoke test.
 *
 * Usage: test_h263
 */
