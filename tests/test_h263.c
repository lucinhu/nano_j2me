static void test_provider_mp4(void)
{
    nj_av_mem mem = acct_mem();
    nj_av_info info;
    nj_av_step step;
    nj_av_dec *dec;
    const char *err = NULL;
    nj_u1 *out;
    nj_u4 cap = 128u * 96u * 2u;
    int i;
    int rc;

    acct_reset();
    dec = nj_av_video_h263.open(clip_3gp, (nj_u4)sizeof(clip_3gp), &mem,
                                &info, &err);
    ok(dec != NULL, "mp4: open");
    if (dec == NULL) {
        printf("  open error: %s\n", err != NULL ? err : "(none)");
        return;
    }
    ok(info.format == NJ_AV_VIDEO_H263, "mp4: format H.263");
    ok(info.width == 128 && info.height == 96, "mp4: dimensions from stsd");
    ok(info.fps == 5, "mp4: fps from mdhd/stts");
    ok(info.frames == 4, "mp4: sample count");
    ok(info.duration_ms == 800, "mp4: duration in milliseconds");
    ok(info.pixfmt == NJ_AV_PIX_RGB565, "mp4: RGB565 output");

    out = (nj_u1 *)malloc(cap);
    ok(out != NULL, "mp4: output buffer");
    if (out == NULL) {
        nj_av_video_h263.close(dec);
        return;
    }
    for (i = 0; i < 4; i++) {
        memset(&step, 0, sizeof(step));
        step.out = out;
        step.out_cap = cap;
        rc = nj_av_video_h263.decode(dec, &step);
        ok(rc == NJ_AV_OK && step.frames == 1 && step.out_used == cap,
           "mp4: frame decodes");
        ok(step.in_used == 0, "mp4: container path leaves in_used zero");
        ok(step.time_us == (nj_s8)i * 200000,
           "mp4: decode timestamp from stts");
        check_spots(out, 128, clip_spots[i], 13, "mp4: frame spot colours");
    }
    memset(&step, 0, sizeof(step));
    step.out = out;
    step.out_cap = cap;
    ok(nj_av_video_h263.decode(dec, &step) == NJ_AV_ERR_END,
       "mp4: END after the fourth sample");

    nj_av_video_h263.close(dec);
    free(out);
    ok(live == 0, "mp4: close releases every allocation");
    ok(bad_free == 0, "mp4: every free came from the provider");
}

/* ------------------------------------------------------------------ */
/* Refusals and damaged input                                          */
/* ------------------------------------------------------------------ */

static void test_refusals(void)
{
    nj_av_mem mem = acct_mem();
    nj_av_info info;
    const char *err = NULL;
    nj_av_dec *dec;
    int i;

    acct_reset();
    err = NULL;
    dec = nj_av_video_h263.open(mini_mp4v, (nj_u4)sizeof(mini_mp4v),
                                &mem, &info, &err);
    ok(dec == NULL, "mp4v: provider refuses MPEG-4 Part 2");
    ok(err != NULL && strstr(err, "MPEG-4") != NULL,
       "mp4v: error names MPEG-4 Part 2");
    ok(live == 0, "mp4v: failed open releases its allocations");

    err = NULL;
    dec = nj_av_video_h263.open(raw_h263, 10, &mem, &info, &err);
    if (dec != NULL) {
        /* A ten-byte prefix still holds the 50-bit picture header, so open
         * can succeed; the picture itself is cut short. */
        nj_u1 out[24576];
        nj_av_step step;
        memset(&step, 0, sizeof(step));
        step.out = out;
        step.out_cap = sizeof(out);
        ok(nj_av_video_h263.decode(dec, &step) != NJ_AV_OK,
           "truncated raw: short picture does not decode");
        nj_av_video_h263.close(dec);
    } else {
        ok(err != NULL, "truncated raw: failed open sets an error string");
    }
    ok(live == 0, "truncated raw: failed open releases its allocations");

    /* Truncate the raw stream at many lengths.  Some prefixes still contain a
     * complete header (open succeeds) while the picture is cut short (decode
     * must fail); every path must free what it took.  */
    for (i = 1; i < (int)sizeof(raw_h263); i += 97) {
        dec = nj_av_video_h263.open(raw_h263, (nj_u4)i, &mem, &info, &err);
        if (dec != NULL) {
            nj_u1 out[24576];
            nj_av_step step;
            memset(&step, 0, sizeof(step));
            step.out = out;
            step.out_cap = sizeof(out);
            (void)nj_av_video_h263.decode(dec, &step);
            nj_av_video_h263.close(dec);
        }
        if (live != 0) {
            break;
        }
    }
    ok(live == 0, "truncated raw: every prefix opens/closes without leaking");
    ok(bad_free == 0, "truncated raw: no invalid free");

    ok(nj_av_video_h263.open(NULL, 0, &mem, &info, &err) == NULL,
       "NULL input refused");
    ok(nj_av_video_h263.open(raw_h263, (nj_u4)sizeof(raw_h263), NULL,
                             &info, &err) == NULL,
       "NULL allocator refused");
}

