static void test_provider_raw(void)
{
    nj_av_mem mem = acct_mem();
    nj_av_info info;
    nj_av_step step;
    nj_av_dec *dec;
    const char *err = NULL;
    nj_u1 *out;
    nj_u4 cap = 128u * 96u * 2u;
    int rc;

    acct_reset();
    ok(nj_av_video_h263.accepts(raw_h263, (nj_u4)sizeof(raw_h263)) == 1,
       "raw: accepts a PSC stream");
    ok(nj_av_video_h263.accepts(clip_3gp, (nj_u4)sizeof(clip_3gp)) == 1,
       "raw: accepts an ftyp stream");
    ok(nj_av_video_h263.accepts((const nj_u1 *)"xyz", 3) == 0,
       "raw: rejects junk");

    dec = nj_av_video_h263.open(raw_h263, (nj_u4)sizeof(raw_h263), &mem,
                                &info, &err);
    ok(dec != NULL, "raw: open");
    if (dec == NULL) {
        printf("  open error: %s\n", err != NULL ? err : "(none)");
        return;
    }
    ok(err == NULL, "raw: no error string on success");
    ok(info.format == NJ_AV_VIDEO_H263, "raw: format H.263");
    ok(info.width == 128 && info.height == 96, "raw: 128x96 from picture header");
    ok(info.pixfmt == NJ_AV_PIX_RGB565, "raw: RGB565 output");
    ok(info.fps == 25 && info.frames == 0, "raw: default fps, unknown count");

    out = (nj_u1 *)malloc(cap);
    ok(out != NULL, "raw: output buffer");
    if (out == NULL) {
        nj_av_video_h263.close(dec);
        return;
    }

    memset(&step, 0, sizeof(step));
    step.in = raw_h263;
    step.in_len = (nj_u4)sizeof(raw_h263);
    step.out = out;
    step.out_cap = cap - 2u;
    rc = nj_av_video_h263.decode(dec, &step);
    ok(rc < 0 && step.frames == 0 && step.out_used == 0,
       "raw: short output buffer refused without consuming a frame");

    memset(&step, 0, sizeof(step));
    step.out = out;
    step.out_cap = cap;
    rc = nj_av_video_h263.decode(dec, &step);
    ok(rc == NJ_AV_OK && step.frames == 1 && step.out_used == cap,
       "raw: frame 0 decodes");
    ok(step.in_used == 1307, "raw: frame 0 consumes the first picture");
    check_spots(out, 128, q20_spots[0], 13, "raw: frame 0 spot colours");

    memset(&step, 0, sizeof(step));
    step.out = out;
    step.out_cap = cap;
    rc = nj_av_video_h263.decode(dec, &step);
    ok(rc == NJ_AV_OK && step.frames == 1 && step.out_used == cap,
       "raw: frame 1 decodes");
    ok(step.in_used == 344, "raw: frame 1 consumes the second picture");
    check_spots(out, 128, q20_spots[1], 13, "raw: frame 1 spot colours");

    memset(&step, 0, sizeof(step));
    step.out = out;
    step.out_cap = cap;
    ok(nj_av_video_h263.decode(dec, &step) == NJ_AV_ERR_END,
       "raw: END at end of stream");

    nj_av_video_h263.close(dec);
    free(out);
    ok(live == 0, "raw: close releases every allocation");
    ok(bad_free == 0, "raw: every free came from the provider");
    ok(peak <= 40000, "raw: peak allocation under 40 KB for 128x96");
    printf("  raw: peak %lu bytes\n", peak);
}

