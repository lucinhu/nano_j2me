static void test_demux_mini(void)
{
    nj_mp4 m;
    nj_mp4_sample s;
    int r;
    int i;
    int bad;

    ok(nj_mp4_open(&m, mini_mp4, (nj_u4)sizeof(mini_mp4)) == NJ_MP4_OK,
       "mini: open");
    ok(m.width == 128 && m.height == 96, "mini: dimensions from stsd");
    ok(m.timescale == 1000 && m.duration == 1000, "mini: mdhd timescale/duration");
    ok(m.sample_count == 2 && m.fps == 2, "mini: sample count and fps");
    ok(m.codec == NJ_MP4_CODEC_S263, "mini: s263 codec");
    ok(m.mdat_count == 1, "mini: one mdat");

    r = nj_mp4_next(&m, &s);
    ok(r == 1 && s.offset == 32 && s.size == 4 && s.dts == 0 &&
       s.duration == 500 && s.key == 1,
       "mini: first sample offset/size/dts/key");
    r = nj_mp4_next(&m, &s);
    ok(r == 1 && s.offset == 36 && s.size == 4 && s.dts == 500 &&
       s.duration == 500 && s.key == 1,
       "mini: second sample offset/size/dts/key");
    ok(nj_mp4_next(&m, &s) == 0, "mini: end of track");

    nj_mp4_rewind(&m);
    r = nj_mp4_next(&m, &s);
    ok(r == 1 && s.offset == 32 && s.dts == 0, "mini: rewind restarts");

    ok(nj_mp4_open(&m, mini_co64, (nj_u4)sizeof(mini_co64)) == NJ_MP4_OK,
       "co64: open");
    ok(m.stco64 == 1 && m.sample_count == 2, "co64: flagged and two samples");
    r = nj_mp4_next(&m, &s);
    ok(r == 1 && s.offset == 32 && s.size == 4 && s.dts == 0,
       "co64: first sample");
    r = nj_mp4_next(&m, &s);
    ok(r == 1 && s.offset == 36 && s.dts == 500, "co64: second sample");

    ok(nj_mp4_open(&m, mini_mp4v, (nj_u4)sizeof(mini_mp4v)) == NJ_MP4_OK &&
       m.codec == NJ_MP4_CODEC_MP4V,
       "mp4v: container parser still selects the track");

    /* Every truncation must either be refused or hand out only samples that
     * lie inside the bytes present.  This is the loader threat model: the
     * size field is hostile. */
    bad = 0;
    for (i = 1; i < (int)sizeof(mini_mp4); i++) {
        if (nj_mp4_open(&m, mini_mp4, (nj_u4)i) == NJ_MP4_OK) {
            int k;
            for (k = 0; k < 4; k++) {
                r = nj_mp4_next(&m, &s);
                if (r <= 0) {
                    break;
                }
                if (s.offset > (nj_u4)i || s.size > (nj_u4)i - s.offset) {
                    bad++;
                }
            }
            if (k == 4) {
                bad++;
            }
        }
    }
    ok(bad == 0, "mini: truncated files never expose bytes outside the buffer");

    ok(nj_mp4_open(&m, NULL, 0) != NJ_MP4_OK, "mini: NULL input refused");
    ok(nj_mp4_open(&m, mini_mp4, 7) != NJ_MP4_OK, "mini: seven bytes refused");
}

