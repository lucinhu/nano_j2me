/* ------------------------------------------------------------------ */
/* 1. Nothing draws before flush(), and flush() clears the queue      */
/* ------------------------------------------------------------------ */
static void test_deferred(nj_vm *vm)
{
    nj_ref img, g, g3, fl, fx, fig;

    g3 = scene_setup(vm, &img, &g);
    fl = centre_layout(vm);
    fx = default_effect(vm);
    fig = new_figure(vm, fix_mbac_tri_colored, sizeof fix_mbac_tri_colored);
    check(fig_layout(vm, fig, fl), "Figure.setLayout accepts a FigureLayout");

    check(render_fig(vm, g3, fig, 0, 0, fl, fx) == NJ_OK,
          "renderFigure() is accepted");
    check(pget(vm, img, 32, 32) == 0xFFFFFFFFu,
          "renderFigure draws nothing before flush (the reference defers)");
    check(field(vm, g3, G3D, "_count") > 0, "the deferred draw is queued");

    check(flush_g3(vm, g3) == NJ_OK, "flush() succeeds");
    check(pget(vm, img, 32, 32) == 0xFFFF0000u,
          "flush() draws the fixture's red triangle");
    check(field(vm, g3, G3D, "_count") == 0, "flush() clears the queue");

    /* The x/y arguments add to the layout centre (reference setCenter). */
    g3 = scene_setup(vm, &img, &g);
    check(render_fig(vm, g3, fig, 16, 0, fl, fx) == NJ_OK &&
          flush_g3(vm, g3) == NJ_OK,
          "a figure renders at a non-zero x offset");
    check(pget(vm, img, 48, 32) == 0xFFFF0000u,
          "the x argument shifts the figure by 16 pixels");
    check(pget(vm, img, 32, 32) == 0xFFFF0000u,
          "the shifted figure still covers the old centre column");
}

/* ------------------------------------------------------------------ */
/* 2. Submission order at equal depth, and the submit-time snapshot    */
/* ------------------------------------------------------------------ */
static void test_order_and_snapshot(nj_vm *vm)
{
    nj_ref img, g, g3, fl, fx, vp, red, blue;
    nj_s4 pv[3] = { 0, 0, 0 };
    nj_s4 cr[1] = { 0x00FF0000 };
    nj_s4 cb[1] = { 0x0000FF00 };

    g3 = scene_setup(vm, &img, &g);
    fl = centre_layout(vm);
    fx = default_effect(vm);
    vp = ints(vm, pv, 3);
    red = ints(vm, cr, 1);
    blue = ints(vm, cb, 1);

    /* Two points at the same place and depth: the later submission wins. */
    check(render_prims(vm, g3, 0, fl, fx, CMD_POINT_COLOUR, 1, vp, 0, 0, red,
                       0, 0) == NJ_OK,
          "a red point is queued");
    check(render_prims(vm, g3, 0, fl, fx, CMD_POINT_COLOUR, 1, vp, 0, 0, blue,
                       0, 0) == NJ_OK,
          "a blue point is queued on top of it");
    check(flush_g3(vm, g3) == NJ_OK, "flush red-then-blue");
    check(pget(vm, img, 32, 32) == 0xFF00FF00u,
          "the later queued primitive wins at equal depth");

    g3 = scene_setup(vm, &img, &g);
    check(render_prims(vm, g3, 0, fl, fx, CMD_POINT_COLOUR, 1, vp, 0, 0, blue,
                       0, 0) == NJ_OK &&
          render_prims(vm, g3, 0, fl, fx, CMD_POINT_COLOUR, 1, vp, 0, 0, red,
                       0, 0) == NJ_OK &&
          flush_g3(vm, g3) == NJ_OK,
          "blue then red: both queue and flush");
    check(pget(vm, img, 32, 32) == 0xFFFF0000u,
          "the reverse order shows the other colour");

    /* A figure queued later covers an earlier point at the same centre. */
    g3 = scene_setup(vm, &img, &g);
    {
        nj_ref fig = new_figure(vm, fix_mbac_tri_blue,
                                sizeof fix_mbac_tri_blue);

        (void)fig_layout(vm, fig, fl);
        check(render_prims(vm, g3, 0, fl, fx, CMD_POINT_COLOUR, 1, vp, 0, 0,
                           red, 0, 0) == NJ_OK &&
              render_fig(vm, g3, fig, 0, 0, fl, fx) == NJ_OK &&
              flush_g3(vm, g3) == NJ_OK,
              "a point then a figure queue and flush");
        check(pget(vm, img, 32, 32) == 0xFF0000FFu,
              "the figure submitted after the point covers it at equal depth");
    }

    /* Snapshot of the layout: renderPrimitives copies the drawing state at
     * submit time; changing the layout before flush must not move the draw. */
    g3 = scene_setup(vm, &img, &g);
    check(render_prims(vm, g3, 0, fl, fx, CMD_POINT_COLOUR, 1, vp, 0, 0, red,
                       0, 0) == NJ_OK,
          "a point is queued with the layout centre at (32,32)");
    {
        nj_value a[2];

        a[0].i = 0;
        a[1].i = 0;
        (void)call(vm, fl, FL, "setCenter", "(II)V", a, NULL);
    }
    check(flush_g3(vm, g3) == NJ_OK, "flush after the layout centre changed");
    check(pget(vm, img, 32, 32) == 0xFFFF0000u,
          "the queued point kept the submitted layout");
    {
        nj_value a[2];

        a[0].i = 32;
        a[1].i = 32;
        (void)call(vm, fl, FL, "setCenter", "(II)V", a, NULL);
    }

    /* Snapshot of the pose: Figure.setPattern() after renderFigure must not
     * change the queued draw either. */
    g3 = scene_setup(vm, &img, &g);
    {
        nj_ref fig = new_figure(vm, fix_mbac_quad_tex2_halves,
                                sizeof fix_mbac_quad_tex2_halves);
        nj_ref red_tex = texture(vm, 0, 1);
        nj_ref green_tex = texture(vm, 1, 1);
        nj_ref arr = nj_object_array_new(vm, "com/mascotcapsule/micro3d/v3/Texture", 2);
        nj_value a[1];

        if (arr) {
            nj_ref *slots = (nj_ref *)nj_array_data(arr);

            slots[0] = red_tex;
            slots[1] = green_tex;
        }
        (void)fig_layout(vm, fig, fl);
        a[0].r = arr;
        (void)call(vm, fig, FIG, "setTexture",
                   "([Lcom/mascotcapsule/micro3d/v3/Texture;)V", a, NULL);
        a[0].i = 0;
        (void)call(vm, fig, FIG, "setPattern", "(I)V", a, NULL);
        check(render_fig(vm, g3, fig, 0, 0, fl, fx) == NJ_OK,
              "a two-pattern figure is queued with pattern 0 selected");
        a[0].i = 2;
        (void)call(vm, fig, FIG, "setPattern", "(I)V", a, NULL);
        check(flush_g3(vm, g3) == NJ_OK, "flush after the pattern changed");
        check(pget(vm, img, 16, 32) == 0xFFFF0000u,
              "the queued draw kept pattern 0 (left half red)");
        check(pget(vm, img, 48, 32) == 0xFFFFFFFFu,
              "the queued draw did not pick up the later pattern 1");
    }
}

/* ------------------------------------------------------------------ */
/* 3. bind()/release() ownership of the target                         */
/* ------------------------------------------------------------------ */
static void test_bind_release(nj_vm *vm)
{
    nj_ref img, img2, g, g2, g3, fl, fx, fig;
    nj_status st;

    g3 = make(vm, G3D);
    fl = centre_layout(vm);
    fx = default_effect(vm);
    fig = new_figure(vm, fix_mbac_tri_colored, sizeof fix_mbac_tri_colored);
    (void)fig_layout(vm, fig, fl);

    st = render_fig(vm, g3, fig, 0, 0, fl, fx);
    expect_throw(vm, "renderFigure with no bound Graphics is IllegalStateException",
                 st, "IllegalStateException");

    check(target(vm, 64, 64, &img, &g), "a fresh target for bind");
    bind_g3(vm, g3, g);
    check(target(vm, 64, 64, &img2, &g2),
          "a second target for the double bind");
    {
        nj_value a[1];

        a[0].r = g2;
        st = nj_call(vm, g3, G3D, "bind", "(L" GFX ";)V", a, NULL);
    }
    expect_throw(vm, "binding an already bound Graphics3D is IllegalStateException",
                 st, "IllegalStateException");

    /* release() drops the queued work without drawing it. */
    check(render_fig(vm, g3, fig, 0, 0, fl, fx) == NJ_OK,
          "a figure is queued before release");
    release_g3(vm, g3, g);
    check(ref_field(vm, g3, G3D, "_g", "L" GFX ";") == 0,
          "release() forgets the target");
    check(field(vm, g3, G3D, "_count") == 0, "release() clears the queue");
    st = flush_g3(vm, g3);
    expect_throw(vm, "flush after release is IllegalStateException", st,
                 "IllegalStateException");
    check(pget(vm, img, 32, 32) == 0xFFFFFFFFu,
          "release() discarded the queued draw instead of drawing it");

    st = render_fig(vm, g3, fig, 0, 0, fl, fx);
    expect_throw(vm, "renderFigure after release is IllegalStateException", st,
                 "IllegalStateException");
}

