static void test_selection(nj_vm *vm)
{
    nj_ref img, g, g3, fl, fx, fig, red, green, arr;
    nj_value a[1];
    nj_status st;

    g3 = scene_setup(vm, &img, &g);
    fl = centre_layout(vm);
    fx = default_effect(vm);
    fig = new_figure(vm, fix_mbac_quad_tex2_halves,
                     sizeof fix_mbac_quad_tex2_halves);
    (void)fig_layout(vm, fig, fl);
    red = texture(vm, 0, 1);
    green = texture(vm, 1, 1);
    arr = tex_array(vm, red, green);

    /* Single-texture mode: only texture index 0 (the left quad) draws. */
    a[0].r = red;
    check(call(vm, fig, FIG, "setTexture",
               "(Lcom/mascotcapsule/micro3d/v3/Texture;)V", a, NULL),
          "setTexture(Texture) accepts a model texture");
    check(field(vm, fig, FIG, "_selected") == 0,
          "single-texture mode selects texture 0");
    a[0].i = 0;
    (void)call(vm, fig, FIG, "setPattern", "(I)V", a, NULL);
    check(render_fig(vm, g3, fig, 0, 0, fl, fx) == NJ_OK &&
          flush_g3(vm, g3) == NJ_OK,
          "pattern 0 renders with the single red texture");
    check(pget(vm, img, 16, 32) == 0xFFFF0000u,
          "the left half shows the selected red texture");
    check(pget(vm, img, 48, 32) == 0xFFFFFFFFu,
          "the right half is not drawn when only texture 0 is allowed");

    /* A different single texture still only reaches slot 1. */
    g3 = scene_setup(vm, &img, &g);
    a[0].r = green;
    (void)call(vm, fig, FIG, "setTexture",
               "(Lcom/mascotcapsule/micro3d/v3/Texture;)V", a, NULL);
    a[0].i = 0;
    (void)call(vm, fig, FIG, "setPattern", "(I)V", a, NULL);
    check(render_fig(vm, g3, fig, 0, 0, fl, fx) == NJ_OK &&
          flush_g3(vm, g3) == NJ_OK,
          "the same figure renders with the green single texture");
    check(pget(vm, img, 16, 32) == 0xFF00FF00u,
          "the left half follows the selected single texture");
    check(pget(vm, img, 48, 32) == 0xFFFFFFFFu,
          "selecting a single texture never draws the second textured slot");

    /* Array mode: pattern 0 draws the red left quad, pattern 1 the green
     * right quad (bit 1<<1 = 2 in the pattern mask). */
    g3 = scene_setup(vm, &img, &g);
    a[0].r = arr;
    check(call(vm, fig, FIG, "setTexture",
               "([Lcom/mascotcapsule/micro3d/v3/Texture;)V", a, NULL),
          "setTexture(Texture[]) accepts a texture array");
    check(field(vm, fig, FIG, "_selected") == -1,
          "array mode starts with no selected texture");
    a[0].i = 0;
    (void)call(vm, fig, FIG, "setPattern", "(I)V", a, NULL);
    check(render_fig(vm, g3, fig, 0, 0, fl, fx) == NJ_OK &&
          flush_g3(vm, g3) == NJ_OK,
          "pattern 0 renders with the red slot of the array");
    check(pget(vm, img, 16, 32) == 0xFFFF0000u &&
          pget(vm, img, 48, 32) == 0xFFFFFFFFu,
          "pattern 0 draws only the first textured group");

    g3 = scene_setup(vm, &img, &g);
    a[0].i = 2;
    (void)call(vm, fig, FIG, "setPattern", "(I)V", a, NULL);
    check(render_fig(vm, g3, fig, 0, 0, fl, fx) == NJ_OK &&
          flush_g3(vm, g3) == NJ_OK,
          "pattern 2 renders with both textured groups in array mode");
    check(pget(vm, img, 16, 32) == 0xFFFF0000u &&
          pget(vm, img, 48, 32) == 0xFF00FF00u,
          "pattern 2 adds the green second textured group");

    /* selectTexture() picks an array entry for the single-texture path. */
    g3 = scene_setup(vm, &img, &g);
    a[0].i = 1;
    st = nj_call(vm, fig, FIG, "selectTexture", "(I)V", a, NULL);
    check(st == NJ_OK && field(vm, fig, FIG, "_selected") == 1,
          "selectTexture(1) selects the green array entry");
    check(render_fig(vm, g3, fig, 0, 0, fl, fx) == NJ_OK &&
          flush_g3(vm, g3) == NJ_OK,
          "the figure renders with the selected array entry");
    check(pget(vm, img, 16, 32) == 0xFF00FF00u &&
          pget(vm, img, 48, 32) == 0xFFFFFFFFu,
          "the selected entry feeds the first textured slot only");

    a[0].i = 2;
    st = nj_call(vm, fig, FIG, "selectTexture", "(I)V", a, NULL);
    expect_throw(vm, "selectTexture out of range is IllegalArgumentException",
                 st, "IllegalArgumentException");

    /* getTexture/getNumTextures reflect the mode. */
    {
        nj_value ret;

        check(nj_call(vm, fig, FIG, "getNumTextures", "()I", NULL, &ret) == NJ_OK &&
              ret.i == 2, "array mode reports both textures");
        a[0].r = 0;
        a[0].i = 0;
        check(nj_call(vm, fig, FIG, "getTexture", "()Lcom/mascotcapsule/micro3d/v3/Texture;",
                      NULL, &ret) == NJ_OK && ret.r == green,
              "getTexture returns the selected array entry");
    }
    /* A disposed texture in the array is rejected when the draw is submitted. */
    g3 = scene_setup(vm, &img, &g);
    red = texture(vm, 0, 1);
    green = texture(vm, 1, 1);
    arr = tex_array(vm, red, green);
    a[0].r = arr;
    (void)call(vm, fig, FIG, "setTexture",
               "([Lcom/mascotcapsule/micro3d/v3/Texture;)V", a, NULL);
    (void)call(vm, green, TEX, "dispose", "()V", NULL, NULL);
    st = render_fig(vm, g3, fig, 0, 0, fl, fx);
    expect_throw(vm, "renderFigure with a disposed texture is IllegalStateException",
                 st, "IllegalStateException");
}

static void test_posture(nj_vm *vm)
{
    nj_ref img, g, g3, fl, fx, fig, at, red, green, arr;
    nj_value a[3], ret;
    nj_status st;

    a[0].r = 0;
    a[1].i = 0;
    a[2].i = 0;
    g3 = scene_setup(vm, &img, &g);
    fl = centre_layout(vm);
    fx = default_effect(vm);
    fig = new_figure(vm, fix_mbac_quad_tex2_halves,
                     sizeof fix_mbac_quad_tex2_halves);
    (void)fig_layout(vm, fig, fl);
    red = texture(vm, 0, 1);
    green = texture(vm, 1, 1);
    arr = tex_array(vm, red, green);
    a[0].r = arr;
    (void)call(vm, fig, FIG, "setTexture",
               "([Lcom/mascotcapsule/micro3d/v3/Texture;)V", a, NULL);

    at = make(vm, AT);
    {
        nj_ref data = r7_bytes(vm, fix_mtra_two, sizeof fix_mtra_two);

        a[0].r = data;
        check(call(vm, at, AT, "<init>", "([B)V", a, &ret),
              "ActionTable(byte[]) accepts the tiny MTRA fixture");
    }

    a[0].r = at;
    a[1].i = 0;
    a[2].i = 0;
    check(call(vm, fig, FIG, "setPosture",
               "(L" AT ";II)V", a, NULL),
          "setPosture(action 0, frame 0) is accepted");
    check(field(vm, fig, FIG, "_a") == 0 && field(vm, fig, FIG, "_b") == 0 &&
          field(vm, fig, FIG, "_pattern") == 0,
          "posture stores action/frame and the frame-0 pattern");
    check(render_fig(vm, g3, fig, 0, 0, fl, fx) == NJ_OK &&
          flush_g3(vm, g3) == NJ_OK,
          "the posed figure renders");
    check(pget(vm, img, 16, 32) == 0xFFFF0000u &&
          pget(vm, img, 48, 32) == 0xFFFFFFFFu,
          "frame 0 selects only the first pattern group");

    /* Frame 5 of the rotation curve has a dynamic pattern key = 2. */
    g3 = scene_setup(vm, &img, &g);
    a[0].r = at;
    a[1].i = 0;
    a[2].i = 5 * 65536;
    (void)call(vm, fig, FIG, "setPosture", "(L" AT ";II)V", a, NULL);
    check(field(vm, fig, FIG, "_b") == 5 * 65536 &&
          field(vm, fig, FIG, "_pattern") == 2,
          "the dynamic pattern key flips the figure to pattern 2");
    check(render_fig(vm, g3, fig, 0, 0, fl, fx) == NJ_OK &&
          flush_g3(vm, g3) == NJ_OK,
          "the animated frame renders");
    check(pget(vm, img, 16, 32) == 0xFFFF0000u &&
          pget(vm, img, 48, 32) == 0xFF00FF00u,
          "the dynamic pattern reaches both textured groups");

    /* A negative frame is clamped to zero by the reference setPosture. */
    a[0].r = at;
    a[1].i = 0;
    a[2].i = -7;
    (void)call(vm, fig, FIG, "setPosture", "(L" AT ";II)V", a, NULL);
    check(field(vm, fig, FIG, "_b") == 0 && field(vm, fig, FIG, "_pattern") == 0,
          "a negative frame clamps to 0 and the frame-0 pattern");

    /* Action 1 translates the model off screen: the frame counts differ. */
    g3 = scene_setup(vm, &img, &g);
    a[0].r = at;
    a[1].i = 1;
    a[2].i = 0;
    (void)call(vm, fig, FIG, "setPosture", "(L" AT ";II)V", a, NULL);
    check(render_fig(vm, g3, fig, 0, 0, fl, fx) == NJ_OK &&
          flush_g3(vm, g3) == NJ_OK,
          "the second action renders");
    check(pget(vm, img, 16, 32) == 0xFFFFFFFFu &&
          pget(vm, img, 48, 32) == 0xFFFFFFFFu,
          "the second action's translation puts the model off screen");

    /* Errors. */
    a[0].r = 0;
    a[1].i = 0;
    a[2].i = 0;
    st = nj_call(vm, fig, FIG, "setPosture", "(L" AT ";II)V", a, NULL);
    expect_throw(vm, "setPosture(null table) is NullPointerException", st,
                 "NullPointerException");
    a[0].r = at;
    a[1].i = 9;
    a[2].i = 0;
    st = nj_call(vm, fig, FIG, "setPosture", "(L" AT ";II)V", a, NULL);
    expect_throw(vm, "setPosture with a bad action is IllegalArgumentException",
                 st, "IllegalArgumentException");

    /* The frame count comes from the MTRA data and is 16.16. */
    memset(a, 0, sizeof a);
    a[0].i = 0;
    (void)nj_call(vm, at, AT, "getNumFrames", "(I)I", a, &ret);
    check(ret.i == 655360, "ActionTable reports 10 frames as 655360");
    a[0].i = 1;
    (void)nj_call(vm, at, AT, "getNumFrames", "(I)I", a, &ret);
    check(ret.i == 196608, "the second action reports 3 frames as 196608");

    (void)call(vm, at, AT, "dispose", "()V", NULL, NULL);
    a[0].r = at;
    a[1].i = 0;
    a[2].i = 0;
    st = nj_call(vm, fig, FIG, "setPosture", "(L" AT ";II)V", a, NULL);
    expect_throw(vm, "setPosture after ActionTable.dispose is IllegalStateException",
                 st, "IllegalStateException");
}

static void test_textured_primitive(nj_vm *vm)
{
    nj_ref img, g, g3, fl, fx, tex, verts, uvs, colors, ck, qverts, quvs;
    nj_s4 tv[9] = { -2048, -2048, 0, 2048, -2048, 0, 0, 2048, 0 };
    /* Raw texture coordinates are texel indices, not 12.12 fractions. */
    nj_s4 uv[6] = { 0, 0, 8, 0, 0, 8 };
    nj_s4 qv[12] = { -2048, -2048, 0, 2048, -2048, 0, 2048, 2048, 0,
                     -2048, 2048, 0 };
    nj_s4 quv[12] = { 0, 0, 8, 0, 8, 8, 0, 8 };
    nj_s4 tc[1] = { 0x0000FF00 };
    nj_value a[2];

    g3 = scene_setup(vm, &img, &g);
    fl = centre_layout(vm);
    fx = default_effect(vm);
    tex = texture(vm, 0, 1);
    verts = ints(vm, tv, 9);
    uvs = ints(vm, uv, 6);
    colors = ints(vm, tc, 1);

    check(render_prims(vm, g3, tex, fl, fx, CMD_TRI_TEXTURE, 1, verts, 0, uvs,
                       colors, 0, 0) == NJ_OK,
          "a textured triangle is accepted");
    check(pget(vm, img, 32, 32) == 0xFFFFFFFFu,
          "the textured triangle draws nothing before flush");
    check(flush_g3(vm, g3) == NJ_OK, "flush draws the textured triangle");
    check(pget(vm, img, 32, 32) == 0xFFFF0000u,
          "the texture's red reaches the framebuffer");
    check(pget(vm, img, 40, 40) == 0xFFFF0000u,
          "the interior samples the bitmap, not a flat filler");

    /* A later textured draw covers an earlier solid one at equal depth. */
    g3 = scene_setup(vm, &img, &g);
    {
        nj_s4 bc[1] = { 0x0000FF00 };
        nj_ref blue = ints(vm, bc, 1);

        check(render_prims(vm, g3, 0, fl, fx, CMD_TRI_COLOUR, 1, verts, 0, 0,
                           blue, 0, 0) == NJ_OK &&
              render_prims(vm, g3, tex, fl, fx, CMD_TRI_TEXTURE, 1, verts, 0,
                           uvs, colors, 0, 0) == NJ_OK &&
              flush_g3(vm, g3) == NJ_OK,
              "a solid then a textured triangle queue and flush");
        check(pget(vm, img, 32, 32) == 0xFFFF0000u,
              "the later textured draw wins over the earlier solid one");
    }

    /* Colorkey: the fixture's left half is red, the right half index 0
     * (black), which the colorkey command bit makes transparent. */
    g3 = scene_setup(vm, &img, &g);
    ck = colorkey_texture(vm);
    qverts = ints(vm, qv, 12);
    quvs = ints(vm, quv, 12);
    a[0].i = 0;
    (void)call(vm, fl, FL, "setCenter", "(II)V", a, NULL);
    a[0].i = 32;
    a[1].i = 32;
    (void)call(vm, fl, FL, "setCenter", "(II)V", a, NULL);
    check(render_prims(vm, g3, ck, fl, fx, CMD_QUAD_TEXTURE | CMD_COLORKEY, 1,
                       qverts, 0, quvs, colors, 0, 0) == NJ_OK &&
          flush_g3(vm, g3) == NJ_OK,
          "a colorkey quad renders");
    check(pget(vm, img, 8, 32) == 0xFFFF0000u,
          "the colorkey quad keeps the red texels");
    check(pget(vm, img, 56, 32) == 0xFFFFFFFFu,
          "the black texels of a colorkey texture stay transparent");
}

/* ------------------------------------------------------------------ */
/* 8. Lines are depth-sorted after the near/far clip (not before)      */
/* ------------------------------------------------------------------ */
static void test_line_clip_depth(nj_vm *vm)
{
    nj_ref img, g, g3, fl, fx, a_verts, b_verts, red, blue;
    nj_value a[4];
    nj_status st;

    g3 = scene_setup(vm, &img, &g);
    fl = centre_layout(vm);
    fx = default_effect(vm);
    /* near=64, far=1000, angle=512 -> kx=(int)(64*0.5/tan(pi/8))=77. */
    a[0].i = 64;
    a[1].i = 1000;
    a[2].i = 512;
    (void)call(vm, fl, FL, "setPerspective", "(III)V", a, NULL);
    a[0].i = 32;
    a[1].i = 32;
    (void)call(vm, fl, FL, "setCenter", "(II)V", a, NULL);

    /*
     * B is a blue horizontal line entirely inside the view volume at z=800,
     * so its sort depth is 800.  A is a red line from z=32 (behind the near
     * plane) to z=2000 (beyond far): its unclipped average depth would be
     * 1016 (farther than B), but the reference sorts lines after clipping
     * (Graphics3D.java:2194), where A spans z=64..1000 and sorts at 532 -
     * nearer than B.  A must therefore be drawn last and win the shared
     * pixels; sorting before the clamp draws B last and leaves them blue.
     */
    {
        nj_s4 av[6] = { -20, 0, 32, -20, 0, 2000 };
        nj_s4 bv[6] = { -400, 0, 800, 400, 0, 800 };
        nj_s4 rc[1] = { 0x00FF0000 };
        nj_s4 bc[1] = { 0x000000FF };

        a_verts = ints(vm, av, 6);
        b_verts = ints(vm, bv, 6);
        red = ints(vm, rc, 1);
        blue = ints(vm, bc, 1);
        st = render_prims(vm, g3, 0, fl, fx, 0x02000400, 1, b_verts, 0, 0,
                          blue, 0, 0);
        check(st == NJ_OK, "the blue reference line queues");
        st = render_prims(vm, g3, 0, fl, fx, 0x02000400, 1, a_verts, 0, 0,
                          red, 0, 0);
        check(st == NJ_OK, "the red line spanning both clip planes queues");
        check(flush_g3(vm, g3) == NJ_OK, "the two lines flush together");
        check(pget(vm, img, 16, 32) == 0xFFFF0000u,
              "the clipped line's (64+1000)/2 depth makes it the nearer line");
        check(pget(vm, img, 2, 32) == 0xFF0000FFu,
              "outside the clipped red segment only the blue line covers the row");
    }
}

/* ------------------------------------------------------------------ */
/* 9. GC and lifetime: the queue owns a snapshot, not the objects      */
/* ------------------------------------------------------------------ */
static void test_gc_lifetime(nj_vm *vm)
{
    nj_ref img, g, g3, fl, fx, fig, red, green, arr, data;
    nj_u4 mark;

    g3 = scene_setup(vm, &img, &g);
    fl = centre_layout(vm);
    fx = default_effect(vm);
    red = texture(vm, 0, 1);
    green = texture(vm, 1, 1);
    arr = tex_array(vm, red, green);
    data = r7_bytes(vm, fix_mbac_quad_tex2_halves,
                    sizeof fix_mbac_quad_tex2_halves);
    fig = make(vm, FIG);
    {
        nj_value a[1], ret;

        a[0].r = data;
        (void)call(vm, fig, FIG, "<init>", "([B)V", a, &ret);
    }
    (void)fig_layout(vm, fig, fl);
    {
        nj_value a[1];

        a[0].r = arr;
        (void)call(vm, fig, FIG, "setTexture",
                   "([Lcom/mascotcapsule/micro3d/v3/Texture;)V", a, NULL);
        a[0].i = 0;
        (void)call(vm, fig, FIG, "setPattern", "(I)V", a, NULL);
    }
    check(render_fig(vm, g3, fig, 0, 0, fl, fx) == NJ_OK,
          "the figure reference is queued before its objects are dropped");

    /* Drop and dispose everything the queue was not supposed to keep. */
    (void)call(vm, fig, FIG, "dispose", "()V", NULL, NULL);
    (void)call(vm, red, TEX, "dispose", "()V", NULL, NULL);
    (void)call(vm, green, TEX, "dispose", "()V", NULL, NULL);
    data = 0;
    fig = 0;
    red = 0;
    green = 0;
    arr = 0;

    /* The VM's normal C test harness keeps objects in C variables, not roots;
     * root the scene objects that must survive the explicit collection. */
    mark = nj_root_mark(vm);
    nj_root(vm, g3);
    nj_root(vm, img);
    nj_root(vm, g);
    nj_root(vm, fl);
    nj_root(vm, fx);
    nj_gc_collect(vm);

    check(flush_g3(vm, g3) == NJ_OK, "flush after GC of the submitted objects");
    check(pget(vm, img, 16, 32) == 0xFFFF0000u,
          "the queued figure still draws from its snapshot after dispose+GC");
    check(pget(vm, img, 48, 32) == 0xFFFFFFFFu,
          "the GC'd pattern-1 half is still not part of the queued draw");
    nj_root_release(vm, mark);

    /* Primitive argument arrays are also snapshotted at submit time. */
    g3 = scene_setup(vm, &img, &g);
    {
        nj_s4 tv[9] = { -2048, -2048, 0, 2048, -2048, 0, 0, 2048, 0 };
        nj_s4 uv[6] = { 0, 0, 4096, 0, 0, 4096 };
        nj_s4 tc[1] = { 0x0000FF00 };
        nj_ref tex = texture(vm, 0, 1);
        nj_ref verts = ints(vm, tv, 9);
        nj_ref uvs = ints(vm, uv, 6);
        nj_ref colors = ints(vm, tc, 1);

        check(render_prims(vm, g3, tex, fl, fx, CMD_TRI_TEXTURE, 1, verts, 0,
                           uvs, colors, 0, 0) == NJ_OK,
              "a textured triangle is queued");
        verts = 0;
        uvs = 0;
        colors = 0;
        tex = 0;
        mark = nj_root_mark(vm);
        nj_root(vm, g3);
        nj_root(vm, img);
        nj_root(vm, g);
        nj_root(vm, fl);
        nj_root(vm, fx);
        nj_gc_collect(vm);
        check(flush_g3(vm, g3) == NJ_OK,
              "flush after GC of the primitive argument arrays");
        check(pget(vm, img, 32, 32) == 0xFFFF0000u,
              "the queued primitive still draws after its arguments were dropped");
        nj_root_release(vm, mark);
    }

    /* The Figure constructor must root its decoded copy: dropping the source
     * byte[] and collecting must leave the figure usable. */
    g3 = scene_setup(vm, &img, &g);
    {
        nj_ref data2 = r7_bytes(vm, fix_mbac_tri_colored,
                                sizeof fix_mbac_tri_colored);
        nj_ref fig2 = make(vm, FIG);
        nj_value a[1], ret;

        a[0].r = data2;
        (void)call(vm, fig2, FIG, "<init>", "([B)V", a, &ret);
        mark = nj_root_mark(vm);
        nj_root(vm, g3);
        nj_root(vm, img);
        nj_root(vm, g);
        nj_root(vm, fl);
        nj_root(vm, fx);
        nj_root(vm, fig2);
        data2 = 0;
        nj_gc_collect(vm);
        check(render_fig(vm, g3, fig2, 0, 0, fl, fx) == NJ_OK &&
              flush_g3(vm, g3) == NJ_OK,
              "a figure built from byte[] renders after its source array is GC'd");
        check(pget(vm, img, 32, 32) == 0xFFFF0000u,
              "the constructor-rooted fixture still draws red after GC");
        nj_root_release(vm, mark);
    }
}

int main(void)
{
    nj_port port;
    nj_vm *vm;

    nj_port_headless(&port);
    vm = nj_vm_create(&port, 2u * 1024u * 1024u);
    if (!vm) {
        printf("tests/test_mascot_scene: could not create a VM\n");
        return 1;
    }

    test_deferred(vm);
    test_order_and_snapshot(vm);
    test_bind_release(vm);
    test_figure_errors(vm);
    test_selection(vm);
    test_posture(vm);
    test_textured_primitive(vm);
    test_line_clip_depth(vm);
    test_gc_lifetime(vm);

    nj_vm_destroy(vm);
    nj_port_shutdown(&port);

    printf("%d checks, %d failures\n", checks, failures);
    return failures ? 1 : 0;
}

