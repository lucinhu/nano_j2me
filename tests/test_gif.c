static unsigned pixel_at(const nj_image *img, int x, int y)
{
    return img->pixels[(nj_size)y * (nj_size)img->width + (nj_size)x];
}

static unsigned rgb_at(const nj_image *img, int x, int y)
{
    return pixel_at(img, x, y) & 0x00FFFFFFu;
}

static unsigned alpha_at(const nj_image *img, int x, int y)
{
    return (pixel_at(img, x, y) >> 24) & 0xFFu;
}

