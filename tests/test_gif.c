static const unsigned k_pal4[4] = { 0xFF0000u, 0x00FF00u, 0x0000FFu, 0xFFFFFFu };

/* ------------------------------------------------------------------ */
/* 1. A plain GIF87a, every pixel                                      */
/* ------------------------------------------------------------------ */
static void test_plain(void)
{
    const char *err = "untouched";
    nj_image *img = nj_gif_decode(k_gif87, (nj_u4)sizeof(k_gif87),
                                  count_alloc, NULL, count_free, &err);
    int x;
    int y;

    CHECK(img != NULL, "a GIF87a decodes");
    if (!img) {
        printf("  (error: %s)\n", err ? err : "?");
        return;
    }
    CHECK_EQ(img->width, 4, "width comes from the logical screen");
    CHECK_EQ(img->height, 3, "height comes from the logical screen");
    CHECK_EQ(img->format, NJ_PIXFMT_ARGB8888,
             "a GIF decodes to ARGB8888, so transparency survives");
    CHECK(img->has_alpha, "and the image says so");
    for (y = 0; y < 3; y++) {
        for (x = 0; x < 4; x++) {
            unsigned want = k_pal4[(x + y) % 4];
            CHECK_EQ(rgb_at(img, x, y), want, "palette index maps to its colour");
            CHECK_EQ(alpha_at(img, x, y), 0xFFu, "an opaque pixel is opaque");
        }
    }
    release_image(img);
    CHECK_EQ(live_blocks, 0, "a successful decode releases everything it took");
}

/* ------------------------------------------------------------------ */
/* 2. Transparency is alpha, not a colour                              */
/* ------------------------------------------------------------------ */
static void test_transparent(void)
{
    nj_image *img = nj_gif_decode(k_gif89_transparent,
                                  (nj_u4)sizeof(k_gif89_transparent),
                                  count_alloc, NULL, count_free, NULL);
    int y;

    CHECK(img != NULL, "a GIF89a with a transparent index decodes");
    if (!img) {
        return;
    }
    for (y = 0; y < 3; y++) {
        CHECK_EQ(alpha_at(img, 0, y), 0u, "the transparent index is alpha 0");
        CHECK_EQ(pixel_at(img, 0, y), 0u, "and carries no colour");
        CHECK_EQ(alpha_at(img, 1, y), 0xFFu, "the next column is opaque");
    }
    CHECK_EQ(rgb_at(img, 1, 0), k_pal4[1], "the colours around it are right");
    release_image(img);
    CHECK_EQ(live_blocks, 0, "a transparent decode releases everything");
}

/* ------------------------------------------------------------------ */
/* 3. Interlacing: every row must land on its real row                 */
/* ------------------------------------------------------------------ */
/* The fixture's palette entry v is (v, 255-v, 3v), and pixel (x,y) is
 * index y*16+x - so a permuted row is immediately visible. */
static void test_interlaced(void)
{
    nj_image *img = nj_gif_decode(k_gif_interlaced,
                                  (nj_u4)sizeof(k_gif_interlaced),
                                  count_alloc, NULL, count_free, NULL);
    int y;

    CHECK(img != NULL, "an interlaced GIF decodes");
    if (!img) {
        return;
    }
    CHECK_EQ(img->width, 16, "interlaced width");
    CHECK_EQ(img->height, 16, "interlaced height");
    for (y = 0; y < 16; y++) {
        unsigned idx = (unsigned)(y * 16);
        unsigned want = ((idx & 0xFFu) << 16) |
                        (((255u - idx) & 0xFFu) << 8) |
                        ((idx * 3u) & 0xFFu);
        int x;
        CHECK_EQ(rgb_at(img, 0, y), want, "interlaced row lands where it belongs");
        for (x = 1; x < 16; x++) {
            unsigned j = idx + (unsigned)x;
            unsigned want2 = ((j & 0xFFu) << 16) |
                             (((255u - j) & 0xFFu) << 8) |
                             ((j * 3u) & 0xFFu);
            if (rgb_at(img, x, y) != want2) {
                break;
            }
        }
        CHECK_EQ(x, 16, "every pixel of the row is in place");
    }
    release_image(img);
    CHECK_EQ(live_blocks, 0, "an interlaced decode releases everything");
}

/* ------------------------------------------------------------------ */
/* 4. An animated GIF contributes its first frame                      */
/* ------------------------------------------------------------------ */
static void test_animated(void)
{
    nj_image *img = nj_gif_decode(k_gif_animated,
                                  (nj_u4)sizeof(k_gif_animated),
                                  count_alloc, NULL, count_free, NULL);
    int i;

    CHECK(img != NULL, "an animated GIF decodes");
    if (!img) {
        return;
    }
    CHECK_EQ(img->width, 8, "animated width");
    CHECK_EQ(img->height, 8, "animated height");
    for (i = 0; i < 64; i++) {
        if (rgb_at(img, i % 8, i / 8) != k_pal4[1]) {
            break;
        }
    }
    CHECK_EQ(i, 64, "only the first frame is drawn, not the second");
    release_image(img);
}

/* ------------------------------------------------------------------ */
/* 5. The provider claims exactly GIF                                  */
/* ------------------------------------------------------------------ */
static void test_provider(void)
{
    nj_image_info info;

    CHECK(nj_codec_gif_software.name != NULL, "the provider is named");
    CHECK((nj_codec_gif_software.caps.formats & NJ_CODEC_FMT_GIF) != 0u,
          "the provider advertises GIF");
    CHECK(nj_codec_gif_software.accepts(k_gif87, (nj_u4)sizeof(k_gif87)) != 0,
          "accepts() takes a GIF87a");
    CHECK(nj_codec_gif_software.accepts(k_gif89_transparent,
                                        (nj_u4)sizeof(k_gif89_transparent)) != 0,
          "accepts() takes a GIF89a");
    CHECK(nj_codec_gif_software.accepts("GIF8", 4u) == 0,
          "a truncated signature is not a GIF");
    CHECK(nj_gif_decode("GIF89a", 6u, count_alloc, NULL, count_free, NULL) == NULL,
          "a bare signature with no header is not a decodable image");

    memset(&info, 0, sizeof(info));
    CHECK_EQ(nj_codec_gif_software.info(k_gif87, (nj_u4)sizeof(k_gif87), &info),
             NJ_OK, "info() reads the header without decoding");
    CHECK_EQ(info.width, 4, "info() width");
    CHECK_EQ(info.height, 3, "info() height");
    CHECK_EQ(info.format, NJ_CODEC_FMT_GIF, "info() reports the format");
}

/* ------------------------------------------------------------------ */
/* 6. Malformed input: no crash, no half-built image, no leak          */
/* ------------------------------------------------------------------ */
static void test_malformed(void)
{
    static const unsigned char not_a_gif[] = { 'P', 'N', 'G', 0x0Du, 0x0Au };
    const char *err;
    nj_image *img;
    nj_u4 cut;

    err = "untouched";
    img = nj_gif_decode(not_a_gif, (nj_u4)sizeof(not_a_gif),
                        count_alloc, NULL, count_free, &err);
    CHECK(img == NULL, "a PNG is refused, not mis-parsed");
    CHECK(err != NULL && strcmp(err, "untouched") != 0,
          "and the refusal explains itself");

    CHECK(nj_gif_decode(k_gif87, 0u, count_alloc, NULL, count_free, &err) == NULL,
          "an empty buffer is refused");
    CHECK(nj_gif_decode(NULL, 0u, count_alloc, NULL, count_free, &err) == NULL,
          "a NULL buffer is refused");

    /* Every truncation of both fixtures, including inside the LZW stream. */
    for (cut = 0u; cut < (nj_u4)sizeof(k_gif87); cut++) {
        img = nj_gif_decode(k_gif87, cut, count_alloc, NULL, count_free, &err);
        if (img) {
            CHECK_EQ(img->width, 4, "a truncation that decodes is still well formed");
            CHECK_EQ(img->height, 3, "a truncation that decodes is still well formed");
            release_image(img);
        } else if (cut < 13u) {
            CHECK(err != NULL, "a truncated header is refused with a message");
        }
    }
    for (cut = 0u; cut < (nj_u4)sizeof(k_gif_interlaced); cut++) {
        img = nj_gif_decode(k_gif_interlaced, cut, count_alloc, NULL, count_free, &err);
        if (img) {
            CHECK_EQ(img->width, 16, "a truncated interlaced GIF is well formed");
            release_image(img);
        }
    }

    /* One corrupted byte at a time: never a crash, never a bad image. */
    {
        unsigned char buf[sizeof(k_gif_interlaced)];
        nj_u4 i;
        for (i = 13u; i < (nj_u4)sizeof(k_gif_interlaced); i++) {
            memcpy(buf, k_gif_interlaced, sizeof(buf));
            buf[i] = (unsigned char)(buf[i] ^ 0x5Au);
            img = nj_gif_decode(buf, (nj_u4)sizeof(buf), count_alloc, NULL,
                                count_free, &err);
            if (img) {
                CHECK_EQ(img->width, 16, "a corrupted GIF never yields a wrong size");
                CHECK_EQ(img->height, 16, "a corrupted GIF never yields a wrong size");
                release_image(img);
            }
        }
    }

    CHECK_EQ(live_blocks, 0, "no failed decode leaks a block");
}

int main(void)
{
    test_plain();
    test_transparent();
    test_interlaced();
    test_animated();
    test_provider();
    test_malformed();

    printf("test_gif: %d checks, %d failures\n", checks, failures);
    printf("%s\n", failures == 0 ? "PASS" : "FAIL");
    return failures == 0 ? 0 : 1;
}
