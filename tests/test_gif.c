/*
 * nano_j2me - tests/test_gif.c
 *
 * The built-in GIF decoder.
 *
 * MIDP 1.0 required GIF and MIDP 2.0 kept it, but a MIDlet that cannot decode
 * its own artwork usually swallows the IOException and carries on painting a
 * null Image - which reads as a black screen rather than as an error.  That is
 * exactly how the missing decoder showed up, so this test pins the contract:
 *
 *   - a GIF87a, a GIF89a with a transparent index and an interlaced GIF all
 *     decode to the pixels the file describes (interlacing is the case where
 *     a row-mapping mistake turns the picture into a scrambled one, so every
 *     row of that fixture is checked);
 *   - only the FIRST frame of an animated GIF is used;
 *   - the transparent index becomes alpha=0, everything else alpha=0xFF;
 *   - the provider claims only what it can read: accepts() answers for
 *     GIF87a/GIF89a and refuses anything else, including a PNG;
 *   - malformed input (empty, truncated, corrupted) returns NULL with a
 *     message, never a half-built image, and never crashes;
 *   - every block the decoder takes through its hooks is handed back, so a
 *     failed decode does not leak.
 *
 * Usage: test_gif
 */
#include "nj2me/nj.h"

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

static int checks;
static int failures;

#define CHECK(cond, what)                                                    \
    do {                                                                     \
        checks++;                                                            \
        if (!(cond)) {                                                       \
            failures++;                                                      \
            printf("  FAIL %s:%d  %s\n", __FILE__, __LINE__, (what));        \
        }                                                                    \
    } while (0)

#define CHECK_EQ(a, b, what)                                                 \
    do {                                                                     \
        long va_ = (long)(a);                                                \
        long vb_ = (long)(b);                                                \
        checks++;                                                            \
        if (va_ != vb_) {                                                    \
            failures++;                                                      \
            printf("  FAIL %s:%d  %s (%ld != %ld)\n",                        \
                   __FILE__, __LINE__, (what), va_, vb_);                    \
        }                                                                    \
    } while (0)

/* ------------------------------------------------------------------ */
/* A counting allocator, so a decode that forgets to free is visible    */
/* ------------------------------------------------------------------ */
static int live_blocks;

static void *count_alloc(void *ud, nj_size n)
{
    void *p;
    (void)ud;
    p = malloc((size_t)n);
    if (p) {
        live_blocks++;
    }
    return p;
}

static void count_free(void *ud, void *p)
{
    (void)ud;
    if (p) {
        live_blocks--;
    }
    free(p);
}

/* The decoder allocates the pixel buffer and the nj_image through the hooks,
 * so releasing means giving both back to the same allocator. */
static void release_image(nj_image *img)
{
    if (!img) {
        return;
    }
    count_free(NULL, img->pixels);
    count_free(NULL, img);
}

