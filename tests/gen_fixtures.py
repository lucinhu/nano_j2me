# DEFLATE fixtures
# ----------------------------------------------------------------------

def build_inflate_fixtures():
    raw = raw_deflate(INFLATE_SRC, 9)
    assert (raw[0] >> 1) & 3 == 2, "raw fixture is not a dynamic-Huffman block"
    write_file("raw.bin", raw)
    write_file("raw.expected", INFLATE_SRC)

    fixed = raw_deflate(INFLATE_SRC, 9, zlib.Z_FIXED)
    assert (fixed[0] >> 1) & 3 == 1, "fixed fixture is not a fixed-Huffman block"
    write_file("fixed.bin", fixed)
    write_file("fixed.expected", INFLATE_SRC)

    zl = zlib.compress(INFLATE_SRC, 9)
    assert zl[:1] == b"\x78" and (zl[0] << 8 | zl[1]) % 31 == 0
    write_file("zlib.bin", zl)
    write_file("zlib.expected", INFLATE_SRC)

    # Hand-built stream of stored blocks with odd sizes, so the reader has to
    # realign to a byte boundary before every LEN/NLEN pair.
    chunks = [b"stored block one, 13b", bytes(range(256)) * 2 + b"\x01\x02\x03",
              b"the third and final stored block"]
    w = BitWriter()
    for i, chunk in enumerate(chunks):
        w.write(1 if i == len(chunks) - 1 else 0, 1)
        w.write(0, 2)                     # BTYPE = stored
        w.align()
        w.write(len(chunk) & 0xFFFF, 16)
        w.write((~len(chunk)) & 0xFFFF, 16)
        for byte in chunk:
            w.write(byte, 8)
    stored = w.bytes()
    assert b"".join(chunks) == zlib.decompress(stored, -15)
    write_file("stored.bin", stored)
    write_file("stored.expected", b"".join(chunks))

    # A valid stream that produces nothing at all: BFINAL=1, fixed, EOB.
    w = BitWriter()
    w.write(1, 1)
    w.write(1, 2)
    w.write_code(0, 7)                    # end-of-block symbol 256
    empty = w.bytes()
    assert zlib.decompress(empty, -15) == b""
    write_file("empty_raw.bin", empty)
    write_file("empty.expected", b"")


def build_adversarial_fixtures():
    # (a) fixed-Huffman block: one literal, then a match with distance 5 while
    #     only one byte of output exists.
    w = BitWriter()
    w.write(1, 1)                         # BFINAL
    w.write(1, 2)                         # BTYPE = fixed Huffman
    w.write_code(0x30 + ord("A"), 8)      # literal 'A'
    w.write_code(257 - 256, 7)            # length symbol 257 -> length 3
    w.write_code(4, 5)                    # distance symbol 4 -> distance 5
    w.write_code(0, 7)                    # end of block
    bad_distance = w.bytes()
    try:
        zlib.decompress(bad_distance, -15)
        raise AssertionError("invalid-distance fixture decoded successfully")
    except zlib.error:
        pass
    write_file("bad_distance.bin", bad_distance)

    # Reserved block type 3.
    w = BitWriter()
    w.write(1, 1)
    w.write(3, 2)
    w.align()
    bad_btype = w.bytes()
    write_file("bad_btype.bin", bad_btype)

    # (b) a dynamic-Huffman stream cut in half.
    full = raw_deflate(BLOB, 9)
    assert (full[0] >> 1) & 3 == 2
    truncated = full[:len(full) * 6 // 10]
    try:
        zlib.decompress(truncated, -15)
        raise AssertionError("truncated fixture decoded successfully")
    except zlib.error:
        pass
    write_file("truncated_dynamic.bin", truncated)


# ----------------------------------------------------------------------
# Reference checksums
# ----------------------------------------------------------------------

CHECK_FILES = [
    "raw.bin", "raw.expected", "zlib.bin", "zlib.expected",
    "stored.bin", "stored.expected", "fixed.bin", "empty_raw.bin",
    "sample.jar", "descriptor.jar", "manifest_edge.mf", "empty.jar",
]


def build_checksums():
    lines = ["# file crc32 adler32"]
    for name in CHECK_FILES:
        data = open(os.path.join(FIX, name), "rb").read()
        lines.append("%s %08x %08x" % (
            name, zlib.crc32(data) & 0xFFFFFFFF, zlib.adler32(data) & 0xFFFFFFFF))
    write_file("checksums.txt", ("\n".join(lines) + "\n").encode("ascii"))
    return lines[1:]


# ----------------------------------------------------------------------
# main
# ----------------------------------------------------------------------

def main():
    os.makedirs(FIX, exist_ok=True)
    os.makedirs(EXP, exist_ok=True)
    write_file("manifest_edge.mf", MANIFEST_EDGE)

    build_sample_jar()
    build_fake_eocd_jar()
    build_descriptor_jar()
    build_local_header_differs_jar()
    build_unsupported_jar()
    build_bogus_jars()
    index = build_jar_index()
    build_inflate_fixtures()
    build_adversarial_fixtures()
    checksums = build_checksums()

    # Self-checks: the fixtures must mean what the C tests assume.
    with zipfile.ZipFile(os.path.join(FIX, "sample.jar")) as zf:
        names = zf.namelist()
        assert names == ["readme.txt", "data/large.txt", "blob.bin", "dir/",
                         "META-INF/MANIFEST.MF"], names
        assert zf.read("readme.txt") == READ_ME
        assert zf.read("blob.bin") == BLOB
        assert zf.read("META-INF/MANIFEST.MF") == MANIFEST
        assert zf.comment == JAR_COMMENT
    assert zlib.decompress(open(os.path.join(FIX, "zlib.bin"), "rb").read()) == INFLATE_SRC
    assert zlib.decompress(open(os.path.join(FIX, "raw.bin"), "rb").read(), -15) == INFLATE_SRC

    print("fixtures written to %s" % FIX)
    print("  jar entries (non-directory): %d" % len(index))
    for line in index:
        print("    %s" % line)
    print("  blob.bin uncompressed size : %d bytes" % len(BLOB))
    for line in checksums:
        print("  checksum %s" % line)
    print("  inflate source size        : %d bytes" % len(INFLATE_SRC))
    return 0


if __name__ == "__main__":
    sys.exit(main())
