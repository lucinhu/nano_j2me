#!/usr/bin/env python3
"""
gen_fixtures.py - build the binary fixtures used by tests/test_zip.c.

Everything is derived deterministically (fixed seeds, fixed timestamps) so the
fixtures can be regenerated byte for byte.  The script only needs the standard
library: zipfile for the JAR containers, zlib for the DEFLATE/zlib streams and
for the reference CRC-32 / Adler-32 values the C tests are checked against.

Layout written below tests/fixtures/:

  sample.jar            stored + deflated + ~100 KB blob + a directory entry
                        + META-INF/MANIFEST.MF, with an archive comment that
                        deliberately contains a fake EOCD signature
  descriptor.jar        sample.jar with bit 3 set and the local sizes zeroed
                        (sizes exist only in the central directory)
  local_header_differs.jar
                        local header name/extra length disagree with the CD
  unsupported.jar       sample.jar with one entry switched to method 99
  bogus_cd_offset.jar   EOCD central-directory offset outside the file
  bogus_cd_sig.jar      EOCD offset in range but pointing at the wrong record
  bogus_count.jar       EOCD claims more entries than the directory holds
  lying_sizes.jar       central directory size disagrees with the payload
  overrun_cd.jar        central directory points past the end of the image
  empty.jar             a valid archive with no entries
  truncated.jar         the first 10 bytes of sample.jar
  raw.bin/.expected     raw DEFLATE (dynamic Huffman)
  fixed.bin/.expected   raw DEFLATE forced to fixed Huffman
  stored.bin/.expected  hand-built stream of stored (uncompressed) blocks
  zlib.bin/.expected    zlib-wrapped DEFLATE
  empty_raw.bin         a valid DEFLATE stream that produces zero bytes
  bad_distance.bin      fixed-Huffman block with a distance before the output
  bad_btype.bin         DEFLATE block with the reserved type 3
  truncated_dynamic.bin dynamic-Huffman stream cut in half
  manifest_edge.mf      manifest parser edge cases (case, continuation, ...)
  expected/             the plain contents of every JAR entry
  jar_index.txt         name/method/sizes/crc32/expected-file of every entry
  checksums.txt         reference CRC-32 and Adler-32 of the fixture files
"""

import os
import random
import struct
import sys
import zipfile
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
FIX = os.path.join(HERE, "fixtures")
EXP = os.path.join(FIX, "expected")

CRLF = b"\r\n"


# ----------------------------------------------------------------------
# Fixture payloads (deterministic)
# ----------------------------------------------------------------------

READ_ME = (
    b"nano_j2me sample archive" + CRLF +
    b"this entry is stored without compression" + CRLF +
    b"so the reader takes the plain-copy path" + CRLF
) * 4

LARGE_TXT = b"".join(
    b"line %04d of the nano_j2me fixture: repeated text compresses well.\r\n" % i
    for i in range(1200)
)


def build_blob():
    """~100 KB of pseudo-random but still compressible bytes."""
    rnd = random.Random(0xC0FFEE)
    alphabet = bytes(range(32, 127))
    out = bytearray()
    while len(out) < 100000:
        kind = rnd.randrange(4)
        if kind == 0:
            out += bytes([rnd.randrange(256)]) * rnd.randrange(4, 48)
        elif kind == 1:
            out += bytes(rnd.choice(alphabet) for _ in range(rnd.randrange(8, 64)))
        elif kind == 2:
            out += bytes(rnd.getrandbits(8) for _ in range(rnd.randrange(8, 24)))
        else:
            out += b"nano_j2me-blob-marker" + bytes([rnd.randrange(256)])
    return bytes(out)


BLOB = build_blob()

MANIFEST = (
    b"Manifest-Version: 1.0" + CRLF +
    b"Created-By: gen_fixtures.py" + CRLF +
    b"MIDlet-Name: Nano Sample" + CRLF +
    b"MIDlet-Version: 1.0.0" + CRLF +
    b"MIDlet-1: NanoSample, /icon.png, nanosample.Midlet" + CRLF +
    b"MicroEdition-Profile: MIDP-2.0" + CRLF +
    CRLF +
    b"Name: nanosample/Midlet.class" + CRLF +
    b"MIDlet-Name: This One Is Not In The Main Section" + CRLF +
    b"SHA-256-Digest: 0000000000000000000000000000000000000000" + CRLF +
    CRLF
)

MANIFEST_EDGE = (
    b"Manifest-Version: 1.0" + CRLF +
    b"MIDlet-Name: Edge Mid" + CRLF +
    b"Midlet-Version: 2.0" + CRLF +
    # A continuation line starts with a single space, which is dropped; the
    # rest is appended verbatim, so the trailing space of the first line is
    # what separates the words of the joined value.
    b"Long-Attr: first part " + CRLF +
    b" second part" + CRLF +
    b" third part" + CRLF +
    # ...and with no trailing space the pieces are joined without one.
    b"Tight-Attr: alpha" + CRLF +
    b" beta" + CRLF +
    b"Empty-Attr:" + CRLF +
    b"Trail-Spaces:   spaced value  " + CRLF +
    CRLF +
    b"Attr-Only-In-Entry: nope" + CRLF
)

# Source for the inflate fixtures: long runs (overlapping matches with
# distance 1), repeated phrases, and all 256 byte values.
INFLATE_SRC = (
    b"A" * 4096 +
    b"BCDEFGHIJ" * 600 +
    bytes(range(256)) * 32 +
    b"tail" +
    b"Z" * 1000 +
    bytes(range(255, -1, -1)) * 8
)


# ----------------------------------------------------------------------
# Small helpers
# ----------------------------------------------------------------------

def write_file(rel, data):
    path = os.path.join(FIX, rel)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "wb") as fh:
        fh.write(data)
    return path


def u16(blob, off):
    return struct.unpack_from("<H", blob, off)[0]


def u32(blob, off):
    return struct.unpack_from("<I", blob, off)[0]


def p16(blob, off, value):
    struct.pack_into("<H", blob, off, value)


def p32(blob, off, value):
    struct.pack_into("<I", blob, off, value)


def find_eocd(blob):
    """Locate the real EOCD the same way the C reader must."""
    for off in range(len(blob) - 22, max(-1, len(blob) - 22 - 65535) - 1, -1):
        if blob[off:off + 4] == b"PK\x05\x06":
            if off + 22 + u16(blob, off + 20) == len(blob):
                return off
    raise AssertionError("no EOCD in fixture")


def central_directory(blob):
    """Return the parsed central directory records of a ZIP image."""
    eocd = find_eocd(blob)
    off = u32(blob, eocd + 16)
    count = u16(blob, eocd + 10)
    out = []
    for _ in range(count):
        assert blob[off:off + 4] == b"PK\x01\x02", "bad central directory record"
        nlen = u16(blob, off + 28)
        elen = u16(blob, off + 30)
        clen = u16(blob, off + 32)
        out.append({
            "off": off,
            "name": blob[off + 46:off + 46 + nlen].decode("utf-8", "replace"),
            "flags": u16(blob, off + 8),
            "method": u16(blob, off + 10),
            "comp": u32(blob, off + 20),
            "uncomp": u32(blob, off + 24),
            "local": u32(blob, off + 42),
            "nlen": nlen,
        })
        off += 46 + nlen + elen + clen
    return eocd, out


def raw_deflate(data, level=9, strategy=zlib.Z_DEFAULT_STRATEGY):
    co = zlib.compressobj(level, zlib.DEFLATED, -15, 9, strategy)
    return co.compress(data) + co.flush()


def flat_name(name):
    return name.replace("/", "__")


# ----------------------------------------------------------------------
# Bit-level builder for hand-crafted DEFLATE streams
# ----------------------------------------------------------------------

class BitWriter:
    """LSB-first bit packer, as DEFLATE stores everything but Huffman codes."""

    def __init__(self):
        self.bits = []

    def write(self, value, nbits):
        for i in range(nbits):
            self.bits.append((value >> i) & 1)

    def write_code(self, code, nbits):
        """Huffman codes travel most-significant bit first."""
        for i in range(nbits - 1, -1, -1):
            self.bits.append((code >> i) & 1)

    def align(self):
        while len(self.bits) % 8:
            self.bits.append(0)

    def bytes(self):
        out = bytearray()
        for i in range(0, len(self.bits), 8):
            byte = 0
            for j, bit in enumerate(self.bits[i:i + 8]):
                byte |= bit << j
            out.append(byte)
        return bytes(out)


# ----------------------------------------------------------------------
# JAR fixtures
# ----------------------------------------------------------------------

JAR_COMMENT = b"nano_j2me fixture archive comment (the reader must skip it)"

# A comment that tries to impersonate the end-of-central-directory record: a
# backwards scan that only looks for the signature would stop here and parse
# garbage, so the reader must also check the comment length.
FAKE_EOCD_COMMENT = (
    b"fake: PK\x05\x06" + b"\x00" * 16 + b"\xff\xff" + b"still the comment"
)


def build_sample_jar():
    path = os.path.join(FIX, "sample.jar")
    with zipfile.ZipFile(path, "w", zipfile.ZIP_DEFLATED) as zf:
        info = zipfile.ZipInfo("readme.txt", date_time=(2024, 1, 2, 3, 4, 6))
        info.compress_type = zipfile.ZIP_STORED
        info.external_attr = 0o100644 << 16
        zf.writestr(info, READ_ME)

        info = zipfile.ZipInfo("data/large.txt", date_time=(2024, 1, 2, 3, 4, 6))
        info.compress_type = zipfile.ZIP_DEFLATED
        info.external_attr = 0o100644 << 16
        zf.writestr(info, LARGE_TXT)

        info = zipfile.ZipInfo("blob.bin", date_time=(2024, 1, 2, 3, 4, 6))
        info.compress_type = zipfile.ZIP_DEFLATED
        info.external_attr = 0o100644 << 16
        zf.writestr(info, BLOB)

        info = zipfile.ZipInfo("dir/", date_time=(2024, 1, 2, 3, 4, 6))
        info.compress_type = zipfile.ZIP_STORED
        info.external_attr = (0o40755 << 16) | 0x10   # directory bit
        zf.writestr(info, b"")

        info = zipfile.ZipInfo("META-INF/MANIFEST.MF", date_time=(2024, 1, 2, 3, 4, 6))
        info.compress_type = zipfile.ZIP_DEFLATED
        info.external_attr = 0o100644 << 16
        zf.writestr(info, MANIFEST)

        zf.comment = JAR_COMMENT
    return path


def build_descriptor_jar():
    """Bit 3 set and the local sizes zeroed: only the central directory knows."""
    blob = bytearray(open(os.path.join(FIX, "sample.jar"), "rb").read())
    _eocd, entries = central_directory(blob)
    for e in entries:
        if e["name"] != "data/large.txt":
            continue
        p16(blob, e["off"] + 8, e["flags"] | 0x0008)          # CD: data descriptor
        p16(blob, e["local"] + 6, u16(blob, e["local"] + 6) | 0x0008)
        p32(blob, e["local"] + 14, 0)                          # crc32
        p32(blob, e["local"] + 18, 0)                          # comp size
        p32(blob, e["local"] + 22, 0)                          # uncomp size
    return write_file("descriptor.jar", bytes(blob))


def build_unsupported_jar():
    """One entry switched to an unsupported compression method."""
    blob = bytearray(open(os.path.join(FIX, "sample.jar"), "rb").read())
    _eocd, entries = central_directory(blob)
    for e in entries:
        if e["name"] != "readme.txt":
            continue
        p16(blob, e["off"] + 10, 99)                           # CD method
        p16(blob, e["local"] + 8, 99)                          # local method
    return write_file("unsupported.jar", bytes(blob))


def build_fake_eocd_jar():
    """Re-comment sample.jar with bytes that impersonate an EOCD record.

    CPython's own zipfile cannot read this image (it takes the *last*
    signature it finds), which is exactly why it is a separate fixture: only
    the bounds/comment-length checking reader may accept it.
    """
    blob = bytearray(open(os.path.join(FIX, "sample.jar"), "rb").read())
    eocd = find_eocd(blob)
    out = bytearray(blob[:eocd + 22])
    p16(out, eocd + 20, len(FAKE_EOCD_COMMENT))
    out += FAKE_EOCD_COMMENT
    assert find_eocd(out) == eocd, "fake EOCD comment confused the parser"
    return write_file("fake_eocd_comment.jar", bytes(out))


def build_local_header_differs_jar():
    """Local header name/extra lengths deliberately disagree with the CD.

    A reader that took the data offset from the central directory (or trusted
    the CD name length) would start reading 12 bytes too early here, so this
    fixture is what proves the local header is really consulted.
    """
    blob = bytearray(open(os.path.join(FIX, "sample.jar"), "rb").read())
    eocd, entries = central_directory(blob)
    target = [e for e in entries if e["name"] == "data/large.txt"][0]
    lo = target["local"]
    nlen = u16(blob, lo + 26)
    assert u16(blob, lo + 28) == 0, "expected an empty local extra field"

    # Same length, different spelling: only the length may be used.
    blob[lo + 30:lo + 30 + nlen] = b"data/LARGE.txt"
    extra = b"NJX\x01" + b"\x00" * 8
    blob[lo + 30 + nlen:lo + 30 + nlen] = extra
    p16(blob, lo + 28, len(extra))
    assert u16(blob, lo + 26) == nlen

    shift = len(extra)
    eocd += shift
    for e in entries:
        if e["local"] > lo:
            p32(blob, e["off"] + shift + 42, e["local"] + shift)
    p32(blob, eocd + 16, u32(blob, eocd + 16) + shift)

    out = bytes(blob)
    _e, check = central_directory(out)          # still a parseable archive
    moved = [e for e in check if e["name"] == "data/large.txt"][0]
    assert u16(out, moved["local"] + 28) == shift
    return write_file("local_header_differs.jar", out)


def build_bogus_jars():
    blob = bytearray(open(os.path.join(FIX, "sample.jar"), "rb").read())
    eocd = find_eocd(blob)

    out_of_range = bytearray(blob)
    p32(out_of_range, eocd + 16, len(blob) + 4096)             # CD past the end
    write_file("bogus_cd_offset.jar", bytes(out_of_range))

    wrong_target = bytearray(blob)
    p32(wrong_target, eocd + 16, 0)                            # points at a LFH
    write_file("bogus_cd_sig.jar", bytes(wrong_target))

    too_many = bytearray(blob)
    p16(too_many, eocd + 10, u16(too_many, eocd + 10) + 3)
    write_file("bogus_count.jar", bytes(too_many))

    # These two open fine: only extraction can notice that the directory lies.
    lying = bytearray(blob)
    for e in central_directory(lying)[1]:
        if e["name"] == "readme.txt":
            p32(lying, e["off"] + 24, e["uncomp"] + 100)    # stored: sizes differ
    write_file("lying_sizes.jar", bytes(lying))

    overrun = bytearray(blob)
    for e in central_directory(overrun)[1]:
        if e["name"] == "blob.bin":
            p32(overrun, e["off"] + 20, 0xFFFF0000)         # payload past the end
    write_file("overrun_cd.jar", bytes(overrun))

    write_file("truncated.jar", bytes(blob[:10]))

    empty = os.path.join(FIX, "empty.jar")
    with zipfile.ZipFile(empty, "w"):
        pass
    return empty


def build_jar_index():
    """Describe every non-directory entry the C test must see."""
    blob = open(os.path.join(FIX, "sample.jar"), "rb").read()
    _eocd, entries = central_directory(blob)
    lines = ["# name method comp_size uncomp_size crc32 expected_file"]
    content = {
        "readme.txt": READ_ME,
        "data/large.txt": LARGE_TXT,
        "blob.bin": BLOB,
        "META-INF/MANIFEST.MF": MANIFEST,
    }
    seen = set()
    for e in entries:
        if e["name"].endswith("/"):
            continue
        data = content[e["name"]]
        write_file(os.path.join("expected", flat_name(e["name"])), data)
        lines.append("%s %d %d %d %08x expected/%s" % (
            e["name"], e["method"], e["comp"], e["uncomp"],
            zlib.crc32(data) & 0xFFFFFFFF, flat_name(e["name"])))
        seen.add(e["name"])
    assert seen == set(content), (seen, set(content))
    write_file("jar_index.txt", ("\n".join(lines) + "\n").encode("ascii"))
    return lines[1:]


